#!/usr/bin/env python3
"""Generate isolated Nat64 comparator-dispatch benchmarks for maps and sets."""
import argparse
import json
import os
from pathlib import Path

FAMILIES = ('mutable-map', 'pure-map', 'mutable-set', 'pure-set')
STRATEGIES = ('alias', 'generic', 'custom', 'reversed', 'effectful')
OPERATIONS = ('build', 'lookup-hit', 'insert-new', 'delete-present')


def source(family, variant, size, operation):
    pure, is_map = family.startswith('pure'), family.endswith('map')
    static = variant == 'static'
    module = ('mo:core/' if variant == 'core' else 'mo:fast/') + ('pure/' if pure else '') + ('Map' if is_map else 'Set')
    kind, types = ('Map', 'Nat64, Nat') if is_map else ('Set', 'Nat64')
    tree_type = f'C.{kind}<{types}>'
    count = 32 if size >= 32 else 1
    cmp = 'alias.compare' if variant == 'alias' else 'custom' if variant in ('custom', 'reversed', 'effectful') else 'Nat64.compare'
    compare_body = {'custom': 'if (reverseOrder) Nat64.compare(b, a) else Nat64.compare(a, b)',
                    'reversed': 'Nat64.compare(b, a)',
                    'effectful': 'calls += 1; Nat64.compare(a, b)'}.get(variant, 'Nat64.compare(a, b)')

    def call(function, tree='tree', key='key', value='ordinal(key)'):
        args = [tree] + ([] if static else [cmp]) + [key]
        if is_map and function == 'add':
            args.append(value)
        return f'C.{function}{"Nat64" if static else ""}({", ".join(args)})'

    add = call('add')
    build_action = f'tree := {add}' if pure else add
    get = call('get' if is_map else 'contains', key='probes[i]')
    if variant == 'generic':
        get = f'genericLookup(tree, {cmp}, probes[i]{", ordinal(probes[i])" if is_map else ""})'
    elif is_map:
        get = f'({get} == ?ordinal(probes[i]))'
    prelude = f'''let keys = shuffled({size});
    let seed = build(keys);
    var tree = seed;
    let probes = Prim.Array_tabulate<Nat64>({count}, func(i) {{ {f'keyOf({size} + i)' if operation in ('lookup-miss', 'insert-new') else 'keys[i]'} }});
    let flags = Prim.Array_init<Bool>({count}, false);'''
    if operation == 'build':
        prelude = f'let keys = shuffled({size}); var tree = C.empty<{types}>();'
        action = 'tree := build(keys);'
    elif operation.startswith('lookup'):
        action = f'var i = 0; while (i < {count}) {{ flags[i] := {get}; i += 1 }};'
    else:
        invoke = call('add' if operation == 'insert-new' else 'remove', key='probes[i]', value='ordinal(probes[i])')
        action = f'var i = 0; while (i < {count}) {{ {"tree := " if pure else ""}{invoke}; i += 1 }};'
    checks = f'verify(tree, {size}, {count if operation == "insert-new" else 0}, {"?probes" if operation == "delete-present" else "null"});'
    if operation.startswith('lookup'):
        checks += f' for (flag in flags.vals()) {{ assert flag == {str(operation == "lookup-hit").lower()} }};'
    if pure and operation in ('insert-new', 'delete-present'):
        checks += f' verify(seed, {size}, 0, null);'
    if variant == 'effectful':
        checks += f' assert measuredCalls {"== 0" if size == 0 else ">= " + str(count)};'
    iterator = 'C.entries(tree)' if is_map else 'C.values(tree)'
    element = '(key, value)' if is_map else 'key'
    map_check = 'assert value == n;' if is_map else ''
    reversed_order = str(variant == 'reversed').lower()
    generic_signature = 'C.Map<K, Nat>' if is_map else 'C.Set<K>'
    generic_call = 'C.get(tree, compare, key) == ?expected' if is_map else 'C.contains(tree, compare, key)'
    return f'''// Generated by benchmarks/comparator-dispatch/generate.py. Do not edit.
import Test "mo:test";
import Prim "mo:prim";
import Nat64 "mo:core/Nat64";
import C "{module}";

persistent actor {{
  transient var calls : Nat = 0;
  transient var reverseOrder : Bool = false;
  transient let alias = {{compare = Nat64.compare}};
  func custom(a : Nat64, b : Nat64) : {{#less; #equal; #greater}} {{ {compare_body} }};
  func genericLookup<K>(tree : {generic_signature}, compare : (K, K) -> {{#less; #equal; #greater}}, key : K{", expected : Nat" if is_map else ""}) : Bool {{
    {generic_call}
  }};
  // Keys cross the signed i64 boundary, exercising full-width unsigned comparisons.
  func keyOf(n : Nat) : Nat64 {{ Nat64.fromNat(n / 2) + (if (n % 2 == 0) 0 else 0x8000_0000_0000_0000) }};
  func ordinal(key : Nat64) : Nat {{ if (key < 0x8000_0000_0000_0000) Nat64.toNat(key) * 2 else Nat64.toNat(key - 0x8000_0000_0000_0000) * 2 + 1 }};
  func shuffled(size : Nat) : [var Nat64] {{
    let keys = Prim.Array_tabulateVar<Nat64>(size, keyOf);
    var i = size;
    var random : Nat32 = 0x617368;
    while (i > 1) {{
      random := random *% 1664525 +% 1013904223;
      let j = Prim.nat32ToNat(random) % i;
      i -= 1;
      let saved = keys[i]; keys[i] := keys[j]; keys[j] := saved
    }};
    keys
  }};
  func build(keys : [var Nat64]) : {tree_type} {{
    var tree = C.empty<{types}>();
    for (key in keys.vals()) {{ {build_action} }};
    tree
  }};
  func verify(tree : {tree_type}, originalSize : Nat, added : Nat, removed : ?[Nat64]) {{
    let expected = Prim.Array_init<Bool>(originalSize + added, true);
    let removedCount = switch (removed) {{ case null 0; case (?keys) {{
      for (key in keys.vals()) {{ expected[ordinal(key)] := false }}; keys.size()
    }} }};
    assert C.size(tree) == originalSize + added - removedCount;
    var seen = 0;
    var previous : ?Nat64 = null;
    for ({element} in {iterator}) {{
      let n = ordinal(key);
      assert n < expected.size() and expected[n]; expected[n] := false;
      {map_check}
      switch (previous) {{ case null {{}}; case (?last) {{ assert (if ({reversed_order}) last > key else last < key) }} }};
      previous := ?key; seen += 1
    }};
    assert seen == C.size(tree);
    for (missing in expected.vals()) {{ assert not missing }}
  }};
  public func bench() : async Test.Metrics {{
    {prelude}
    calls := 0;
    let metrics = Test.test(func() {{ {action} }});
    let measuredCalls = calls;
    {checks}
    metrics
  }}
}}
'''


def matrix(phase):
    for family in FAMILIES:
        for size in (1000, 10000, 100000):
            for variant in (('direct',) if phase == 'baseline' else ('core', 'direct', 'static')):
                for operation in OPERATIONS:
                    yield family, variant, size, operation
        for variant in STRATEGIES:
            yield family, variant, 10000, 'lookup-hit'
        for size in (0, 1):
            for variant in (('direct',) if phase == 'baseline' else ('direct', 'static')):
                for operation in ('lookup-miss', 'insert-new'):
                    yield family, variant, size, operation


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', required=True, type=Path)
    parser.add_argument('--deps', required=True, type=Path)
    parser.add_argument('--phase', choices=('baseline', 'candidate'), default='candidate')
    parser.add_argument('--dist', type=Path)
    parser.add_argument('--fast', type=Path)
    parser.add_argument('--select', help='Comma-separated complete case names, or exploration for a compact lookup/overhead smoke matrix')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    out, deps = args.out.resolve(), args.deps.resolve()
    fast, dist = (args.fast or root / 'packages/fast/src').resolve(), (args.dist or root / 'dist').resolve()
    if out.exists():
        parser.error('output already exists; choose a fresh directory')
    cases = []
    for family, variant, size, operation in matrix(args.phase):
        name = f'{family.replace("-", "_")}_{variant}_{size}_{operation.replace("-", "_")}'
        if args.select:
            if args.select == 'exploration':
                if not ((size == 10000 and operation == 'lookup-hit') or (variant == 'direct' and size in (0, 1) and operation == 'insert-new')):
                    continue
            elif name not in args.select.split(','):
                continue
        directory = out / name
        directory.mkdir(parents=True)
        (directory / 'main.mo').write_text(source(family, variant, size, operation))
        config = {'mo': {'core': os.path.relpath(deps / '.mops/core@2.5.0/src', directory),
                         'fast': os.path.relpath(fast, directory)},
                  'canisters': [{'name': name, 'src': 'main.mo', 'mocArgs': []}]}
        if variant != 'core':
            config['canisters'][0]['mocArgs'] = ['--plugin', os.path.relpath(dist / family, directory)]
        (directory / 'ash.json').write_text(json.dumps(config, indent=2) + '\n')
        cases.append({'family': family, 'variant': variant, 'size': size, 'operation': operation,
                      'operations_per_sample': 1 if operation == 'build' or size < 32 else 32,
                      'key_type': 'Nat64', 'input_order': 'deterministic Fisher-Yates',
                      'config': f'{name}/ash.json', 'metrics_key': f'{name}::bench'})
    if not cases:
        parser.error('no cases selected')
    (out / 'cases.json').write_text(json.dumps(cases, indent=2) + '\n')
    print(f'Generated {len(cases)} isolated cases at {out}')


if __name__ == '__main__':
    main()
