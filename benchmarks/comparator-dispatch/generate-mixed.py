#!/usr/bin/env python3
"""Generate small lookup probes that materialize known and unknown comparators together."""
import argparse
import json
import os
from pathlib import Path
import generate

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--out', required=True, type=Path)
parser.add_argument('--deps', required=True, type=Path)
args = parser.parse_args()
root = Path(__file__).resolve().parents[2]
out, deps = args.out.resolve(), args.deps.resolve()
if out.exists():
    parser.error('output already exists; choose a fresh directory')
def replace_once(source, old, new):
    if source.count(old) != 1:
        raise ValueError(f'expected one source fragment: {old!r}')
    return source.replace(old, new)


cases = []
for family in generate.FAMILIES:
    for known in (False, True):
        variant = 'mixed-known' if known else 'mixed-unknown'
        name = f'{family}_{variant}_10000_lookup_hit'.replace('-', '_')
        source = generate.source(family, 'custom', 10000, 'lookup-hit')
        old = f'C.{"get" if family.endswith("map") else "contains"}(tree, custom, probes[i])'
        if source.count(old) != 1:
            raise ValueError('expected exactly one measured lookup to replace')
        source = replace_once(source, old, old.replace('custom', 'selected'))
        source = replace_once(source, '  transient var reverseOrder : Bool = false;',
            f'  transient var chooseKnown : Bool = {str(known).lower()};\n  transient var reverseOrder : Bool = false;')
        # Selection is outside the measured closure. Both function identities
        # remain reachable in the canister regardless of the selected branch.
        source = replace_once(source, '    calls := 0;',
            '    let selected = if (chooseKnown) Nat64.compare else custom;\n    calls := 0;')
        source = replace_once(source, '  public func bench() : async Test.Metrics {',
            '  // Ash skips this argument-taking configuration method. Both choices\n'
            '  // are externally reachable; comparator selection cannot be constant.\n'
            '  public func chooseStandard(standard : Bool) : async () { chooseKnown := standard };\n'
            '  public func bench() : async Test.Metrics {')
        source = replace_once(source, 'Generated by benchmarks/comparator-dispatch/generate.py',
            'Generated by benchmarks/comparator-dispatch/generate-mixed.py')
        directory = out / name
        directory.mkdir(parents=True)
        (directory / 'main.mo').write_text(source)
        config = {'mo': {'core': os.path.relpath(deps / '.mops/core@2.5.0/src', directory),
                         'fast': os.path.relpath(root / 'packages/fast/src', directory)},
                  'canisters': [{'name': name, 'src': 'main.mo', 'mocArgs':
                    ['--plugin', os.path.relpath(root / 'dist' / family, directory)]}]}
        (directory / 'ash.json').write_text(json.dumps(config, indent=2) + '\n')
        cases.append({'family': family, 'variant': variant, 'size': 10000, 'operation': 'lookup-hit',
            'operations_per_sample': 32, 'key_type': 'Nat64', 'input_order': 'deterministic Fisher-Yates',
            'config': f'{name}/ash.json', 'metrics_key': f'{name}::bench'})
(out / 'cases.json').write_text(json.dumps(cases, indent=2) + '\n')
print(f'Generated {len(cases)} isolated mixed-identity probes: {out}')
