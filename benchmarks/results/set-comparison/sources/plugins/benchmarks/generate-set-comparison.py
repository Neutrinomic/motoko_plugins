#!/usr/bin/env python3
"""Generate isolated Ash/PocketIC comparisons of Core and fast ordered sets."""
import argparse
import json
import os
from pathlib import Path


OPERATIONS = (
    'build-shuffled', 'contains-hit', 'contains-miss', 'insert-new',
    'insert-existing', 'delete-present', 'delete-missing', 'values',
    'union', 'intersection',
)
POINTS = set(OPERATIONS[1:7])
STATIC = POINTS | {'build-shuffled'}


def generate_method(family, variant, size, operation):
    pure = family == 'pure'
    scalar = variant == 'native'

    def call(function, tree, key):
        args = f'{tree}, {key}' if scalar else f'{tree}, compare, {key}'
        return f'Set.{function}{"Nat" if scalar else ""}({args})'

    add = call('add', 'tree', 'keys[i] + offset')
    build = f'tree := {add}' if pure else add
    prelude = f'''let keys = shuffled({size});
    let seed = build(keys, 0);
    assert Set.size(seed) == {size};
    var tree = seed;'''
    validation = ''
    if operation == 'build-shuffled':
        prelude = f'let keys = shuffled({size});\n    var tree = Set.empty<Nat>();'
        expression = 'tree := build(keys, 0);'
        validation = f'verifyRange(tree, 0, {size});'
    elif operation in POINTS:
        miss = operation in {'contains-miss', 'insert-new', 'delete-missing'}
        key = f'{size} + probes[i]' if miss else 'probes[i]'
        function = operation.split('-')[0]
        invoke = call(function, 'tree', key)
        if pure and function in {'insert', 'delete'}:
            action = f'let (next, changed) = {invoke}; tree := next; flags[i] := changed'
        else:
            action = f'flags[i] := {invoke}'
        prelude += f'''
    let probes = Array.tabulate<Nat>(32, func(i) {{ keys[i] }});
    let flags = Prim.Array_init<Bool>(32, false);'''
        expression = f'var i = 0; while (i < 32) {{ {action}; i += 1 }};'
        expected = operation in {'contains-hit', 'insert-new', 'delete-present'}
        length = size + 32 if operation == 'insert-new' else size - 32 if operation == 'delete-present' else size
        validation = f'''assert Set.size(tree) == {length};
    var i = 0;
    while (i < 32) {{
      assert flags[i] == {str(expected).lower()};
      let key = {key};
      assert Set.contains(tree, compare, key) == {str(operation not in {'contains-miss', 'delete-present', 'delete-missing'}).lower()};
      i += 1
    }};
    // A full ordered scan checks unrelated elements as well as measured probes.
    var ordinal = 0;
    for (key in Set.values(tree)) {{
      if (operation == "delete-present") {{
        while (removed(ordinal, probes)) {{ ordinal += 1 }};
        assert key == ordinal;
      }} else if (key < {size}) {{ assert key == ordinal }}
      else {{ assert operation == "insert-new" and removed(key - {size}, probes) }};
      ordinal += 1
    }};
    assert ordinal == {size + 32 if operation == 'insert-new' else size};'''
        # Delete probes never include the highest key with the default matrix;
        # still handle a trailing deleted key for arbitrary supported sizes.
        if operation == 'delete-present':
            validation = validation.replace(f'assert ordinal == {size};',
                f'while (removed(ordinal, probes)) {{ ordinal += 1 }};\n    assert ordinal == {size};')
        if pure:
            validation += f'\n    verifyRange(seed, 0, {size});'
    elif operation == 'values':
        prelude += '\n    var length = 0; var checksum = 0;'
        expression = '''for (key in Set.values(tree)) {
        checksum := (checksum + key) % 1_000_003; length += 1
      };'''
        validation = f'assert length == {size}; assert checksum == {(size * (size - 1) // 2) % 1_000_003}; verifyRange(tree, 0, {size});'
    else:
        half = size // 2
        prelude += f'\n    let other = build(keys, {half});'
        expression = f'tree := Set.{operation}(seed, other, compare);'
        validation = (f'verifyRange(tree, 0, {size + half});' if operation == 'union'
                      else f'verifyRange(tree, {half}, {size});')
        validation += f'\n    verifyRange(seed, 0, {size}); verifyRange(other, {half}, {size + half});'

    return f'''  public func bench_{operation.replace('-', '_')}() : async Test.Metrics {{
    let operation = "{operation}";
    {prelude}
    let metrics = Test.test(func() {{
      {expression}
    }});
    {validation}
    metrics
  }};''', build


def source(family, variant, size, operations):
    module = ('mo:core/' if variant == 'core' else 'mo:fast/') + ('pure/' if family == 'pure' else '') + 'Set'
    methods = [generate_method(family, variant, size, operation)[0] for operation in operations]
    build = generate_method(family, variant, size, operations[0])[1]
    return f'''// Generated by benchmarks/generate-set-comparison.py. Do not edit.
import Test "mo:test";
import Prim "mo:prim";
import Array "mo:core/Array";
import Set "{module}";

persistent actor {{
  func compare(a : Nat, b : Nat) : {{#less; #equal; #greater}} {{
    if (a < b) #less else if (a == b) #equal else #greater
  }};
  // Fisher-Yates with a fixed 32-bit LCG: identical order for every implementation.
  func shuffled(size : Nat) : [var Nat] {{
    let keys = Prim.Array_init<Nat>(size, 0);
    var i = 0;
    while (i < size) {{ keys[i] := i; i += 1 }};
    var random : Nat32 = 0x617368;
    while (i > 1) {{
      random := random *% 1664525 +% 1013904223;
      let j = Prim.nat32ToNat(random) % i;
      i -= 1;
      let saved = keys[i]; keys[i] := keys[j]; keys[j] := saved
    }};
    keys
  }};
  func build(keys : [var Nat], offset : Nat) : Set.Set<Nat> {{
    var tree = Set.empty<Nat>();
    var i = 0;
    while (i < keys.size()) {{ {build}; i += 1 }};
    tree
  }};
  func verifyRange(tree : Set.Set<Nat>, first : Nat, end : Nat) {{
    assert Set.size(tree) == end - first;
    var expected = first;
    for (key in Set.values(tree)) {{ assert key == expected; expected += 1 }};
    assert expected == end
  }};
  func removed(key : Nat, probes : [Nat]) : Bool {{
    for (probe in probes.values()) {{ if (key == probe) return true }};
    false
  }};

{chr(10).join(methods)}
}}
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', required=True, type=Path)
    parser.add_argument('--deps', type=Path, help='Directory containing .mops/core@2.5.0')
    parser.add_argument('--sizes', default='1000,10000,100000')
    parser.add_argument('--families', default='mutable,pure')
    parser.add_argument('--variants', default='core,generic,native')
    parser.add_argument('--operations', default=','.join(OPERATIONS))
    args = parser.parse_args()
    sizes = list(map(int, args.sizes.split(',')))
    families, variants, operations = [getattr(args, item).split(',') for item in ('families', 'variants', 'operations')]
    for label, values, allowed in [('families', families, {'mutable', 'pure'}),
                                    ('variants', variants, {'core', 'generic', 'native'}),
                                    ('operations', operations, set(OPERATIONS))]:
        if len(values) != len(set(values)) or not set(values) <= allowed:
            parser.error(f'invalid {label}: {values}')
    if len(sizes) != len(set(sizes)) or any(size < 1000 or size > 100000 for size in sizes):
        parser.error('sizes must be unique values in 1000..100000')
    root = Path(__file__).resolve().parents[1]
    deps = (args.deps or root / 'packages/fast').resolve()
    out = args.out.resolve()
    out.mkdir(parents=True, exist_ok=True)
    cases = []
    for family in families:
        for size in sizes:
            for variant in variants:
                selected = [op for op in operations if variant != 'native' or op in STATIC]
                if not selected:
                    continue
                for operation in selected:
                    name = f'{family}_{variant}_{size}_{operation.replace("-", "_")}'
                    directory = out / name
                    directory.mkdir(exist_ok=True)
                    (directory / 'main.mo').write_text(source(family, variant, size, [operation]))
                    config = {'mo': {'core': os.path.relpath(deps / '.mops/core@2.5.0/src', directory),
                                     'fast': os.path.relpath(root / 'packages/fast/src', directory)},
                              'canisters': [{'name': name, 'src': 'main.mo', 'mocArgs': []}]}
                    if variant != 'core':
                        config['canisters'][0]['mocArgs'] = ['--plugin', os.path.relpath(root / 'dist' / (family + '-set'), directory)]
                    (directory / 'ash.json').write_text(json.dumps(config, indent=2) + '\n')
                    cases.append({'family': family, 'variant': variant, 'size': size, 'operation': operation,
                                  'operations_per_sample': 32 if operation in POINTS else 1,
                                  'key_type': 'Nat', 'input_order': 'deterministic Fisher-Yates',
                                  'config': f'{name}/ash.json',
                                  'metrics_key': f'{name}::bench_{operation.replace("-", "_")}'})
    (out / 'cases.json').write_text(json.dumps(cases, indent=2) + '\n')
    print(f'Generated {len(cases)} checked cases in {len(set(case["config"] for case in cases))} isolated Ash configurations: {out}')


if __name__ == '__main__':
    main()
