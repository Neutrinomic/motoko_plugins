#!/usr/bin/env python3
"""Generate typed JSON encode/decode workloads with independent host inputs."""
import argparse
import base64
import json
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--out', type=Path, required=True)
args = parser.parse_args()
args.out.mkdir(parents=True, exist_ok=True)


def compact(value):
    return json.dumps(value, ensure_ascii=False, separators=(',', ':'), sort_keys=True)


def literal(text):
    return json.dumps(text, ensure_ascii=False)


row = {'active': True, 'id': '18446744073709551615', 'name': 'Ada ☃', 'tag': None}
rows = [{'active': i % 2 == 0, 'id': str(i * 17), 'name': 'record ☃',
         'tag': None if i % 3 == 0 else 'tag'} for i in range(1024)]
blob = bytes((i * 17 + 11) % 256 for i in range(65536))
workloads = [
    ('record', 'Row', 'row', compact(row)),
    ('records-1024', '[Row]', 'rows', compact(rows)),
    ('blob-64k', 'Blob', 'bytes', compact(base64.b64encode(blob).decode())),
]
cases, methods, configure, validate, outputs = [], [], [], [], []
for name, typ, variable, input_json in workloads:
    outputs.append(f'transient var decoded_{variable} : ?{typ} = null;')
    for direction in ('encode', 'decode'):
        index = len(cases)
        method = f'bench_{index}'
        entry = {'name': f'json-{name}-{direction}', 'index': index, 'family': 'json',
                 'phases': [{'label': direction, 'method': method,
                             'kind': 'json' if direction == 'encode' else 'checked_decode',
                             'require_no_gc': True}]}
        if direction == 'encode':
            entry['expected_json'] = json.loads(input_json)
            operation = f'encoded := require(Prim.to_json({variable}));'
            output_size = 'Prim.encodeUtf8(encoded).size()'
            check = 'Prim.encodeUtf8(encoded)'
        else:
            operation = f'decoded_{variable} := ?require(Prim.from_json<{typ}>(input));'
            output_size = '2'
            check = f'{{ assert decoded_{variable} == ?{variable}; "ok" }}'
        cases.append(entry)
        configure.append(f'case {index} input := {literal(input_json)};')
        validate.append(f'case {index} {check};')
        methods.append(f'''public func {method}() : async Measurement {{
    let allocatedBefore = Prim.rts_total_allocation();
    let reclaimedBefore = Prim.rts_reclaimed();
    let started = Prim.performanceCounter(0);
    {operation}
    let ended = Prim.performanceCounter(0);
    let allocatedAfter = Prim.rts_total_allocation();
    let reclaimedAfter = Prim.rts_reclaimed();
    {{ instructions = ended - started; allocated = allocatedAfter - allocatedBefore;
       reclaimed = reclaimedAfter - reclaimedBefore; outputSize = {output_size} }}
  }};''')

source = f'''// Generated by benchmarks/generate-json.py.
import Prim "mo:⛔";
actor {{
  type Error = {{kind : Text; message : Text; path : Text; offset : Nat64}};
  type Row = {{active : Bool; id : Nat64; name : Text; tag : ?Text}};
  type Measurement = {{instructions : Nat64; allocated : Nat; reclaimed : Nat; outputSize : Nat}};
  func require<T>(r : {{#ok : T; #err : Error}}) : T {{
    switch r {{ case (#ok v) v; case (#err e) Prim.trap(e.message) }}
  }};
  transient let row : Row = {{active = true; id = 18_446_744_073_709_551_615; name = "Ada ☃"; tag = null}};
  transient var rows : [Row] = [];
  transient var bytes : Blob = "";
  transient var input : Text = "";
  transient var encoded : Text = "";
  transient var selected : Nat = 0;
  {chr(10).join(outputs)}
  public func configure(index : Nat) : async () {{
    selected := index;
    rows := Prim.Array_tabulate<Row>(1024, func(i) {{
      {{ active = i % 2 == 0; id = Prim.natToNat64(i * 17); name = "record ☃";
         tag = if (i % 3 == 0) null else ?"tag" }}
    }});
    bytes := Prim.arrayToBlob(Prim.Array_tabulate<Nat8>(65536,
      func(i) {{ Prim.natToNat8((i * 17 + 11) % 256) }}));
    switch index {{ {chr(10).join(configure)} case _ Prim.trap("unknown benchmark") }}
  }};
  public func clear() : async () {{
    encoded := ""; decoded_row := null; decoded_rows := null; decoded_bytes := null;
  }};
  public query func bytesResult() : async Blob {{
    switch selected {{ {chr(10).join(validate)} case _ Prim.trap("unknown benchmark") }}
  }};
  {chr(10).join(methods)}
}}
'''
(args.out / 'main.mo').write_text(source)
(args.out / 'cases.json').write_text(json.dumps({
    'cases': cases,
    'methodology': 'Fresh canister per workload/trial; host-generated JSON and typed inputs prepared outside measurement. Four forced GC increments before each phase. Timed interval includes Result unwrapping and retained output assignment, excludes validation, UTF8 reply conversion and message-end GC. Heap allocations and synchronous reclamation are measured separately.',
    'correctness': 'Encoder output is parsed by host JSON.parse and compared to independent Python-generated expected data. Decoder input is Python-generated JSON; the actor compares every decoded typed value to an independently constructed Motoko input in bytesResult outside the measured interval.',
}, indent=2, ensure_ascii=False) + '\n')
print(args.out / 'main.mo')
