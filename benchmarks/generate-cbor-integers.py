#!/usr/bin/env python3
"""CBOR integer scratch reuse workloads with independent cbor2 wire values."""
import argparse
import json
from pathlib import Path
import cbor2

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--out', type=Path, required=True)
args = parser.parse_args()
args.out.mkdir(parents=True, exist_ok=True)

def blob(data):
    return '"' + ''.join(f'\\{b:02x}' for b in data) + '"'

big = 2**4095 - 1
workloads = [
    ('empty-array', '[Nat]', '[]', []),
    ('nat-zero', 'Nat', '0', 0),
    ('int-negative', 'Int', '-1', -1),
    ('big-positive', 'Nat', str(big), big),
    ('big-negative', 'Int', str(-big-1), -big-1),
    ('nats-1024', '[Nat]', 'Prim.Array_tabulate<Nat>(1024, func(i) { i })', list(range(1024))),
    ('ints-1024', '[Int]', 'Prim.Array_tabulate<Int>(1024, func(i) { i - 512 })', list(range(-512,512))),
    ('big-ints-256', '[Int]', f'Prim.Array_tabulate<Int>(256, func(i) {{ if (i % 2 == 0) {big} else {-big-1} }})', [big if i % 2 == 0 else -big-1 for i in range(256)]),
    ('mixed-scalars-256', '[(Nat, Text, Int, Blob)]', f'Prim.Array_tabulate<(Nat,Text,Int,Blob)>(256, func(i) {{ (if (i % 2 == 0) {big} else i, "é", if (i % 2 == 0) -1 else {-big-1}, "\\00\\ff") }})', [[big if i % 2 == 0 else i, 'é', -1 if i % 2 == 0 else -big-1, b'\x00\xff'] for i in range(256)]),
]
decls, setups, methods, checks, clear, cases = [], [], [], [], [], []
for index, (name, typ, value, expected) in enumerate(workloads):
    decls.extend([f'transient var expected{index} : ?({typ}) = null;', f'transient var decoded{index} : ?({typ}) = null;'])
    setups.append(f'case {index} {{ expected{index} := ?({value} : {typ}); input := {blob(cbor2.dumps(expected, canonical=True))} }};')
    clear.append(f'decoded{index} := null;')
    checks.append(f'case {index} {{ assert decoded{index} == expected{index}; "ok" }};')
    method = f'bench_{index}_plugin'
    cases.append({'name': 'cbor-' + name + '-decode', 'index': index, 'family': 'cbor', 'phases': [{'label': 'plugin', 'method': method, 'kind': 'checked_decode', 'require_no_gc': True}]})
    methods.append(f'''public func {method}() : async Measurement {{
      let allocatedBefore = Prim.rts_total_allocation();
      let reclaimedBefore = Prim.rts_reclaimed();
      let started = Prim.performanceCounter(0);
      decoded{index} := ?require(Prim.from_cbor<{typ}>(input));
      let ended = Prim.performanceCounter(0);
      let allocatedAfter = Prim.rts_total_allocation();
      let reclaimedAfter = Prim.rts_reclaimed();
      {{ instructions = ended - started; allocated = allocatedAfter - allocatedBefore;
         reclaimed = reclaimedAfter - reclaimedBefore; outputSize = 2 }}
    }};''')
decls.extend(['type Error = {kind : Text; message : Text; path : Text; offset : Nat64};', 'transient var failure : ?Error = null;'])
clear.append('failure := null;')
for name, typ, wire, kind, message, path, offset in [
    ('nat-negative-error', 'Nat', b'\x20', 'range', "Integer is outside the requested type's range", '', 1),
    ('late-integer-error', '[Int]', b'\x82' + cbor2.dumps(big) + b'\x1a\x00', 'syntax', 'Unexpected end of CBOR input', '/1', len(cbor2.dumps(big)) + 2),
]:
    index = len(cases)
    setups.append(f'case {index} {{ input := {blob(wire)} }};')
    checks.append(f'case {index} {{ assert failure == ?{{kind = "{kind}"; message = "{message}"; path = "{path}"; offset = {offset} : Nat64}}; "ok" }};')
    method = f'bench_{index}_plugin'
    cases.append({'name': 'cbor-' + name, 'index': index, 'family': 'cbor', 'phases': [{'label': 'plugin', 'method': method, 'kind': 'checked_decode', 'require_no_gc': True}]})
    methods.append(f'''public func {method}() : async Measurement {{
      let allocatedBefore = Prim.rts_total_allocation();
      let reclaimedBefore = Prim.rts_reclaimed();
      let started = Prim.performanceCounter(0);
      failure := switch (Prim.from_cbor<{typ}>(input)) {{ case (#err e) ?e; case (#ok _) Prim.trap("Expected integer error") }};
      let ended = Prim.performanceCounter(0);
      let allocatedAfter = Prim.rts_total_allocation();
      let reclaimedAfter = Prim.rts_reclaimed();
      {{ instructions = ended - started; allocated = allocatedAfter - allocatedBefore;
         reclaimed = reclaimedAfter - reclaimedBefore; outputSize = 2 }}
    }};''')
(args.out / 'main.mo').write_text(f'''// Generated by benchmarks/generate-cbor-integers.py using cbor2 canonical input.
import Prim "mo:⛔";
actor {{
  type Measurement = {{ instructions : Nat64; allocated : Nat; reclaimed : Nat; outputSize : Nat }};
  func require<T,E>(r : {{#ok : T; #err : E}}) : T {{ switch r {{ case (#ok v) v; case (#err _) Prim.trap("CBOR error") }} }};
  transient var selected = 0;
  transient var input : Blob = "";
  {chr(10).join(decls)}
  public func configure(index : Nat) : async () {{ selected := index; switch index {{ {chr(10).join(setups)} case _ Prim.trap("unknown case") }} }};
  public func clear() : async () {{ {' '.join(clear)} }};
  public query func bytesResult() : async Blob {{ switch selected {{ {chr(10).join(checks)} case _ Prim.trap("unknown case") }} }};
  {chr(10).join(methods)}
}}
''')
(args.out / 'cases.json').write_text(json.dumps({'cases': cases, 'correctness': 'Successful CBOR input is independently encoded with cbor2 canonical=True. Outside timing the actor compares each retained typed result with a separately constructed complete Motoko value. Error cases compare the complete expected kind, message, path and offset; valid negative-to-Nat and malformed late uint32 inputs exercise typed errors. The checked_decode phase checks the actor validation reply.', 'methodology': 'Inputs and independent typed expected values are configured outside timing. The timed phase includes typed Result unwrapping and retained result assignment. Every retained result is compared with the full expected value outside timing. Successful CBOR input is independently encoded with cbor2 canonical=True. Error cases assert complete typed error records; one valid negative integer cannot fit Nat and one truncated uint32 follows a correctly encoded bignum. Three fresh-canister trials, no GC permitted.'}, indent=2) + '\n')
