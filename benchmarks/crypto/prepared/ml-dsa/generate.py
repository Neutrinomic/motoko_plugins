#!/usr/bin/env python3
"""Generate prepared ML-DSA measurements from existing official ACVP answers."""
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
CRYPTO = HERE.parents[1]
ROOT = CRYPTO.parents[1]
CORPUS = ROOT / "plugins/ml-dsa/tests/vectors/acvp-ml-dsa-44.json"
PUBLIC_PAYLOAD = 20_576
SECRET_PAYLOAD = 28_800
IDS = [4, 6, 11, 362]


def blob(value):
    return '"' + ''.join('\\' + value[i:i + 2].lower() for i in range(0, len(value), 2)) + '"'


def actor(declarations, configure, measured, result_type, initial, oracle):
    return f'''// Generated by prepared/ml-dsa/generate.py. Do not edit expectations.
import Prim "mo:⛔";
import H "mo:fast/MLDSA";
persistent actor {{
  type Measurement = {{ instructions : Nat64; allocated : Nat; reclaimed : Nat; outputSize : Nat }};
  transient var result : {result_type} = {initial};
  {declarations}
  func unwrap<T>(value : H.Result<T>) : T {{
    switch value {{ case (#ok value) value; case (#err error) Prim.trap(debug_show(error)) }}
  }};
  public func configure() : async () {{ {configure} }};
  public func run() : async Measurement {{
    let allocatedBefore = Prim.rts_total_allocation();
    let reclaimedBefore = Prim.rts_reclaimed();
    let start = Prim.performanceCounter(0);
    {measured}
    let stop = Prim.performanceCounter(0);
    let allocatedAfter = Prim.rts_total_allocation();
    let reclaimedAfter = Prim.rts_reclaimed();
    {{ instructions = stop - start; allocated = allocatedAfter - allocatedBefore;
       reclaimed = reclaimedAfter - reclaimedBefore; outputSize = 0 }}
  }};
  public query func memory() : async {{ heapSize : Nat; memorySize : Nat; totalAllocation : Nat; reclaimed : Nat }} {{
    {{ heapSize = Prim.rts_heap_size(); memorySize = Prim.rts_memory_size();
       totalAllocation = Prim.rts_total_allocation(); reclaimed = Prim.rts_reclaimed() }}
  }};
  public query func bytesResult() : async Blob {{ {oracle} }};
}}
'''


def emit(vector, operation, mode, reuse=1):
    tc = vector['tcId']
    verification = operation == 'verify'
    public_derivation = operation == 'public-key'
    uses_handle = mode in ['prepare', 'prepared', 'cold']
    fields = ['pk', 'message', 'signature', 'context'] if verification else ['seed', 'message', 'context', 'rnd']
    if public_derivation:
        fields = ['seed']
    declarations = '\n  '.join(f'transient let {field} : Blob = {blob(vector[field])};' for field in fields)
    configure = ''
    if uses_handle:
        handle_type = 'PreparedPublicKey' if verification else 'PreparedSecretKey'
        factory = 'H.preparePublicKey(pk)' if verification else 'H.prepareSecretKey(seed)'
        declarations += f'''\n  transient var preparedKey : ?H.{handle_type} = null;
  func getKey() : H.{handle_type} {{
    switch preparedKey {{ case (?key) key; case null Prim.trap("key not configured") }}
  }};'''
        construct = f'preparedKey := ?unwrap({factory});'
        if mode == 'prepared':
            configure = construct
    if verification:
        direct = 'H.verify(pk, message, signature, context)'
        prepared = 'H.verifyPrepared(key, message, signature, context)'
        result_type, initial = 'Bool', 'false'
        expected = '01'
        as_blob = lambda value: f'if ({value}) "\\01" else "\\00"'
    elif public_derivation:
        direct = 'H.publicKey(seed)'
        result_type, initial = 'Blob', '""'
        expected = vector['pk'].lower()
        as_blob = lambda value: value
    else:
        direct = 'H.sign(seed, message, context)' if vector['deterministic'] else 'H.signRandomized(seed, message, context, rnd)'
        prepared = 'H.signPrepared(key, message, context)' if vector['deterministic'] else 'H.signRandomizedPrepared(key, message, context, rnd)'
        result_type, initial = 'Blob', '""'
        expected = vector['signature'].lower()
        as_blob = lambda value: value
    oracle = as_blob('result')
    if mode == 'prepare':
        measured = construct
        # Opaque bytes never escape. Validate the new handle against the same
        # signature/bool oracle as direct/hot, strictly after measurement.
        oracle = f'let key = getKey(); {as_blob("unwrap(" + prepared + ")")}'
    else:
        prefix = ''
        expression = direct
        if uses_handle:
            prefix = (construct + '\n    ') if mode == 'cold' else ''
            prefix += 'let key = getKey();\n    '
            expression = prepared
        body = f'result := unwrap({expression});'
        if reuse > 1:
            body = f'var i = 0; while (i < {reuse}) {{ {body} i += 1 }};'
        measured = prefix + body
    group = f'mldsa-{operation}-acvp-{tc}'
    name = f'{group}-{mode}-n{reuse}'
    source = HERE / 'cases' / name / 'main.mo'
    source.parent.mkdir(parents=True, exist_ok=True)
    source.write_text(actor(declarations, configure, measured, result_type, initial, oracle))
    return {
        'name': name,
        'family': 'ml-dsa',
        'implementation': 'native',
        'plugins': ['ml-dsa'],
        'source': source.relative_to(CRYPTO).as_posix(),
        'expected_hex': expected,
        'memory_metrics': True,
        'message_bytes': len(vector['message']) // 2,
        'context_bytes': len(vector['context']) // 2,
        'deterministic': vector['deterministic'],
        'prepared': {
            'scheme': 'ml-dsa',
            'profile': 'FIPS204-ML-DSA-44-pure-external',
            'operation': operation,
            'fixture': f'acvp-siggen-tr1-{tc}',
            'fixture_source': 'prepared/ml-dsa/fixtures.json',
            'comparison_group': group,
            'mode': mode,
            'reuse': reuse,
            'payload_bytes': (PUBLIC_PAYLOAD if verification else SECRET_PAYLOAD) if uses_handle else 0,
        },
    }


def main():
    raw = CORPUS.read_bytes()
    corpus = json.loads(raw)
    vectors = [next(row for row in corpus['sigGen'] if row['tcId'] == tc) for tc in IDS]
    fixture = {
        'source_corpus': 'plugins/ml-dsa/tests/vectors/acvp-ml-dsa-44.json',
        'source_corpus_sha256': hashlib.sha256(raw).hexdigest(),
        'sourceCommit': corpus['sourceCommit'],
        'sources': corpus['sources'],
        'sigGen': vectors,
    }
    (HERE / 'fixtures.json').write_text(json.dumps(fixture, indent=2) + '\n')
    comparable = []
    for vector in vectors:
        signing = 'sign' if vector['deterministic'] else 'sign-randomized'
        for operation in [signing, 'verify']:
            for mode in ['direct', 'prepare', 'prepared']:
                comparable.append(emit(vector, operation, mode))
    short = vectors[0]
    for operation in ['sign', 'verify']:
        for reuse in [2, 10, 100]:
            for mode in ['direct', 'prepared']:
                comparable.append(emit(short, operation, mode, reuse))
    end_to_end = [emit(short, 'public-key', 'control')]
    for operation in ['sign', 'verify']:
        for reuse in [1, 2, 10, 100]:
            end_to_end.append(emit(short, operation, 'cold', reuse))
    assert len(comparable) == 36 and len(end_to_end) == 9
    for name, cases in [('cases.json', comparable), ('end-to-end-cases.json', end_to_end), ('all-cases.json', comparable + end_to_end)]:
        assert len({row['name'] for row in cases}) == len(cases)
        (HERE / name).write_text(json.dumps({'cases': cases}, indent=2) + '\n')
    print(f'Generated {len(comparable)} direct/prepare/hot cases and {len(end_to_end)} cold/control cases.')


if __name__ == '__main__':
    main()
