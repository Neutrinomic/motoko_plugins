#!/usr/bin/env python3
"""Generate prepared-key comparisons from the copied independent fixture subset.

No compiler, plugin, cryptographic calculation or network access is involved.
Use --check to verify generated actors and manifest without changing them.
"""
import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
BENCH = HERE.parents[1]


def blob(value):
    return '"' + ''.join('\\%02x' % byte for byte in bytes.fromhex(value)) + '"'


def declarations(inputs):
    return '\n  '.join(
        f'transient let {name} : ' +
        ('[Blob] = [' + ', '.join(blob(part) for part in value) + '];'
         if isinstance(value, list) else 'Blob = ' + blob(value) + ';')
        for name, value in inputs.items())


def prepared_setup(fixture):
    operation = fixture['operation']
    inputs = fixture['inputs']
    ic = operation.endswith('IC')
    single = operation in ('verifyIC', 'verifyEthereum')
    key_type = 'B.PreparedICPublicKey' if ic else (
        'B.PreparedEthereumPublicKey' if single else 'B.PreparedEthereumPoPKey')
    factory = 'B.prepareICPublicKey' if ic else (
        'B.prepareEthereumPublicKey' if single else 'B.prepareEthereumPoPKey')
    if single:
        return (
            f'transient var preparedKey : ?{key_type} = null;',
            f'let #ok(key) = {factory}(publicKey) else Prim.trap("prepare key failed"); preparedKey := ?key;',
            'let ?key = preparedKey else Prim.trap("prepare first");',
            f'B.{operation}Prepared(key, message, signature)',
            19680 if ic else 144,
            1,
        )
    count = len(inputs['keys'])
    shared = fixture.get('share_repeated_key', False)
    if shared:
        assert len(set(zip(inputs['keys'], inputs['proofs']))) == 1
    distinct = 1 if shared else count
    assignments = []
    for index in range(distinct):
        arguments = f'keys[{index}]' + ('' if ic else f', proofs[{index}]')
        assignments.append(
            f'let #ok(key{index}) = {factory}({arguments}) else Prim.trap("prepare key failed");')
    references = ', '.join('key0' if shared else f'key{index}' for index in range(count))
    assignments.append(f'preparedKeys := [{references}];')
    message = 'message' if operation.startswith('fastAggregate') else 'messages'
    return (
        f'transient var preparedKeys : [{key_type}] = [];',
        '\n    '.join(assignments),
        '',
        f'B.{operation}Prepared(preparedKeys, {message}, signature)',
        distinct * (19680 if ic else 144),
        distinct,
    )


def actor(fixture, mode):
    root, prepare, borrow, prepared_call, payload, distinct = prepared_setup(fixture)
    operation = fixture['operation']
    direct_arguments = ', '.join(fixture['argument_order'])
    result_field = '' if mode == 'prepare' else (
        'transient var result : B.Result<Bool> = #err(#invalidArgument);')
    if mode == 'direct':
        root = ''
        configure = 'result := #err(#invalidArgument)'
        run = f'result := B.{operation}({direct_arguments});'
        output = ''
    elif mode == 'prepare':
        configure = ''
        run = prepare
        output = f'{borrow}\n    let result = {prepared_call};'
    else:
        configure = prepare
        run = f'{borrow}\n    result := {prepared_call};'
        output = ''
    source = f'''// Generated by prepared/bls12-381/generate.py. Do not edit.
import Prim "mo:⛔";
import B "mo:fast/BLS12381";
persistent actor {{
  type Measurement = {{instructions : Nat64; allocated : Nat; reclaimed : Nat; outputSize : Nat}};
  {result_field}
  {declarations(fixture['inputs'])}
  {root}
  public func configure() : async () {{ {configure} }};
  public func run() : async Measurement {{
    let allocatedBefore = Prim.rts_total_allocation();
    let reclaimedBefore = Prim.rts_reclaimed();
    let start = Prim.performanceCounter(0);
    {run}
    let stop = Prim.performanceCounter(0);
    let allocatedAfter = Prim.rts_total_allocation();
    let reclaimedAfter = Prim.rts_reclaimed();
    {{instructions = stop - start; allocated = allocatedAfter - allocatedBefore;
      reclaimed = reclaimedAfter - reclaimedBefore; outputSize = 0}}
  }};
  public query func memory() : async {{
    heapSize : Nat; memorySize : Nat; totalAllocation : Nat; reclaimed : Nat
  }} {{
    {{heapSize = Prim.rts_heap_size(); memorySize = Prim.rts_memory_size();
      totalAllocation = Prim.rts_total_allocation(); reclaimed = Prim.rts_reclaimed()}}
  }};
  public query func bytesResult() : async Blob {{
    {output}
    assert result == #ok(true);
    "\\01"
  }};
}}
'''
    source = '\n'.join(line.rstrip() for line in source.splitlines()) + '\n'
    return source, payload, distinct


def generate():
    fixtures = json.loads((HERE / 'fixtures.json').read_text())
    outputs = {}
    cases = []
    for fixture in fixtures['fixtures']:
        assert fixture['expected'] == {'ok_bool': True}
        for mode in ('direct', 'prepare', 'prepared'):
            name = 'bls12-381-' + fixture['id'] + '-' + mode
            source, payload, distinct = actor(fixture, mode)
            path = HERE / 'cases' / name / 'main.mo'
            outputs[path] = source
            cases.append({
                'name': name,
                'implementation': 'native',
                'family': 'bls12-381',
                'plugins': ['bls12-381'],
                'source': path.relative_to(BENCH).as_posix(),
                'expected_hex': '01',
                'memory_metrics': True,
                'operations_per_sample': 1,
                'prepared': {
                    'scheme': 'bls12-381',
                    'profile': fixture['profile'],
                    'operation': fixture['operation'],
                    'fixture': fixture['id'],
                    'fixture_source': 'prepared/bls12-381/fixtures.json',
                    'comparison_group': 'bls12-381-' + fixture['id'],
                    'mode': mode,
                    'reuse': 1,
                    'payload_bytes': 0 if mode == 'direct' else payload,
                    'prepared_key_count': 0 if mode == 'direct' else distinct,
                    'key_references': len(fixture['inputs'].get('keys', [None])),
                    'shared_repeated_key': fixture.get('share_repeated_key', False),
                },
            })
    assert len(cases) == 24
    outputs[HERE / 'cases.json'] = json.dumps({
        'methodology': 'Eight comparison groups from seven independent valid inputs; direct, preparation and prepared calls use the same oracle. Preparation rows measure factories, including required PoP verification; bytesResult checks their outputs outside measurement. Repeated-key n8 groups measure one factory with eight references and eight factories producing equal values separately.',
        'cases': cases,
    }, indent=2) + '\n'
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    outputs = generate()
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'generated file differs: {path}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print(f'{len(outputs) - 1} actors {"checked" if args.check else "generated"}')


if __name__ == '__main__':
    main()
