#!/usr/bin/env python3
"""Generate bounded round-four secret-comb candidates using independent math.

This experiment helper emits source to an explicit output path. The selected
production runtime has one static format and no runtime tuning parameter.
"""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[5]
spec = importlib.util.spec_from_file_location("point_oracle", ROOT / "plugins/p256/tests/vectors/generate-p256-comb.py")
curve = importlib.util.module_from_spec(spec)
spec.loader.exec_module(curve)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tables", type=int, choices=(2, 4), required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--proof", type=Path, required=True)
    parser.add_argument("--openssl", default="openssl")
    args = parser.parse_args()
    rows = 64 // args.tables
    powers = [curve.G]
    for _ in range(255):
        powers.append(curve.add(powers[-1], powers[-1]))
    tables = []
    evidence = []
    prefix = bytes.fromhex("3059301306072a8648ce3d020106082a8648ce3d030107034200")
    for table in range(args.tables):
        entries = []
        for digit in range(1, 16):
            point = None
            coefficient = 0
            for column in range(4):
                if digit >> column & 1:
                    bit = table * rows + 64 * column
                    coefficient += 1 << bit
                    point = curve.add(point, powers[bit])
            encoded = b"\x04" + point[0].to_bytes(32, "big") + point[1].to_bytes(32, "big")
            secret = bytes.fromhex("30310201010420") + coefficient.to_bytes(32, "big") + bytes.fromhex("a00a06082a8648ce3d030107")
            actual = subprocess.run([args.openssl, "pkey", "-inform", "DER", "-pubout", "-outform", "DER"], input=secret, capture_output=True, check=True).stdout
            assert actual == prefix + encoded
            words = []
            for coordinate in point:
                montgomery = coordinate * (1 << 256) % curve.P
                words.extend((montgomery >> (64 * i)) & ((1 << 64) - 1) for i in range(4))
            entries.append(words)
            evidence.append({"table": table, "digit": digit, "coefficient": f"{coefficient:064x}", "sec1": encoded.hex(), "words": words})
        tables.append(entries)
    text = "// Generated by the round-four secret-comb proof; do not edit.\n"
    text += f"pub const TABLES: usize = {args.tables};\npub const ROWS: usize = {rows};\n"
    text += "pub const POINTS: [[[u64; 8]; 15]; TABLES] = [\n"
    for entries in tables:
        text += "    [\n"
        text += "".join("        [" + ", ".join(f"0x{x:016x}" for x in words) + "],\n" for words in entries)
        text += "    ],\n"
    text += "];\n"
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text)
    args.proof.parent.mkdir(parents=True, exist_ok=True)
    args.proof.write_text(json.dumps({"tables": args.tables, "rows": rows, "mixed_additions": 64, "full_table_selections": 64, "doublings": rows, "table_bytes": args.tables * 15 * 64, "points": evidence, "generator_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(), "runtime_sha256": hashlib.sha256(text.encode()).hexdigest(), "openssl": subprocess.check_output([args.openssl, "version"], text=True).strip(), "validated": "Every point matches independent Python arithmetic and OpenSSL exact-scalar multiplication"}, indent=2) + "\n")
    print(f"Generated {args.tables} tables / {rows} rounds / {len(evidence)} independently checked points")


if __name__ == "__main__":
    main()
