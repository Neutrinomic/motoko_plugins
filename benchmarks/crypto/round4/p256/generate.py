#!/usr/bin/env python3
"""Generate P256 round-4 screens, the full 62-case matrix and a 28-case final cohort.

No plugin output supplies an expected answer. Existing independent fixtures and
control actors are copied without changing earlier evidence. Screen actors are
also members of the final matrix. Run with --screen while projective proofs are
being prepared; its six fixtures and actor bytes do not depend on those proofs.
"""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
BENCH = HERE.parents[1]
ROOT = BENCH.parents[1]
WIDTH = 8
PAYLOAD_BYTES = 16320


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def relative(path):
    return path.relative_to(BENCH).as_posix()


def blob(value):
    return '"' + ''.join('\\%02x' % byte for byte in bytes.fromhex(value)) + '"'


def write_json(path, value):
    path.write_text(json.dumps(value, indent=2) + '\n')


def control_actor(secret, digest, expression, expected):
    return f'''// Generated by round4/p256/generate.py; exact independent output checked outside measurement.
import Prim "mo:⛔";
import P256 "mo:fast/P256";
persistent actor {{
  transient let secret : Blob = {blob(secret)};
  transient let digest : Blob = {blob(digest)};
  transient var result : P256.Result<Blob> = #ok("");
  public func configure() : async () {{}};
  public func run() : async {{instructions : Nat64; allocated : Nat; reclaimed : Nat; outputSize : Nat}} {{
    let allocatedBefore = Prim.rts_total_allocation();
    let reclaimedBefore = Prim.rts_reclaimed();
    let start = Prim.performanceCounter(0);
    result := {expression};
    let stop = Prim.performanceCounter(0);
    let allocatedAfter = Prim.rts_total_allocation();
    let reclaimedAfter = Prim.rts_reclaimed();
    {{instructions = stop - start; allocated = allocatedAfter - allocatedBefore;
      reclaimed = reclaimedAfter - reclaimedBefore; outputSize = {len(bytes.fromhex(expected))}}}
  }};
  public query func memory() : async {{heapSize : Nat; memorySize : Nat; totalAllocation : Nat; reclaimed : Nat}} {{
    {{heapSize = Prim.rts_heap_size(); memorySize = Prim.rts_memory_size();
      totalAllocation = Prim.rts_total_allocation(); reclaimed = Prim.rts_reclaimed()}}
  }};
  public query func bytesResult() : async Blob {{
    let #ok(value) = result else Prim.trap("unexpected P256 control error");
    assert value == {blob(expected)};
    value
  }};
}}
'''


def verify_actor(fixture, mode, reuse):
    prepare = 'let #ok(key) = P256.preparePublicKey(publicKey) else Prim.trap("prepare error"); prepared := ?key;'
    borrow = 'let ?key = prepared else Prim.trap("missing prepared key");'
    configure = prepare if mode == 'prepared' else ''
    verify = 'P256.verifyPrehashPrepared(key, digest, signature)' if mode in ('prepared', 'cold') else 'P256.verifyPrehash(publicKey, digest, signature)'
    if mode == 'prepare':
        operation = prepare
    else:
        operation = ('do { ' + prepare + ' }; ' if mode == 'cold' else '')
        if mode in ('prepared', 'cold'):
            operation += borrow
        operation += f' var i = 0; while (i < {reuse}) {{ result := {verify}; i += 1 }};'
    output = borrow + ' let answer = P256.verifyPrehashPrepared(key, digest, signature);' if mode == 'prepare' else 'let answer = result;'
    return f'''// Generated by round4/p256/generate.py; opaque keys stay rooted through result checking.
import Prim "mo:⛔";
import P256 "mo:fast/P256";
persistent actor {{
  transient let publicKey : Blob = {blob(fixture['public'])};
  transient let digest : Blob = {blob(fixture['digest'])};
  transient let signature : Blob = {blob(fixture['signature'])};
  transient var result : P256.Result<Bool> = #ok false;
  transient var prepared : ?P256.PreparedPublicKey = null;
  public func configure() : async () {{ {configure} }};
  public func run() : async {{instructions : Nat64; allocated : Nat; reclaimed : Nat; outputSize : Nat}} {{
    let allocatedBefore = Prim.rts_total_allocation();
    let reclaimedBefore = Prim.rts_reclaimed();
    let start = Prim.performanceCounter(0);
    {operation}
    let stop = Prim.performanceCounter(0);
    let allocatedAfter = Prim.rts_total_allocation();
    let reclaimedAfter = Prim.rts_reclaimed();
    {{instructions = stop - start; allocated = allocatedAfter - allocatedBefore;
      reclaimed = reclaimedAfter - reclaimedBefore; outputSize = 1}}
  }};
  public query func memory() : async {{heapSize : Nat; memorySize : Nat; totalAllocation : Nat; reclaimed : Nat}} {{
    {{heapSize = Prim.rts_heap_size(); memorySize = Prim.rts_memory_size();
      totalAllocation = Prim.rts_total_allocation(); reclaimed = Prim.rts_reclaimed()}}
  }};
  public query func bytesResult() : async Blob {{
    {output}
    let #ok(value) = answer else Prim.trap("verification error");
    assert value == {str(fixture['valid']).lower()};
    if (value) "\\01" else "\\00"
  }};
}}
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--screen', action='store_true', help='emit only the six-case screen; does not require projective proofs')
    args = parser.parse_args()
    proof = json.loads((ROOT / 'plugins/p256/tests/vectors/prepared-comb-proof.json').read_text())
    assert proof['width'] == WIDTH, 'round4 compares the fixed width-8 public representation'
    independent_path = BENCH / 'round3/p256/audit/independent-vectors.json'
    independent = json.loads(independent_path.read_text())
    oracle = {v['label']: v for v in independent['vectors']}
    assert independent['count'] == len(oracle) == 43
    prepared_path = BENCH / 'prepared/p256/fixtures.json'
    prepared = json.loads(prepared_path.read_text())
    verify_fixtures = prepared['vectors']
    assert len(verify_fixtures) == 7
    round3_path = BENCH / 'round3/p256/cases.json'
    round3 = {c['name']: c for c in json.loads(round3_path.read_text())['cases']}
    sign_labels = ['RFC6979/sample', 'one/zero', 'one/order', 'order-minus-one/max', 'high-bit/order-plus-one', 'sha256-pair-0']
    derive_labels = ['RFC6979/sample', 'one/zero', 'high-bit/order-plus-one']
    copied_controls = [
        ('public-key-uncompressed', 'publicKey'),
        ('convert-compressed-to-uncompressed', 'convertPublicKey'),
        ('convert-uncompressed-to-compressed', 'convertPublicKey'),
        ('der-encode-both-integers-padded', 'signatureToDer'),
        ('der-decode-both-integers-padded', 'signatureFromDer'),
        ('normalize-high-s', 'normalizeSignature'),
        ('normalize-low-s', 'normalizeSignature'),
    ]
    fixture_data = {
        'protocol': 'crypto-prepared-v1',
        'purpose': 'same-input baseline/candidate P256 arithmetic comparison',
        'public_comb_width': WIDTH,
        'prepared_payload_bytes': PAYLOAD_BYTES,
        'oracle': independent['oracle'],
        'upstream': {relative(p): sha(p) for p in [independent_path, prepared_path, round3_path]},
        'verification_vectors': verify_fixtures,
        'signing_vectors': [oracle[label] for label in sign_labels],
        'derivation_vectors': [oracle[label] for label in derive_labels],
        'copied_controls': [],
    }
    cases = []
    sources = {}

    def add(name, source, expected, operation, fixture, mode='control', reuse=1, provenance=None):
        target = HERE / 'cases' / name / 'main.mo'
        sources[name] = (target, source)
        item = {
            'name': name, 'implementation': 'native', 'family': 'p256', 'plugins': ['p256'],
            'source': relative(target), 'expected_hex': expected, 'memory_metrics': True,
            'prepared': {
                'scheme': 'p256', 'profile': 'RFC6979-SHA256-prehash', 'operation': operation,
                'fixture': fixture, 'fixture_source': relative(HERE / 'fixtures.json'),
                'comparison_group': f'p256-r4-{operation}-{fixture}', 'mode': mode,
                'reuse': reuse, 'payload_bytes': PAYLOAD_BYTES if mode in ('prepare', 'prepared', 'cold') else 0,
            },
        }
        if provenance:
            item['control_source'] = provenance['source']
            item['control_source_sha256'] = provenance['source_sha256']
        cases.append(item)

    def add_verify(fixture, modes):
        fid = fixture['label'].replace('/', '-').replace('_', '-')
        for mode, reuse in modes:
            add(f'p256-r4-{fid}-{mode}-{reuse}', verify_actor(fixture, mode, reuse),
                '01' if fixture['valid'] else '00', 'verifyPrehash', fid, mode, reuse)

    for fixture in verify_fixtures:
        modes = [(mode, 1) for mode in ('direct', 'prepare', 'prepared', 'cold')]
        if fixture['label'] == 'rfc-sample':
            modes += [(mode, reuse) for reuse in (10, 100) for mode in ('direct', 'prepared', 'cold')]
        add_verify(fixture, modes)
    for operation, labels, field, expression in [
        ('signPrehash', sign_labels, 'signature', 'P256.signPrehash(secret, digest)'),
        ('derivePublicKey', derive_labels, 'public', 'P256.derivePublicKey(secret)'),
    ]:
        for label in labels:
            fixture = oracle[label]
            fid = label.lower().replace('/', '-')
            name = f'p256-r4-{operation}-{fid}'
            source = control_actor(fixture['secret'], fixture['digest'], expression, fixture[field])
            add(name, source, fixture[field], operation, fid)
    for short_name, operation in copied_controls:
        previous = round3[f'r2-p256-{short_name}']
        path = BENCH / previous['source']
        provenance = {'source': relative(path), 'source_sha256': sha(path),
            'expected_hex': previous['expected_hex'], 'fixture_provenance': previous['fixture_provenance']}
        fixture_data['copied_controls'].append({'label': short_name, **provenance})
        add(f'p256-r4-{short_name}', path.read_text(), previous['expected_hex'], operation, short_name, provenance=provenance)

    screen_names = [
        'p256-r4-signPrehash-rfc6979-sample',
        'p256-r4-derivePublicKey-rfc6979-sample',
        'p256-r4-rfc-sample-direct-1',
        'p256-r4-rfc-sample-prepare-1',
        'p256-r4-rfc-sample-prepared-1',
        'p256-r4-convert-compressed-to-uncompressed',
    ]
    screen = [next(c for c in cases if c['name'] == name) for name in screen_names]
    # Keep screen fixture bytes independent of when the research proofs arrive.
    screen_fixtures = {**fixture_data, 'verification_vectors': [verify_fixtures[0]],
        'signing_vectors': [oracle['RFC6979/sample']], 'derivation_vectors': [oracle['RFC6979/sample']],
        'copied_controls': [c for c in fixture_data['copied_controls'] if c['label'] == 'convert-compressed-to-uncompressed']}
    write_json(HERE / 'screen-fixtures.json', screen_fixtures)
    screen = [{**c, 'prepared': {**c['prepared'], 'fixture_source': relative(HERE / 'screen-fixtures.json')}} for c in screen]
    write_json(HERE / 'screen.json', {'cases': screen})

    if not args.screen:
        projective_path = HERE / 'projective-check/vectors.json'
        projective = json.loads(projective_path.read_text())
        labels = {'rare_n_plus_3', 'near_p_minus_3', 'reject_field_wrap', 'reject_limb_wrap'}
        assert {v['label'] for v in projective['vectors']} == labels
        extra = [{**v, 'public': v['public_key'], 'valid': v['expected_valid']} for v in projective['vectors']]
        fixture_data['projective_vectors'] = extra
        fixture_data['projective_provenance'] = projective['provenance']
        fixture_data['upstream'][relative(projective_path)] = sha(projective_path)
        for fixture in extra:
            add_verify(fixture, [(mode, 1) for mode in ('direct', 'prepare', 'prepared')])
        # Independently recheck all equations using Python affine arithmetic.
        path = BENCH / 'prepared/p256/generate.py'
        spec = importlib.util.spec_from_file_location('prepared_p256_oracle', path)
        checker = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(checker)
        checker.check_fixtures(verify_fixtures + extra)
        write_json(HERE / 'fixtures.json', fixture_data)
        (HERE / 'independent-vectors.json').write_bytes(independent_path.read_bytes())
        assert len(cases) == 62 and len({c['name'] for c in cases}) == 62
        write_json(HERE / 'cases.json', {'cases': cases})
        final_names = [f'p256-r4-rfc-sample-{mode}-1' for mode in ('direct', 'prepare', 'prepared', 'cold')]
        final_names += [f'p256-r4-rfc-sample-{mode}-{reuse}' for reuse in (10, 100) for mode in ('direct', 'prepared', 'cold')]
        final_names += [f'p256-r4-{fixture}-{mode}-1'
            for fixture in ('rfc-low-s', 'rfc-wrong-digest', 'rare-n-plus-3', 'reject-field-wrap')
            for mode in ('direct', 'prepare', 'prepared')]
        final_names += [
            'p256-r4-signPrehash-rfc6979-sample',
            'p256-r4-signPrehash-one-order',
            'p256-r4-signPrehash-order-minus-one-max',
            'p256-r4-derivePublicKey-rfc6979-sample',
            'p256-r4-derivePublicKey-high-bit-order-plus-one',
            'p256-r4-convert-compressed-to-uncompressed',
        ]
        by_name = {case['name']: case for case in cases}
        final_cases = [by_name[name] for name in final_names]
        assert len(final_cases) == len(set(final_names)) == 28
        write_json(HERE / 'final-selected.json', {'cases': final_cases})
        selected = cases
    else:
        selected = screen
    for case in selected:
        target, source = sources[case['name']]
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(source)
    print(f'Generated {len(selected)} cases; screen.json always has the same six cases. No builds run.')


if __name__ == '__main__':
    main()
