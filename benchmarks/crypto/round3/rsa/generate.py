#!/usr/bin/env python3
"""Generate fixed RSA3072 plugin benchmarks from an independent OpenSSL vector."""
import json
from pathlib import Path
HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
f = json.loads((ROOT/'plugins/rsa/vectors/openssl3072.json').read_text())
def blob(value): return '"' + ''.join('\\'+value[i:i+2] for i in range(0,len(value),2)) + '"'
inputs = '\n'.join(f'  transient let {name} : Blob = {blob(f[key])};' for name,key in [('secret','privateKey'),('publicKey','publicKey'),('message','message'),('digest','digest'),('salt','salt'),('signature','signature')])
cases = []
for name,operation,boolean,expected in [
 ('derive-public-key','derivePublicKey(secret)',False,f['publicKey']),
 ('validate-private-key','validatePrivateKey(secret)',True,'01'),
 ('validate-public-key','validatePublicKey(publicKey)',True,'01'),
 ('sign-prehash','signPrehash(secret,digest,salt)',False,f['signature']),
 ('verify-prehash','verifyPrehash(publicKey,digest,signature)',True,'01'),
 ('sign-message','sign(secret,message,salt)',False,f['signature']),
 ('verify-message','verify(publicKey,message,signature)',True,'01'),
]:
 label='r3-rsa3072-'+name
 path=HERE/'cases'/label/'main.mo';path.parent.mkdir(parents=True,exist_ok=True)
 source='''// Generated by benchmarks/crypto/round3/rsa/generate.py.
import Prim "mo:prim";
import RSA "mo:fast/RSA";
persistent actor {
INPUTS
  transient var output : TYPE = INITIAL;
  public func configure() : async () {};
  public func run() : async {instructions:Nat64;allocated:Nat;reclaimed:Nat;outputSize:Nat} {
    let before = Prim.rts_total_allocation();
    let reclaimedBefore = Prim.rts_reclaimed();
    let start = Prim.performanceCounter(0);
    let #ok(value) = RSA.OPERATION else Prim.trap("RSA benchmark operation failed");
    output := value;
    let instructions = Prim.performanceCounter(0) - start;
    let allocated = Prim.rts_total_allocation() - before;
    let reclaimed = Prim.rts_reclaimed() - reclaimedBefore;
    {instructions;allocated;reclaimed;outputSize=SIZE}
  };
  public query func bytesResult() : async Blob {
    let result : Blob = RESULT;
    assert result == EXPECTED;
    result
  };
}
'''.replace('INPUTS',inputs).replace('TYPE','Bool' if boolean else 'Blob').replace('INITIAL','false' if boolean else '""').replace('OPERATION',operation).replace('SIZE','1' if boolean else '384').replace('RESULT','if (output) "\\01" else "\\00"' if boolean else 'output').replace('EXPECTED',blob(expected))
 path.write_text(source)
 cases.append({'name':label,'implementation':'native','plugins':['rsa'],'source':str(path.relative_to(HERE.parents[1])),'expected_hex':expected})
(HERE/'cases.json').write_text(json.dumps({'profile':'RSA3072/e65537 PSS SHA256 MGF1SHA256 salt32; all cryptographic input parsing and CRT consistency checks included. Message case hashes47bytes; prehash uses32byte digest.','cases':cases},indent=2)+'\n')
