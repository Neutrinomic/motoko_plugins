#!/usr/bin/env python3
"""Round-two curve hotspots; writes only this directory, never round-one cases.

Expected SEC1/scalar/ECDSA/DER bytes are independently derived with Python integer
affine arithmetic. Schnorr cases use the frozen official BIP340 corpus. Candidate
and frozen baseline execute the identical existing public API and generated source.
"""
import csv
import hashlib
import importlib.util
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
BENCH = HERE.parents[1]
ROOT = BENCH.parents[1]
ORACLE = BENCH/'generate-curves.py'
spec = importlib.util.spec_from_file_location('round_one_affine_oracle', ORACLE)
oracle = importlib.util.module_from_spec(spec)
spec.loader.exec_module(oracle)


def blob(value):
    return '"'+''.join('\\%02x' % byte for byte in value)+'"'


def sec1(point, compressed=True):
    x, y = point
    return ((bytes([2 | (y & 1)])+x.to_bytes(32, 'big')) if compressed else
            b'\x04'+x.to_bytes(32, 'big')+y.to_bytes(32, 'big'))


def signature(curve, secret, digest):
    n = curve['n']
    add = lambda x, y: oracle.ec_add(x, y, curve['p'], curve['a'])
    public = oracle.multiply(curve['g'], secret, add)
    r = oracle.multiply(curve['g'], oracle.NONCE, add)[0] % n
    s = (int.from_bytes(digest, 'big')+r*secret)*pow(oracle.NONCE, -1, n) % n
    s = min(s, n-s)
    assert r and s
    inv = pow(s, -1, n)
    recovered = add(oracle.multiply(curve['g'], int.from_bytes(digest, 'big')*inv % n, add),
                    oracle.multiply(public, r*inv % n, add))
    assert recovered[0] % n == r
    return r.to_bytes(32, 'big')+s.to_bytes(32, 'big')


def to_der(compact):
    integers = []
    for value in (compact[:32], compact[32:]):
        value = value.lstrip(b'\x00') or b'\x00'
        if value[0] & 0x80:
            value = b'\x00'+value
        integers.append(b'\x02'+bytes([len(value)])+value)
    payload = b''.join(integers)
    return b'\x30'+bytes([len(payload)])+payload


def source(module, inputs, expression, expected, result_type='Blob'):
    initial = '""' if result_type == 'Blob' else 'false'
    declarations = '\n  '.join(f'transient let {name} : Blob = {blob(value)};' for name, value in inputs.items())
    output = 'value' if result_type == 'Blob' else 'if (value) "\\01" else "\\00"'
    return f'''// Generated by round2/curve-hotspots/generate.py. Do not edit.
import Prim "mo:prim";
import C "mo:fast/{module}";
persistent actor {{
  {declarations}
  transient var result : C.Result<{result_type}> = #ok({initial});
  public func configure() : async () {{}};
  public func run() : async {{instructions : Nat64; allocated : Nat; reclaimed : Nat; outputSize : Nat}} {{
    let allocatedBefore = Prim.rts_total_allocation();
    let reclaimedBefore = Prim.rts_reclaimed();
    let start = Prim.performanceCounter(0);
    result := {expression};
    let stop = Prim.performanceCounter(0);
    let allocatedAfter = Prim.rts_total_allocation();
    let reclaimedAfter = Prim.rts_reclaimed();
    {{instructions = stop-start; allocated = allocatedAfter-allocatedBefore;
      reclaimed = reclaimedAfter-reclaimedBefore; outputSize = 0}}
  }};
  public query func bytesResult() : async Blob {{
    let #ok(value) = result else Prim.trap("unexpected curve error");
    let actual : Blob = {output};
    assert actual == {blob(expected)};
    actual
  }};
}}
'''


def main():
    cases, fixtures = [], []
    def add_case(family, operation, inputs, expression, expected, result_type='Blob', note='', provenance=None):
        name = f'r2-{family}-{operation}'
        directory = HERE/'cases'/name
        directory.mkdir(parents=True, exist_ok=True)
        target = directory/'main.mo'
        target.write_text(source(oracle.CURVES[family]['module'], inputs, expression, expected, result_type))
        common = dict(name=name, family=family, implementation='fast', comparison=name,
                      plugins=[family], source=target.relative_to(BENCH).as_posix(), expected_hex=expected.hex(),
                      operations_per_sample=1, notes=note or 'One existing public API call; immutable Blob inputs are prepared before measurement. Result interpretation and expected-output checking are outside measurement.',
                      fixture_provenance=provenance or 'Independent Python affine arithmetic, compact ECDSA algebra verification and minimal DER integer encoding; fixed public test scalars. No plugin outputs used as expected values.')
        cases.append(common)
        fixtures.append(dict(name=name, inputs={k:v.hex() for k,v in inputs.items()}, expression=expression, expected_hex=expected.hex(), expected_result='ok', result_type=result_type))

    for family, curve in oracle.CURVES.items():
        n = curve['n']
        add = lambda x, y: oracle.ec_add(x, y, curve['p'], curve['a'])
        multiply = lambda point, scalar: oracle.multiply(point, scalar, add)
        d = oracle.SECRET
        public = multiply(curve['g'], d)
        key = sec1(public)
        raw = sec1(public, False)
        secret = d.to_bytes(32, 'big')
        for input_kind, input_key in (('compressed', key), ('uncompressed', raw)):
            for output_kind, compressed in (('compressed', True), ('uncompressed', False)):
                add_case(family, f'convert-{input_kind}-to-{output_kind}', {'key':input_key},
                         f'C.convertPublicKey(key, {str(compressed).lower()})', sec1(public, compressed))
        add_case(family, 'public-key-uncompressed', {'secret':secret}, 'C.publicKey(secret, false)', raw)

        low = signature(curve, d, oracle.DIGEST)
        high = low[:32]+(n-int.from_bytes(low[32:], 'big')).to_bytes(32, 'big')
        for input_kind, input_key in (('compressed', key), ('uncompressed', raw)):
            for sig_kind, compact in (('low-s', low), ('high-s', high)):
                add_case(family, f'verify-{input_kind}-{sig_kind}', {'key':input_key,'digest':oracle.DIGEST,'signature':compact},
                         'C.verifyPrehash(key, digest, signature)', b'\x01', 'Bool')
            wrong_digest = bytes([oracle.DIGEST[0]^1])+oracle.DIGEST[1:]
            add_case(family, f'verify-{input_kind}-invalid-equation', {'key':input_key,'digest':wrong_digest,'signature':low},
                     'C.verifyPrehash(key, digest, signature)', b'\x00', 'Bool',
                     note='Well-formed public key and signature, with the signed digest mutated. A complete verification equation must return #ok(false).')

        for label, digest in (('zero', bytes(32)), ('order', n.to_bytes(32, 'big')), ('all-ff', bytes([255])*32)):
            signed = signature(curve, d, digest)
            add_case(family, f'verify-digest-{label}', {'key':key,'digest':digest,'signature':signed},
                     'C.verifyPrehash(key, digest, signature)', b'\x01', 'Bool',
                     note='Valid independently signed boundary digest, exercising scalar reduction and zero/window boundaries in public verification.')
        for label, scalar in (('generator', 1), ('negated-generator', n-1)):
            signed = signature(curve, scalar, oracle.DIGEST)
            add_case(family, f'verify-key-{label}', {'key':sec1(multiply(curve['g'],scalar)),'digest':oracle.DIGEST,'signature':signed},
                     'C.verifyPrehash(key, digest, signature)', b'\x01', 'Bool')

        boundary = (n-1).to_bytes(32,'big')+(n-2).to_bytes(32,'big')
        for label, compact in (('ordinary',low), ('both-integers-padded',boundary)):
            der = to_der(compact)
            add_case(family, f'der-encode-{label}', {'signature':compact}, 'C.signatureToDer(signature)', der)
            add_case(family, f'der-decode-{label}', {'der':der}, 'C.signatureFromDer(der)', compact)
        for label, compact in (('low-s',low), ('high-s',high)):
            add_case(family, f'normalize-{label}', {'signature':compact}, 'C.normalizeSignature(signature)', low)

        if family != 'secp256k1':
            continue
        q_scalar = int.from_bytes(hashlib.sha256(b'round2 distinct secp point').digest(),'big') % (n-1)+1
        q = multiply(curve['g'],q_scalar)
        tweak_scalar = int.from_bytes(hashlib.sha256(b'round2 full-width secp tweak').digest(),'big') % (n-1)+1
        tweak = tweak_scalar.to_bytes(32,'big')
        for left_kind, left in (('compressed',key),('uncompressed',raw)):
            add_case(family, f'point-add-{left_kind}-distinct', {'left':left,'right':sec1(q,False)},
                     'C.pointAdd(left, right)', sec1(add(public,q)))
            add_case(family, f'point-add-{left_kind}-doubling', {'left':left,'right':key},
                     'C.pointAdd(left, right)', sec1(add(public,public)))
            add_case(family, f'point-multiply-{left_kind}', {'key':left,'scalar':tweak},
                     'C.pointMultiply(key, scalar)', sec1(multiply(public,tweak_scalar)))
            add_case(family, f'x-only-{left_kind}', {'key':left}, 'C.xOnlyPublicKey(key)', public[0].to_bytes(32,'big'))
            for label, scalar in (('zero',0),('full-width',tweak_scalar)):
                add_case(family, f'tweak-{left_kind}-{label}', {'key':left,'tweak':scalar.to_bytes(32,'big')},
                         'C.tweakPublicKey(key, tweak)', sec1(add(public,multiply(curve['g'],scalar))))
        add_case(family, 'base-multiply-full-width', {'scalar':tweak}, 'C.baseMultiply(scalar)', sec1(multiply(curve['g'],tweak_scalar)))
        even_secret = d if public[1]%2 == 0 else n-d
        even_public = multiply(curve['g'],even_secret)
        add_case(family, 'tweak-x-only-public-full-width', {'key':public[0].to_bytes(32,'big'),'tweak':tweak},
                 'C.tweakXOnlyPublicKey(key, tweak)', sec1(add(even_public,multiply(curve['g'],tweak_scalar))))
        for label, scalar in (('even-y',even_secret),('odd-y',n-even_secret)):
            add_case(family, f'tweak-x-only-secret-{label}', {'secret':scalar.to_bytes(32,'big'),'tweak':tweak},
                     'C.tweakXOnlySecretKey(secret, tweak)', ((even_secret+tweak_scalar)%n).to_bytes(32,'big'))

    corpus = HERE/'fixtures/bip340.csv'
    # Official vectors15,1,18 exercise empty/32/100-byte messages with exact signing oracles.
    for vector in csv.DictReader(corpus.read_text().splitlines()):
        if int(vector['index']) not in (15,1,18):
            continue
        inputs = {'secret':bytes.fromhex(vector['secret key']), 'key':bytes.fromhex(vector['public key']),
                  'aux':bytes.fromhex(vector['aux_rand']), 'message':bytes.fromhex(vector['message']),
                  'signature':bytes.fromhex(vector['signature'])}
        length = len(inputs['message'])
        provenance = f'Official BIP340 vector{vector["index"]}; https://github.com/bitcoin/bips/blob/master/bip-0340/test-vectors.csv; frozen CSV SHA256 '+hashlib.sha256(corpus.read_bytes()).hexdigest()
        add_case('secp256k1', f'schnorr-sign-message-{length}', inputs, 'C.schnorrSign(secret, message, aux)',inputs['signature'],provenance=provenance)
        add_case('secp256k1', f'schnorr-verify-message-{length}',inputs,'C.schnorrVerify(key, message, signature)',b'\x01','Bool',provenance=provenance)

    (HERE/'curve-cases.json').write_text(json.dumps(cases,indent=2)+'\n')
    (HERE/'fixtures/curve-inputs.json').write_text(json.dumps({'oracle_source':ORACLE.relative_to(ROOT).as_posix(),
        'oracle_sha256':hashlib.sha256(ORACLE.read_bytes()).hexdigest(),'cases':fixtures},indent=2)+'\n')
    bls_manifest = HERE/'bls/cases.json'
    if bls_manifest.exists():
        extra = json.loads(bls_manifest.read_text())
        cases += extra['cases'] if isinstance(extra,dict) else extra
    assert len(cases)==len({(c['name'],c['implementation']) for c in cases})
    (HERE/'cases.json').write_text(json.dumps(cases,indent=2)+'\n')
    print(f'Generated {len(fixtures)} secp/P256 cases, {len(cases)} total with available BLS cases')


if __name__ == '__main__':
    main()
