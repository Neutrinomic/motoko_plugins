#!/usr/bin/env python3
"""Generate round-two BLS hotspots, independently checked with py_ecc==8.0.0.

Writes only alongside this script. Use --check to reproduce and compare without
writing. Never imports plugin code or invokes the compiler or benchmark runner.
"""
import argparse
import hashlib
import json
from functools import reduce
from pathlib import Path

import py_ecc
from py_ecc.bls import G2ProofOfPossession as Eth
from py_ecc.bls.g2_primitives import subgroup_check
from py_ecc.bls.hash_to_curve import hash_to_G1
from py_ecc.bls.point_compression import compress_G1, compress_G2, decompress_G1, decompress_G2
from py_ecc.optimized_bls12_381 import (
    FQ12, G1, G2, Z1, Z2, add, curve_order, field_modulus,
    final_exponentiate, is_inf, multiply, neg, pairing,
)

HERE = Path(__file__).resolve().parent
BENCH = HERE.parents[2]
ROOT = BENCH.parents[1]
IC_DST = b'BLS_SIG_BLS12381G1_XMD:SHA-256_SSWU_RO_NUL_'
ERRORS = ['invalidLength', 'invalidPoint', 'invalidScalar', 'invalidField',
          'tooManyItems', 'emptyBatch', 'identity', 'invalidProof',
          'duplicateMessage', 'invalidArgument']
RFC_PINS = {
    1: '9ed93f6ae3e5d3e2ef48d7f3a954ac4ccc0702f693e62b2f48798348618ef6cc',
    2: '7ff2010d99cd886ab8e951ae1ed657b57e6b95fe6029fa4a0f519ea5ca29f126',
}


def scalar(label, index):
    """Deterministic non-secret full-width canonical scalars (bit 254 set)."""
    digest = hashlib.sha512(b'motoko-bls-round2/' + label + index.to_bytes(4, 'big')).digest()
    return (1 << 254) + int.from_bytes(digest, 'big') % (curve_order - (1 << 254))


def encode(point, group):
    compressed = compress_G1(point) if group == 1 else compress_G2(point)
    parts = [compressed] if group == 1 else compressed
    return b''.join(part.to_bytes(48, 'big') for part in parts)


def decode(encoded, group):
    if group == 1:
        return decompress_G1(int.from_bytes(encoded, 'big'))
    return decompress_G2(tuple(int.from_bytes(encoded[i:i+48], 'big') for i in (0, 48)))


def blob(data):
    return '"' + ''.join('\\%02x' % byte for byte in data) + '"'


def mo_value(value):
    return blob(value) if isinstance(value, bytes) else '[' + ', '.join(map(blob, value)) + ']'


def encoded_result(expected):
    if 'err' in expected:
        return bytes([255, 1 + ERRORS.index(expected['err'])])
    if 'ok_bool' in expected:
        return bytes([0, int(expected['ok_bool'])])
    return b'\x00' + bytes.fromhex(expected['ok_hex'])


def actor(operation, inputs, expected):
    output_type = 'Bool' if 'ok_bool' in expected or operation.startswith(('aggregate', 'fastAggregate')) else 'Blob'
    declarations = '\n  '.join(
        f'transient let {name} : {"Blob" if isinstance(value, bytes) else "[Blob]"} = {mo_value(value)};'
        for name, value in inputs.items())
    canonical = ('switch (result) { case (#ok(true)) "\\00\\01"; case (#ok(false)) "\\00\\00"; case (#err(error)) errorBytes(error) }'
                 if output_type == 'Bool' else
                 'switch (result) { case (#ok(value)) successBytes(value); case (#err(error)) errorBytes(error) }')
    error_cases = '\n      '.join(f'case (#{error}) {blob(bytes([255, index + 1]))};'
                                   for index, error in enumerate(ERRORS))
    # Result construction/storage is measured. Encoding and equality assertions
    # are deliberately in the query, outside the sampled instruction interval.
    return f'''// Generated by round2/curve-hotspots/bls/generate.py. Do not edit.
import Prim "mo:prim";
import B "mo:fast/BLS12381";
persistent actor {{
  type Measurement = {{ instructions : Nat64; allocated : Nat; reclaimed : Nat; outputSize : Nat }};
  transient var result : B.Result<{output_type}> = #err(#invalidArgument);
  {declarations}
  func errorBytes(error : B.Error) : Blob {{
    switch (error) {{
      {error_cases}
    }}
  }};
  func successBytes(value : Blob) : Blob {{
    let bytes = Prim.blobToArray(value);
    Prim.arrayToBlob(Prim.Array_tabulate<Nat8>(bytes.size() + 1, func(i) {{
      if (i == 0) 0 else bytes[i - 1]
    }}))
  }};
  public func configure() : async () {{ result := #err(#invalidArgument) }};
  public func run() : async Measurement {{
    let allocatedBefore = Prim.rts_total_allocation();
    let reclaimedBefore = Prim.rts_reclaimed();
    let start = Prim.performanceCounter(0);
    result := B.{operation}({', '.join(inputs)});
    let stop = Prim.performanceCounter(0);
    let allocatedAfter = Prim.rts_total_allocation();
    let reclaimedAfter = Prim.rts_reclaimed();
    {{ instructions = stop - start; allocated = allocatedAfter - allocatedBefore;
       reclaimed = reclaimedAfter - reclaimedBefore; outputSize = {len(encoded_result(expected))} }}
  }};
  public query func bytesResult() : async Blob {{
    let actual : Blob = {canonical};
    assert actual == {blob(encoded_result(expected))};
    actual
  }};
}}
'''


def make_cases():
    assert py_ecc.__version__ == '8.0.0', 'Fixture oracle must be py_ecc==8.0.0'
    cases = []
    source_evidence = []

    def case(suffix, operation, inputs, expected, notes, oracle):
        name = 'round2_bls12_381_' + suffix
        cases.append(dict(name=name, operation=operation, inputs=inputs,
                          expected=expected, notes=notes, oracle=oracle))

    for group, base, identity in [(1, G1, Z1), (2, G2, Z2)]:
        valid = encode(multiply(base, scalar(b'validation', group)), group)
        assert subgroup_check(decode(valid, group))
        for label, point in [('valid', valid), ('identity', encode(identity, group))]:
            case(f'validate_g{group}_{label}', f'validateG{group}', dict(point=point),
                 dict(ok_hex=point.hex()),
                 'Canonical compressed point validation including subgroup check. ' +
                 ('Full-width scalar-derived nonidentity point.' if label == 'valid' else
                  'The raw validation API accepts identity; signature-profile APIs reject identity.'),
                 'py_ecc 8.0.0 independent generator multiplication, compression, decompression and subgroup_check.')

        # Q0 is before cofactor clearing in the published RFC9380 corpus.
        path = HERE / 'fixtures' / f'rfc9380-g{group}.json'
        raw = path.read_bytes()
        assert hashlib.sha256(raw).hexdigest() == RFC_PINS[group]
        corpus = json.loads(raw)
        point = corpus['vectors'][0]['Q0']
        x = [int(v, 16) for v in point['x'].split(',')]
        y = [int(v, 16) for v in point['y'].split(',')]
        sign = (y[-1] > field_modulus // 2) if y[-1] else y[0] > field_modulus // 2
        first = ((1 << 383) | (int(sign) << 381) | x[-1]).to_bytes(48, 'big')
        encoded = first if group == 1 else first + x[0].to_bytes(48, 'big')
        decoded = decode(encoded, group)
        assert encode(decoded, group) == encoded and not is_inf(decoded)
        assert not subgroup_check(decoded)
        source_evidence.append(dict(file=str(path.relative_to(ROOT)), sha256=RFC_PINS[group],
                                    copied_from=f'tests/crypto-audit/bls/rfc9380-g{group}.json',
                                    vector=0, field='Q0', coordinates=point,
                                    url='https://raw.githubusercontent.com/cfrg/draft-irtf-cfrg-hash-to-curve/main/poc/vectors/' +
                                    f'BLS12381G{group}_XMD:SHA-256_SSWU_RO_.json'))
        case(f'validate_g{group}_non_subgroup', f'validateG{group}', dict(point=encoded),
             dict(err='invalidPoint'), 'Canonical, on-curve RFC9380 Q0 point outside the prime-order subgroup. ' +
             'Measures subgroup rejection, not an early encoding rejection.',
             f'Pinned RFC9380 G{group} vector 0 Q0; py_ecc independently decodes, recompresses and rejects subgroup membership.')

    # Every boundary uses the same prefixes of dense, full-width deterministic
    # scalars and distinct nonidentity subgroup points. No zero-scalar shortcuts.
    for group, base, counts in [
        (1, G1, [0, 1, 2, 3, 4, 7, 8, 9, 15, 16, 17, 31, 32, 33]),
        (2, G2, [3, 4, 8, 32]),
    ]:
        factors = [scalar(b'point', i) for i in range(max(counts))]
        scalars = [scalar(b'msm', i) for i in range(max(counts))]
        points = [multiply(base, factor) for factor in factors]
        encoded_points = [encode(point, group) for point in points]
        assert len(set(encoded_points)) == len(encoded_points)
        # A separate pointwise accumulation cross-checks the scalar-linearity
        # oracle for every prefix without reproducing bucket/window algorithms.
        accumulated = Z1 if group == 1 else Z2
        outputs = {0: encode(accumulated, group)}
        for i, (point, coefficient) in enumerate(zip(points, scalars), start=1):
            accumulated = add(accumulated, multiply(point, coefficient))
            if i in counts:
                linear = multiply(base, sum(x*y for x, y in zip(factors[:i], scalars[:i])) % curve_order)
                assert encode(accumulated, group) == encode(linear, group)
                outputs[i] = encode(linear, group)
        for count in counts:
            case(f'g{group}_msm_n{count}', f'g{group}Msm',
                 dict(points=b''.join(encoded_points[:count]),
                      scalars=b''.join(value.to_bytes(32, 'big') for value in scalars[:count])),
                 dict(ok_hex=outputs[count].hex()),
                 f'{count} packed points/scalars; complete public API includes validation, decoding, MSM and encoding. ' +
                 'Distinct nonidentity points and dense canonical 255-bit public scalars; identical prefixes across sizes. ' +
                 ('Empty input must return identity.' if count == 0 else 'Input packing is outside measurement.'),
                 'py_ecc 8.0.0: sum of independent pointwise scalar products cross-checked against generator multiplication by sum(point_factor * scalar) mod r.')
        print(f'Prepared G{group} MSM fixtures', flush=True)

    secrets = [scalar(b'signature-key', i) for i in range(8)]
    keys = [Eth.SkToPk(secret) for secret in secrets]
    proofs = [Eth.PopProve(secret) for secret in secrets]
    assert all(Eth.PopVerify(key, proof) for key, proof in zip(keys, proofs))
    messages = [hashlib.sha256(b'motoko-bls-round2/message/' + bytes([i])).digest() for i in range(8)]
    signatures = [Eth.Sign(secret, message) for secret, message in zip(secrets, messages)]
    same_signatures = [Eth.Sign(secret, messages[0]) for secret in secrets]
    ic_keys = [encode(multiply(G2, secret), 2) for secret in secrets]
    ic_hashes = [hash_to_G1(message, IC_DST, hashlib.sha256) for message in messages]
    ic_signatures = [multiply(point, secret) for point, secret in zip(ic_hashes, secrets)]
    eth_oracle = 'py_ecc 8.0.0 G2ProofOfPossession SkToPk/Sign/PopProve/Aggregate; all key PoPs and each aggregate independently verified.'
    ic_oracle = 'py_ecc 8.0.0 hash_to_G1 with IC NUL DST; scalar-derived G2 keys and aggregated G1 signatures; independent pairing-product identity verified.'
    for count in (2, 8):
        repeated_signature = Eth.Aggregate([signatures[0]] * count)
        assert Eth.AggregateVerify([keys[0]] * count, [messages[0]] * count, repeated_signature)
        case(f'aggregate_ethereum_repeated_key_message_n{count}', 'aggregateVerifyEthereum',
             dict(keys=[keys[0]] * count, proofs=[proofs[0]] * count,
                  messages=[messages[0]] * count, signature=repeated_signature),
             dict(ok_bool=True), f'{count} copies of the same canonical key, PoP and 32-byte message. ' +
             'Complete Ethereum POP aggregate API, including required proof checks on each call. Repetition is valid under this profile.', eth_oracle)

        signature = Eth.Aggregate(signatures[:count])
        assert Eth.AggregateVerify(keys[:count], messages[:count], signature)
        case(f'aggregate_ethereum_distinct_n{count}', 'aggregateVerifyEthereum',
             dict(keys=keys[:count], proofs=proofs[:count], messages=messages[:count], signature=signature),
             dict(ok_bool=True), f'{count} distinct keys, valid PoPs and distinct 32-byte messages. ' +
             'Complete Ethereum POP aggregate API, including every proof check and message hash.', eth_oracle)

        signature = Eth.Aggregate(same_signatures[:count])
        assert Eth.FastAggregateVerify(keys[:count], messages[0], signature)
        case(f'fast_aggregate_ethereum_distinct_keys_n{count}', 'fastAggregateVerifyEthereum',
             dict(keys=keys[:count], proofs=proofs[:count], message=messages[0], signature=signature),
             dict(ok_bool=True), f'{count} distinct keys and valid PoPs signing the same 32-byte message. ' +
             'Complete fast aggregate API includes every PoP verification, key aggregation and final signature verification; no prevalidated-proof assumption.', eth_oracle)

        ic_signature = reduce(add, ic_signatures[:count], Z1)
        product = pairing(G2, neg(ic_signature), final_exponentiate=False)
        for secret, hashed in zip(secrets[:count], ic_hashes[:count]):
            product *= pairing(multiply(G2, secret), hashed, final_exponentiate=False)
        assert final_exponentiate(product) == FQ12.one()
        case(f'aggregate_ic_distinct_n{count}', 'aggregateVerifyIC',
             dict(keys=ic_keys[:count], messages=messages[:count], signature=encode(ic_signature, 1)),
             dict(ok_bool=True), f'{count} distinct G2 keys and pairwise-distinct 32-byte messages. Complete IC basic aggregate API including duplicate scan, validation, hashing and pairing.', ic_oracle)

        # Duplicate is last, and repeats the penultimate entry: all preceding
        # comparisons must run before the API can return duplicateMessage.
        duplicates = messages[:count]
        duplicates[-1] = duplicates[-2]
        case(f'aggregate_ic_late_duplicate_n{count}', 'aggregateVerifyIC',
             dict(keys=ic_keys[:count], messages=duplicates, signature=encode(ic_signature, 1)),
             dict(err='duplicateMessage'), f'{count} entries, only final message duplicates penultimate; measures complete duplicate scan and required rejection before cryptography. Signature is from the corresponding distinct-message fixture.',
             'Public IC basic-aggregate contract: duplicate message rejection precedes signature/key cryptography. Canonical inputs are independently generated with py_ecc 8.0.0.')
        print(f'Prepared n={count} aggregate fixtures', flush=True)

    messages = [i.to_bytes(32, 'big') for i in range(127)]
    messages[-1] = messages[-2]
    case('aggregate_ic_late_duplicate_n127', 'aggregateVerifyIC',
         dict(keys=[encode(G2, 2)] * 127, messages=messages, signature=encode(G1, 1)),
         dict(err='duplicateMessage'),
         '127 canonical generator keys and 32-byte messages; only the final message repeats the penultimate. Exercises all 8001 pairwise comparisons before duplicate rejection. Canonical generator signature is not valid for these messages; duplicateMessage must win before cryptography.',
         'Deterministic integer-encoded messages independently checked for uniqueness before the final duplicate; standard py_ecc G1/G2 generator encodings. Expected error follows the public IC API contract.')
    assert len(set(messages[:-1])) == 126 and messages[-1] == messages[-2]
    assert len(cases) == 35 and len({case['name'] for case in cases}) == 35
    return cases, source_evidence


def generate(check=False):
    cases, sources = make_cases()
    outputs = {}
    manifest = []
    fixtures = []
    for case in cases:
        target = HERE / 'cases' / case['name'] / 'main.mo'
        source = actor(case['operation'], case['inputs'], case['expected'])
        outputs[target] = source
        manifest.append(dict(name=case['name'], family='bls12-381', implementation='fast',
                             comparison=case['name'], plugins=['bls12-381'],
                             source=target.relative_to(BENCH).as_posix(),
                             expected_hex=encoded_result(case['expected']).hex(),
                             operations_per_sample=1, benchmark_kind='absolute-only',
                             notes=case['notes'],
                             fixture_provenance=case['oracle'] + ' Retained inputs/results: round2/curve-hotspots/bls/fixtures.json; generator/oracle/corpus hashes: provenance.json.'))
        fixtures.append(dict(name=case['name'], operation=case['operation'],
                             inputs={name: value.hex() if isinstance(value, bytes) else [part.hex() for part in value]
                                     for name, value in case['inputs'].items()},
                             expected=case['expected'], expected_hex=encoded_result(case['expected']).hex(),
                             oracle=case['oracle']))
    dumps = lambda value: json.dumps(value, indent=2, sort_keys=True) + '\n'
    outputs[HERE / 'cases.json'] = dumps(manifest)
    outputs[HERE / 'fixtures.json'] = dumps(fixtures)
    py_root = Path(py_ecc.__file__).resolve().parent
    module_hashes = {path.relative_to(py_root).as_posix(): hashlib.sha256(path.read_bytes()).hexdigest()
                     for path in sorted(py_root.rglob('*.py'))}
    outputs[HERE / 'provenance.json'] = dumps(dict(
        oracle='Ethereum py_ecc', oracle_version=py_ecc.__version__,
        oracle_source_sha256=module_hashes,
        generator_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        fixture_sha256=hashlib.sha256(outputs[HERE / 'fixtures.json'].encode()).hexdigest(),
        manifest_sha256=hashlib.sha256(outputs[HERE / 'cases.json'].encode()).hexdigest(),
        source_sha256={path.relative_to(HERE).as_posix(): hashlib.sha256(text.encode()).hexdigest()
                       for path, text in outputs.items() if path.suffix == '.mo'},
        sources=sources, cases=len(cases),
        result_encoding='Success: 00 followed by compressed point or Boolean 00/01. Error: ff followed by 1-based public Error order: ' + ', '.join(ERRORS),
        generation_scope='Generator reads pinned RFC corpora; writes only its own directory. No plugin code is imported or executed.',
        measurement='One complete public API call plus Result assignment. Input construction, status/byte encoding and assertion are outside the instruction interval. Ethereum APIs include per-call PoP verification.',
        baseline_api='_build/crypto-optimization-round2/baseline/packages/fast/src/BLS12381.mo',
    ))
    if check:
        for path, contents in outputs.items():
            assert path.read_text() == contents, f'Generated fixture mismatch: {path}'
        print(f'Checked {len(cases)} BLS hotspot fixtures and {len(outputs)} artifacts', flush=True)
    else:
        for path, contents in outputs.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(contents)
        print(f'Generated {len(cases)} BLS hotspot fixtures in {HERE}', flush=True)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    generate(parser.parse_args().check)
