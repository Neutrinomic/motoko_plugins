def counterpart_fixtures():
    """Recheck exact retained inputs with py_ecc, never with the plugin."""
    fixtures = json.loads((HERE / 'selected-counterparts.json').read_text())
    for fixture in fixtures:
        function = fixture['function']
        inputs = {name: bytes.fromhex(value) for name, value in fixture['inputs'].items()}
        point = lambda value: decompress_G1(int.from_bytes(value, 'big'))
        if function == 'validateG1':
            decoded = point(inputs['point'])
            assert subgroup_check(decoded)
            expected = encode(decoded, 1)
        elif function == 'g1Add':
            expected = encode(add(point(inputs['left']), point(inputs['right'])), 1)
        elif function == 'g1Mul':
            expected = encode(multiply(point(inputs['point']), int.from_bytes(inputs['scalar'], 'big')), 1)
        elif function == 'g1Msm':
            points, scalars = inputs['points'], inputs['scalars']
            assert len(points) // 48 == len(scalars) // 32 == 8
            expected = encode(reduce(add, [multiply(point(points[i*48:(i+1)*48]), int.from_bytes(scalars[i*32:(i+1)*32], 'big')) for i in range(8)], Z1), 1)
        elif function == 'mapToG1':
            expected = encode(clear_cofactor_G1(map_to_curve_G1(FQ(int.from_bytes(inputs['input'], 'big')))), 1)
        else:
            assert function == 'mapToG2'
            value = inputs['input']
            expected = encode(clear_cofactor_G2(map_to_curve_G2(FQ2([int.from_bytes(value[:48], 'big'), int.from_bytes(value[48:], 'big')]))), 2)
        if fixture['wire'] == 'tagged':
            expected = b'\x00' + expected
        assert expected.hex() == fixture['fast_case']['expected_hex'], function
        assert hashlib.sha256(fixture['source_snapshot'].encode()).hexdigest() == fixture['fast_case']['source_sha256']
        yield fixture, inputs, expected


def generate(check):
    assert py_ecc.__version__ == '8.0.0'
    inventory = json.loads((HERE / 'inventory-inputs.json').read_text())
    assert sha(HERE / 'fixtures/public-api.mo') == inventory['module_sha256']
    missing = [row['name'] for row in inventory['public_callables']
               if not any(row['name'] in case['direct_api_calls'] for case in inventory['existing_cases'])]
    assert set(missing) == set(MISSING)
    fixtures = []
    secret = scalar(0)
    key, proof = Eth.SkToPk(secret), Eth.PopProve(secret)
    assert Eth.PopVerify(key, proof)
    fixtures.append(dict(function='verifyEthereumProof', suffix='verify_ethereum_proof',
                         inputs=dict(key=key, proof=proof), expected=b'\x00\x01',
                         notes='One valid Ethereum POP proof for a deterministic full-width scalar-derived key; key/proof decoding, subgroup validation, hash-to-curve and verification all measured.',
                         oracle='py_ecc 8.0.0 G2ProofOfPossession SkToPk/PopProve/PopVerify; proof generated and independently verified.'))
    factors = [scalar(i) for i in range(1, 5)]
    for group, base, identity in [(1, G1, Z1), (2, G2, Z2)]:
        points = [multiply(base, factor) for factor in factors]
        expected_point = reduce(add, points, identity)
        assert encode(expected_point, group) == encode(multiply(base, sum(factors) % curve_order), group)
        fixtures.append(dict(function=f'g{group}Aggregate', suffix=f'g{group}_aggregate_n4',
                             inputs=dict(points=b''.join(encode(point, group) for point in points)),
                             expected=b'\x00' + encode(expected_point, group),
                             notes='Four distinct nonidentity subgroup points derived from dense 255-bit public scalars; complete packed-input validation, subgroup checks, group sum and compressed output are inside timing.',
                             oracle='py_ecc 8.0.0 pointwise sum cross-checked with generator multiplication by sum of four full-width point factors mod r.'))
    outputs = {}
    cases = []
    retained = []
    for fixture in fixtures:
        retained.append(dict(function=fixture['function'], inputs={name: value.hex() for name, value in fixture['inputs'].items()},
                             expected_hex=fixture['expected'].hex(), oracle=fixture['oracle']))
        for implementation in (['fast', 'mops'] if fixture['function'] == 'g1Aggregate' else ['fast']):
            comparison = 'api_bls12_381_' + fixture['suffix']
            name = comparison + '_' + implementation
            path = HERE / 'cases' / name / 'main.mo'
            outputs[path] = actor(fixture['function'], fixture['inputs'], fixture['expected'], implementation)
            cases.append(dict(name=name, family='bls12-381', api_function=fixture['function'],
                              implementation=implementation, comparison=comparison,
                              plugins=['bls12-381'] if implementation == 'fast' else [],
                              source=path.relative_to(BENCH).as_posix(), expected_hex=fixture['expected'].hex(),
                              operations_per_sample=1, benchmark_kind='exact-api' if fixture['function'] == 'g1Aggregate' else 'absolute-only',
                              notes=fixture['notes'] + (' Pure Motoko adapter uses Mops compressed G1 decoding plus explicit subgroup checks; Blob conversion and compressed encoding are measured.' if implementation == 'mops' else ''),
                              adapter_description='decompress_g1 + g1_subgroup_check + g1_add fold + compressed encoding' if implementation == 'mops' else '',
                              fixture_provenance=fixture['oracle'] + ' Retained in round2/api-curves/bls/fixtures.json.'))
    adapter_descriptions = {
        'validateG1': 'decompress_g1 + g1_subgroup_check + compressed encoding',
        'g1Add': 'decompress_g1 + g1_subgroup_check + g1_add + compressed encoding',
        'g1Mul': 'decompress_g1 + g1_subgroup_check + canonical scalar decode + g1_mul + compressed encoding',
        'g1Msm': 'packed point/scalar decode + canonical checks + g1_subgroup_check + g1_msm + compressed encoding',
        'mapToG1': 'canonical field-byte decode + map_fp_to_g1 + compressed encoding',
        'mapToG2': 'canonical real/imaginary field-byte decode + map_fp2_to_g2 + compressed encoding',
    }
    suffixes = {'validateG1': 'validate_g1', 'g1Add': 'g1_add', 'g1Mul': 'g1_mul',
                'g1Msm': 'g1_msm_n8', 'mapToG1': 'map_to_g1', 'mapToG2': 'map_to_g2'}
    for fixture, inputs, expected in counterpart_fixtures():
        function, plugin = fixture['function'], fixture['fast_case']
        name = 'api_bls12_381_' + suffixes[function] + '_mops'
        path = HERE / 'cases' / name / 'main.mo'
        outputs[path] = actor(function, inputs, expected, 'mops', fixture['wire'])
        cases.append(dict(name=name, family='bls12-381', api_function=function,
                          implementation='mops', comparison=plugin['comparison'], plugins=[],
                          matching_plugin_case=plugin['name'], adapter_description=adapter_descriptions[function],
                          source=path.relative_to(BENCH).as_posix(), expected_hex=expected.hex(),
                          operations_per_sample=1, benchmark_kind='exact-api',
                          notes='Same immutable input and output bytes as ' + plugin['name'] + '. All Blob conversion, point/field/scalar validation, arithmetic and compressed output encoding are measured. Result storage/unwrapping matches the selected plugin workload.',
                          fixture_provenance='Independent py_ecc 8.0.0 verifies this exact retained fixture using point arithmetic or RFC9380 map plus cofactor clearing. Source/input snapshots: round2/api-curves/bls/selected-counterparts.json.'))
        retained.append(dict(function=function, inputs={name: value.hex() for name, value in inputs.items()},
                             expected_hex=expected.hex(), matching_plugin_case=plugin['name'],
                             oracle='Independent py_ecc 8.0.0 exact-output verification; wire=' + fixture['wire']))
