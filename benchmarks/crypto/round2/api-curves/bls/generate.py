def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def blob(data):
    return '"' + ''.join('\\%02x' % byte for byte in data) + '"'


def encode(point, group):
    compressed = compress_G1(point) if group == 1 else compress_G2(point)
    return b''.join(value.to_bytes(48, 'big') for value in ([compressed] if group == 1 else compressed))


def scalar(index):
    value = hashlib.sha512(b'motoko-api-bls-fixture/' + bytes([index])).digest()
    return (1 << 254) + int.from_bytes(value, 'big') % (curve_order - (1 << 254))


MOPS_AGGREGATE = '''
  // Entire adapter is measured: same packed compressed input, checks and output.
  func compressedG1(point : M.G1Point) : Blob {
    if (M.g1_is_inf(point)) return Prim.arrayToBlob(Prim.Array_tabulate<Nat8>(48, func(i) {
      if (i == 0) 0xc0 else 0
    }));
    let (x, y) = M.g1_to_affine(point);
    let bytes = Prim.Array_tabulate<Nat8>(48, func(i) {
      Prim.natToNat8((x / (256 ** (47 - i))) % 256)
    });
    Prim.arrayToBlob(Prim.Array_tabulate<Nat8>(48, func(i) {
      if (i == 0) bytes[i] | 0x80 | (if (y > M.P / 2) 0x20 else 0) else bytes[i]
    }))
  };
  func aggregate(input : Blob) : Result<Blob> {
    if (input.size() % 48 != 0) return #err(#invalidLength);
    let count = input.size() / 48;
    if (count > 128) return #err(#tooManyItems);
    let bytes = Prim.blobToArray(input);
    var sum = M.G1_INF;
    var i = 0;
    while (i < count) {
      let encoded = Prim.Array_tabulate<Nat8>(48, func(j) { bytes[i * 48 + j] });
      let ?point = M.decompress_g1(encoded) else return #err(#invalidPoint);
      if (not M.g1_subgroup_check(point)) return #err(#invalidPoint);
      sum := M.g1_add(sum, point);
      i += 1;
    };
    #ok(compressedG1(sum))
  };
'''


def actor(function, inputs, expected, implementation, wire='tagged'):
    is_bool = function == 'verifyEthereumProof'
    typ = 'Bool' if is_bool else 'Blob'
    imported = 'import B "mo:fast/BLS12381";' if implementation == 'fast' else 'import M "mo:bls12-381";'
    declarations = '\n  '.join(f'transient let {name} : Blob = {blob(value)};' for name, value in inputs.items())
    error_cases = '\n      '.join(f'case (#{error}) {blob(bytes([255, index + 1]))};'
                                   for index, error in enumerate(ERRORS))
    normalize = ('switch (result) { case (#ok(true)) "\\00\\01"; case (#ok(false)) "\\00\\00"; case (#err(error)) errorBytes(error) }'
                 if is_bool else
                 'switch (result) { case (#ok(value)) successBytes(value); case (#err(error)) errorBytes(error) }')
    called = 'B.' + function if implementation == 'fast' else 'aggregate' if function == 'g1Aggregate' else CALLS[function]
    helpers = '' if implementation == 'fast' else MOPS_AGGREGATE if function == 'g1Aggregate' else COMMON + ADAPTERS[function]
    result_type, initial = f'Result<{typ}>', '#err(#invalidArgument)'
    operation = f'result := {called}({", ".join(inputs)});'
    if wire == 'raw':
        assert typ == 'Blob'
        result_type, initial, normalize = 'Blob', '""', 'result'
        operation = f'let #ok(value) = {called}({", ".join(inputs)}) else Prim.trap("unexpected API error"); result := value;'
    return f'''// Generated by round2/api-curves/bls/generate.py. Do not edit.
import Prim "mo:prim";
{imported}
persistent actor {{
  type Error = {{ {'; '.join('#' + error for error in ERRORS)} }};
  type Result<T> = {{ #ok : T; #err : Error }};
  type Measurement = {{ instructions : Nat64; allocated : Nat; reclaimed : Nat; outputSize : Nat }};
  transient var result : {result_type} = {initial};
  {declarations}
  {helpers}
  func errorBytes(error : Error) : Blob {{
    switch (error) {{
      {error_cases}
    }}
  }};
  func successBytes(value : Blob) : Blob {{
    let bytes = Prim.blobToArray(value);
    Prim.arrayToBlob(Prim.Array_tabulate<Nat8>(bytes.size() + 1, func(i) {{
      if (i == 0) 0 else bytes[i - 1]
    }}))
  }};
  public func configure() : async () {{ result := {initial} }};
  public func run() : async Measurement {{
    let allocatedBefore = Prim.rts_total_allocation();
    let reclaimedBefore = Prim.rts_reclaimed();
    let start = Prim.performanceCounter(0);
    {operation}
    let stop = Prim.performanceCounter(0);
    let allocatedAfter = Prim.rts_total_allocation();
    let reclaimedAfter = Prim.rts_reclaimed();
    {{ instructions = stop - start; allocated = allocatedAfter - allocatedBefore;
       reclaimed = reclaimedAfter - reclaimedBefore; outputSize = {len(expected)} }}
  }};
  public query func bytesResult() : async Blob {{
    let actual : Blob = {normalize};
    assert actual == {blob(expected)};
    actual
  }};
}}
'''


