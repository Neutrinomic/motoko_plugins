#!/usr/bin/env python3
"""Closest supplied-nonce ECDSA baselines; intentionally unequal RFC6979 contracts."""
import hashlib
import importlib.util
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
BENCH = HERE.parents[2]
ORACLE = BENCH / 'generate-curves.py'
spec = importlib.util.spec_from_file_location('independent_curve_oracle', ORACLE)
oracle = importlib.util.module_from_spec(spec)
spec.loader.exec_module(oracle)


def blob(value):
    return '"' + ''.join('\\%02x' % b for b in value) + '"'


def actor(family, nonce, expected):
    kind = oracle.CURVES[family]['kind']
    serialization = ('E.Signature(signature.original_r, '
                     '(if (signature.original_s > curve.params.r / 2) curve.params.r - signature.original_s else signature.original_s), '
                     'curve).toBytes(#raw)'
                     if family == 'secp256k1' else 'signature.toBytes(#raw)')
    return f'''// Generated by round2/api-curves/closest-signing/generate.py. Do not edit.
// Different contract: supplied nonce is independently prepared before the measured call.
import Prim "mo:prim";
import E "mo:ecdsa";
persistent actor {{
  type Result<T> = {{#ok : T; #err : Text}};
  transient let curve = E.Curve(#{kind});
  transient let secret : Blob = {blob(oracle.SECRET.to_bytes(32, 'big'))};
  transient let digest : Blob = {blob(oracle.DIGEST)};
  transient let preparedNonce : Blob = {blob(nonce.to_bytes(32, 'big'))};
  transient var result : Blob = "";
  func signPrepared(secret : Blob, digest : Blob, nonce : Blob) : Result<Blob> {{
    if (secret.size() != 32) return #err("invalid secret length");
    let key = switch (E.privateKeyFromBytes(secret.vals(), #raw({{curve}}))) {{
      case (#err(error)) return #err(error); case (#ok(value)) value;
    }};
    if (digest.size() != 32) return #err("invalid digest length");
    if (nonce.size() != 32) return #err("invalid prepared nonce length");
    switch (key.signHashed(digest.vals(), nonce.vals())) {{
      case (#err(error)) #err(error);
      case (#ok(signature)) #ok(Prim.arrayToBlob({serialization}));
    }}
  }};
  public func configure() : async () {{}};
  public func run() : async {{instructions : Nat64; allocated : Nat; reclaimed : Nat; outputSize : Nat}} {{
    let allocatedBefore = Prim.rts_total_allocation();
    let reclaimedBefore = Prim.rts_reclaimed();
    let start = Prim.performanceCounter(0);
    let #ok(value) = signPrepared(secret, digest, preparedNonce)
      else Prim.trap("unexpected supplied-nonce ECDSA error");
    result := value;
    let stop = Prim.performanceCounter(0);
    let allocatedAfter = Prim.rts_total_allocation();
    let reclaimedAfter = Prim.rts_reclaimed();
    {{instructions = stop-start; allocated = allocatedAfter-allocatedBefore;
      reclaimed = reclaimedAfter-reclaimedBefore; outputSize = 0}}
  }};
  public query func bytesResult() : async Blob {{
    let actual : Blob = result;
    assert actual == {blob(expected)};
    actual
  }};
}}
'''


def main():
    cases = []; overrides = {}; fixtures = []
    source_rows = {c['name']: c for c in json.loads((BENCH / 'curve-cases/cases.json').read_text())}
    for family, module in [('secp256k1', 'Secp256k1'), ('p256', 'P256')]:
        curve = oracle.CURVES[family]
        nonce = oracle.rfc6979_nonce(oracle.SECRET, oracle.DIGEST, curve['n'])
        assert 0 < nonce < curve['n']
        add = lambda a, b: oracle.ec_add(a, b, curve['p'], curve['a'])
        r = oracle.multiply(curve['g'], nonce, add)[0] % curve['n']
        original_s = ((int.from_bytes(oracle.DIGEST, 'big') + r * oracle.SECRET) *
                      pow(nonce, -1, curve['n'])) % curve['n']
        s = min(original_s, curve['n'] - original_s) if family == 'secp256k1' else original_s
        expected = r.to_bytes(32, 'big') + s.to_bytes(32, 'big')
        plugin_name = family + '_sign_rfc6979_fast'
        assert expected.hex() == source_rows[plugin_name]['expected_hex']
        name = f'api-{family}-signPrehash-prepared-nonce-ecdsa'
        target = HERE / 'cases' / name / 'main.mo'
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(actor(family, nonce, expected))
        note = ('Closest available pure Motoko counterpart has a different API contract: '
                'ecdsa@8.0.1 PrivateKey.signHashed consumes a prepared nonce; the plugin '
                'derives RFC6979/HMAC-SHA256 nonce inside signPrehash. Nonce derivation and '
                '32-byte nonce Blob construction happen offline in the independent Python '
                'oracle and are outside pure timing. Nonce iterator creation, byte decoding '
                'and reduction inside signHashed are measured, as are secret decoding/range '
                'validation, digest-length validation, ECDSA arithmetic, compact signature '
                'serialization and Blob construction. Reusable curve construction is outside. '
                'No equal-contract speedup is asserted. Pure scalar multiplication is '
                'variable-time; no equivalent side-channel property is asserted. ')
        note += ('Secp256k1 output explicitly serializes original R and min(original S,n-original S) to match native low-S.'
                 if family == 'secp256k1' else
                 'P256 output serializes Signature.original_r/original_s via toBytes(#raw), '
                 'preserving RFC6979 S exactly.')
        cases.append(dict(name=name, family=family, implementation='ecdsa-prepared-nonce',
                          comparison=f'{family}_sign_rfc6979', plugins=[],
                          source=target.relative_to(BENCH).as_posix(), expected_hex=expected.hex(),
                          operations_per_sample=1, notes=note, benchmark_kind='closest-different-contract',
                          footnote='ECDSA-prepared-nonce', footnote_id='ECDSA-prepared-nonce',
                          equivalent_api_contract=False))
        overrides[f'{module}.signPrehash'] = dict(
            native_case=dict(name=name, implementation='ecdsa-prepared-nonce'),
            plugin_case=dict(name=plugin_name, implementation='fast'),
            counterpart_api='E.privateKeyFromBytes(#raw) -> PrivateKey.signHashed(digest, preparedNonce) -> Signature.toBytes(#raw)',
            notes=note, footnote='ECDSA-prepared-nonce', footnote_id='ECDSA-prepared-nonce',
            equivalent_api_contract=False)
        fixtures.append(dict(family=family, secret_hex=oracle.SECRET.to_bytes(32, 'big').hex(),
                             digest_hex=oracle.DIGEST.hex(), nonce_hex=nonce.to_bytes(32, 'big').hex(),
                             original_s_hex=original_s.to_bytes(32, 'big').hex(), expected_hex=expected.hex()))
    (HERE / 'cases.json').write_text(json.dumps(cases, indent=2) + '\n')
    (HERE / 'override.json').write_text(json.dumps(overrides, indent=2) + '\n')
    (HERE / 'fixtures.json').write_text(json.dumps(dict(
        oracle_source=ORACLE.relative_to(BENCH).as_posix(),
        oracle_sha256=hashlib.sha256(ORACLE.read_bytes()).hexdigest(),
        generator_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        expected_origin='Independent RFC6979 Python HMAC + affine arithmetic; matched preexisting fixture, never native outputs.',
        cases=fixtures), indent=2) + '\n')
    print('Generated two explicitly unequal-contract supplied-nonce signing counterparts')


if __name__ == '__main__':
    main()
