#!/usr/bin/env python3
"""Closest pure-Motoko G2 comparisons with explicitly different wire formats."""
import argparse
import hashlib
import json
from pathlib import Path

import py_ecc
from py_ecc.bls.g2_primitives import subgroup_check
from py_ecc.bls.point_compression import compress_G2, decompress_G2
from py_ecc.optimized_bls12_381 import Z2, add, normalize

HERE = Path(__file__).resolve().parent
BENCH = HERE.parents[2]
ERRORS = ['invalidLength', 'invalidPoint', 'invalidScalar', 'invalidField',
          'tooManyItems', 'emptyBatch', 'identity', 'invalidProof',
          'duplicateMessage', 'invalidArgument']
CONTRACT = ('Closest mathematical operation with different input wire formats: plugin consumes canonical '
            '96-byte IETF compressed G2 points; pure Motoko consumes canonical 256-byte EIP-2537 '
            'uncompressed G2 points (real then imaginary fields with 16-byte zero padding per field). '
            'Both validate curve/subgroup membership and return the same canonical compressed output. '
            'Compressed decoding also reconstructs y using a field square root; the uncompressed decoder '
            'does not perform that work. Input conversion between formats is independently prepared '
            'outside timing; timed pure code starts from its uncompressed Blob and includes Blob-to-array '
            'conversion, point validation, optional summation, compressed output and Result construction. '
            'Any ratio describes these explicitly different contracts, not equivalent API performance.')


def blob(data):
    return '"' + ''.join('\\%02x' % byte for byte in data) + '"'


def compressed(point):
    return b''.join(value.to_bytes(48, 'big') for value in compress_G2(point))


def uncompressed(point):
    x, y = normalize(point)
    return b''.join(int(value).to_bytes(64, 'big') for coordinate in (x, y) for value in coordinate.coeffs)


def actor(data, aggregate, expected):
    errors = '\n      '.join(f'case (#{error}) {blob(bytes([255, i + 1]))};' for i, error in enumerate(ERRORS))
    operation = '''
    if (input.size() % 256 != 0) return #err(#invalidLength);
    let count = input.size() / 256;
    if (count > 128) return #err(#tooManyItems);
    let bytes = Prim.blobToArray(input);
    var sum = M.G2_INF;
    var i = 0;
    while (i < count) {
      let ?point = M.decode_g2(bytes, i * 256) else return #err(#invalidPoint);
      sum := M.g2_add(sum, point);
      i += 1;
    };
    #ok(encodeG2(sum))''' if aggregate else '''
    if (input.size() != 256) return #err(#invalidLength);
    let ?point = M.decode_g2(Prim.blobToArray(input), 0) else return #err(#invalidPoint);
    #ok(encodeG2(point))'''
    return f'''// Generated by round2/api-curves/closest/generate.py.
// Closest comparison: pure input is EIP-2537 uncompressed, plugin input is IETF compressed.
import Prim "mo:prim";
import M "mo:bls12-381";
persistent actor {{
  type Error = {{ {'; '.join('#' + error for error in ERRORS)} }};
  type Result<T> = {{ #ok : T; #err : Error }};
  type Measurement = {{ instructions : Nat64; allocated : Nat; reclaimed : Nat; outputSize : Nat }};
  transient let input : Blob = {blob(data)};
  transient var result : Result<Blob> = #err(#invalidArgument);
  func putField(bytes : [var Nat8], offset : Nat, value : Nat) {{
    var remaining = value;
    var i = 48;
    while (i > 0) {{ i -= 1; bytes[offset + i] := Prim.natToNat8(remaining % 256); remaining /= 256 }};
  }};
  func encodeG2(point : M.G2Point) : Blob {{
    let bytes = Prim.Array_init<Nat8>(96, 0);
    if (M.g2_is_inf(point)) {{ bytes[0] := 0xc0 }} else {{
      let (x, y) = M.g2_to_affine(point);
      putField(bytes, 0, x.1); putField(bytes, 48, x.0);
      let sign = y.1 > M.P / 2 or (y.1 == 0 and y.0 > M.P / 2);
      bytes[0] := bytes[0] | 0x80 | (if (sign) 0x20 else 0);
    }};
    Prim.arrayMutToBlob(bytes)
  }};
  func operation() : Result<Blob> {{{operation}
  }};
  public func configure() : async () {{ result := #err(#invalidArgument) }};
  public func run() : async Measurement {{
    let allocatedBefore = Prim.rts_total_allocation();
    let reclaimedBefore = Prim.rts_reclaimed();
    let start = Prim.performanceCounter(0);
    result := operation();
    let stop = Prim.performanceCounter(0);
    let allocatedAfter = Prim.rts_total_allocation();
    let reclaimedAfter = Prim.rts_reclaimed();
    {{ instructions = stop - start; allocated = allocatedAfter - allocatedBefore;
       reclaimed = reclaimedAfter - reclaimedBefore; outputSize = {len(expected)} }}
  }};
  func errorBytes(error : Error) : Blob {{
    switch (error) {{
      {errors}
    }}
  }};
  public query func bytesResult() : async Blob {{
    let actual : Blob = switch (result) {{
      case (#err(error)) errorBytes(error);
      case (#ok(value)) {{
        let bytes = Prim.blobToArray(value);
        Prim.arrayToBlob(Prim.Array_tabulate<Nat8>(bytes.size() + 1, func(i) {{
          if (i == 0) 0 else bytes[i - 1]
        }}))
      }};
    }};
    assert actual == {blob(expected)};
    actual
  }};
}}
'''


def generate(check):
    assert py_ecc.__version__ == '8.0.0'
    selected = json.loads((HERE / 'inputs.json').read_text())
    outputs, cases, fixtures, overrides = {}, [], [], {}
    for item in selected:
        aggregate = item['function'] == 'g2Aggregate'
        packed = bytes.fromhex(item['input_compressed_hex'])
        count = 4 if aggregate else 1
        assert len(packed) == count * 96
        points = []
        for at in range(0, len(packed), 96):
            raw = packed[at:at + 96]
            point = decompress_G2(tuple(int.from_bytes(raw[i:i+48], 'big') for i in (0, 48)))
            assert subgroup_check(point) and compressed(point) == raw
            points.append(point)
        raw = b''.join(map(uncompressed, points))
        assert len(raw) == count * 256
        output = Z2
        for point in points:
            output = add(output, point)
        expected = b'\x00' + compressed(output)
        assert expected.hex() == item['plugin_case']['expected_hex']
        name = 'closest_bls12_381_' + ('g2_aggregate_n4' if aggregate else 'validate_g2') + '_mops'
        target = HERE / 'cases' / name / 'main.mo'
        outputs[target] = actor(raw, aggregate, expected)
        cases.append(dict(name=name, family='bls12-381', implementation='mops', plugins=[],
                          comparison=item['plugin_case']['comparison'], api_function=item['function'],
                          matching_plugin_case=item['plugin_case']['name'], source=target.relative_to(BENCH).as_posix(),
                          expected_hex=expected.hex(), operations_per_sample=1, benchmark_kind='closest-different-wire',
                          notes=CONTRACT, fixture_provenance='py_ecc 8.0.0 independently decodes selected compressed points, checks subgroup/recompression, converts affine coordinates to EIP-2537 form and checks the same aggregate result. Retained inputs/provenance in round2/api-curves/closest/.'))
        overrides[item['id']] = dict(id=item['id'], native_case=dict(name=name, implementation='mops'),
                                    native_source=target.relative_to(BENCH).as_posix(),
                                    plugin_case=dict(name=item['plugin_case']['name'], implementation='fast'),
                                    notes=CONTRACT, contract='closest-different-wire', equivalent_api_contract=False)
        fixtures.append(dict(api=item['id'], count=count, original_compressed_hex=packed.hex(),
                             pure_uncompressed_hex=raw.hex(), expected_hex=expected.hex(),
                             independent_subgroup_checks=[True] * count, independently_verified=True))
    assert len(cases) == len(overrides) == 2
    dumps = lambda value: json.dumps(value, indent=2, sort_keys=True) + '\n'
    outputs[HERE / 'cases.json'] = dumps(cases)
    outputs[HERE / 'override.json'] = dumps(overrides)
    outputs[HERE / 'fixtures.json'] = dumps(fixtures)
    root = Path(py_ecc.__file__).resolve().parent
    outputs[HERE / 'provenance.json'] = dumps(dict(
        oracle='Ethereum py_ecc', oracle_version=py_ecc.__version__,
        oracle_source_sha256={path.relative_to(root).as_posix(): hashlib.sha256(path.read_bytes()).hexdigest() for path in sorted(root.rglob('*.py'))},
        generator_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        input_sha256=hashlib.sha256((HERE / 'inputs.json').read_bytes()).hexdigest(),
        generated_sha256={path.relative_to(HERE).as_posix(): hashlib.sha256(text.encode()).hexdigest() for path, text in outputs.items()},
        cases=2, contract=CONTRACT,
    ))
    for path, text in outputs.items():
        if check:
            assert path.read_text() == text, f'Generated artifact mismatch: {path}'
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    print(('Checked' if check else 'Generated') + ' 2 closest pure G2 comparisons with explicit different-wire contracts')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    generate(parser.parse_args().check)
