#!/usr/bin/env python3
"""Empty BLS group operations: canonical infinity is C0 followed by zeros.

No cryptographic implementation is consulted for these mathematical identities.
All output tagging, error interpretation and checking remain outside measurement.
"""
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
BENCH = HERE.parents[2]
ERRORS = ['invalidLength', 'invalidPoint', 'invalidScalar', 'invalidField',
          'tooManyItems', 'emptyBatch', 'identity', 'invalidProof',
          'duplicateMessage', 'invalidArgument']


def blob(data):
    return '"' + ''.join('\\%02x' % b for b in data) + '"'


def actor(function, group):
    expected = b'\x00\xc0' + bytes((48 if group == 1 else 96) - 1)
    errors = '\n      '.join(f'case (#{error}) {blob(bytes([255, index + 1]))};'
                             for index, error in enumerate(ERRORS))
    arguments = 'points, scalars' if function.endswith('Msm') else 'points'
    scalars = 'transient let scalars : Blob = "";' if function.endswith('Msm') else ''
    return f'''// Generated by round2/api-curves/bls-empty/generate.py. Do not edit.
import Prim "mo:prim";
import B "mo:fast/BLS12381";
persistent actor {{
  type Measurement = {{ instructions : Nat64; allocated : Nat; reclaimed : Nat; outputSize : Nat }};
  transient var result : B.Result<Blob> = #err(#invalidArgument);
  transient let points : Blob = "";
  {scalars}
  func errorBytes(error : B.Error) : Blob {{
    switch (error) {{
      {errors}
    }}
  }};
  func successBytes(value : Blob) : Blob {{
    let bytes = Prim.blobToArray(value);
    Prim.arrayToBlob(Prim.Array_tabulate<Nat8>(bytes.size() + 1, func(i) {{
      if (i == 0) 0 else bytes[i - 1]
    }}))
  }};
  public func configure() : async () {{ result := #err(#invalidArgument) }};
  public func run() : async Measurement {{
    let allocatedBefore = Prim.rts_total_allocation();
    let reclaimedBefore = Prim.rts_reclaimed();
    let start = Prim.performanceCounter(0);
    result := B.{function}({arguments});
    let stop = Prim.performanceCounter(0);
    let allocatedAfter = Prim.rts_total_allocation();
    let reclaimedAfter = Prim.rts_reclaimed();
    {{ instructions = stop - start; allocated = allocatedAfter - allocatedBefore;
       reclaimed = reclaimedAfter - reclaimedBefore; outputSize = {len(expected)} }}
  }};
  public query func bytesResult() : async Blob {{
    let actual : Blob = switch (result) {{ case (#ok(value)) successBytes(value); case (#err(error)) errorBytes(error) }};
    assert actual == {blob(expected)};
    actual
  }};
}}
''', expected


def main():
    cases = []
    for function, group in [('g2Msm', 2), ('g1Aggregate', 1), ('g2Aggregate', 2)]:
        name = f'api_bls12_381_{function}_empty_fast'
        target = HERE/'cases'/name/'main.mo'
        target.parent.mkdir(parents=True, exist_ok=True)
        source, expected = actor(function, group)
        target.write_text(source)
        cases.append(dict(name=name, family='bls12-381', implementation='fast',
                          api_function=function, comparison=name.removesuffix('_fast'),
                          plugins=['bls12-381'], source=target.relative_to(BENCH).as_posix(),
                          expected_hex=expected.hex(), operations_per_sample=1,
                          notes='Empty packed Blob inputs. One direct public operation and Result storage are measured. Result tagging and checking are outside measurement.',
                          fixture_provenance='Empty group sum/MSM is infinity. IETF compressed infinity is C0 followed by 47 (G1) or 95 (G2) zero bytes, prefixed by 00 for #ok.',
                          source_sha256=hashlib.sha256(source.encode()).hexdigest()))
    (HERE/'cases.json').write_text(json.dumps(cases, indent=2)+'\n')
    print('Generated 3 empty BLS operation actors')


if __name__ == '__main__':
    main()
