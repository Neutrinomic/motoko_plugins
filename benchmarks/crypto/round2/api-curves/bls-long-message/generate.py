#!/usr/bin/env python3
"""Independent py_ecc8 oracle for aggregate-verification long-message hotspots."""
import argparse
import hashlib
import json
from pathlib import Path

import py_ecc
from py_ecc.bls import G2ProofOfPossession as Eth

HERE = Path(__file__).resolve().parent
BENCH = HERE.parents[2]
COUNT = 16
SEED = b'motoko-bls-long-message-v1/'
ERRORS = ['invalidLength', 'invalidPoint', 'invalidScalar', 'invalidField',
          'tooManyItems', 'emptyBatch', 'identity', 'invalidProof',
          'duplicateMessage', 'invalidArgument']


def blob(data):
    return '"' + ''.join('\\%02x' % byte for byte in data) + '"'


def message(size, index, repeated):
    data = bytearray((position * 17 + 23) % 251 for position in range(size))
    suffix = 0 if repeated else index
    data[-2:] = suffix.to_bytes(2, 'big')
    return bytes(data)


def actor(size, repeated, keys, proofs, signature):
    error_cases = '\n      '.join(f'case (#{error}) {blob(bytes([255, i + 1]))};'
                                   for i, error in enumerate(ERRORS))
    return f'''// Generated by round2/api-curves/bls-long-message/generate.py.
import Prim "mo:prim";
import B "mo:fast/BLS12381";
persistent actor {{
  type Measurement = {{ instructions : Nat64; allocated : Nat; reclaimed : Nat; outputSize : Nat }};
  transient let keys : [Blob] = [{', '.join(map(blob, keys))}];
  transient let proofs : [Blob] = [{', '.join(map(blob, proofs))}];
  transient let signature : Blob = {blob(signature)};
  transient var messages : [Blob] = [];
  transient var result : B.Result<Bool> = #err(#invalidArgument);
  func makeMessage(index : Nat) : Blob {{
    let suffix : Nat = {'0' if repeated else 'index'};
    Prim.arrayToBlob(Prim.Array_tabulate<Nat8>({size}, func(position) {{
      if (position == {size - 2}) Prim.natToNat8(suffix / 256)
      else if (position == {size - 1}) Prim.natToNat8(suffix % 256)
      else Prim.natToNat8((position * 17 + 23) % 251)
    }}))
  }};
  public func configure() : async () {{
    // Every entry receives its own Blob, including repeated equal content.
    messages := Prim.Array_tabulate<Blob>({COUNT}, func(i) {{ makeMessage(i) }});
    result := #err(#invalidArgument);
  }};
  public func run() : async Measurement {{
    let allocatedBefore = Prim.rts_total_allocation();
    let reclaimedBefore = Prim.rts_reclaimed();
    let start = Prim.performanceCounter(0);
    result := B.aggregateVerifyEthereum(keys, proofs, messages, signature);
    let stop = Prim.performanceCounter(0);
    let allocatedAfter = Prim.rts_total_allocation();
    let reclaimedAfter = Prim.rts_reclaimed();
    {{ instructions = stop - start; allocated = allocatedAfter - allocatedBefore;
       reclaimed = reclaimedAfter - reclaimedBefore; outputSize = 2 }}
  }};
  func errorBytes(error : B.Error) : Blob {{
    switch (error) {{
      {error_cases}
    }}
  }};
  public query func bytesResult() : async Blob {{
    let actual : Blob = switch (result) {{
      case (#ok(true)) "\\00\\01";
      case (#ok(false)) "\\00\\00";
      case (#err(error)) errorBytes(error);
    }};
    assert actual == "\\00\\01";
    actual
  }};
}}
'''


def generate(check):
    assert py_ecc.__version__ == '8.0.0'
    from py_ecc.optimized_bls12_381 import curve_order
    secrets = [(1 << 254) + int.from_bytes(hashlib.sha512(SEED + bytes([i])).digest(), 'big') %
               (curve_order - (1 << 254)) for i in range(COUNT)]
    keys = [Eth.SkToPk(secret) for secret in secrets]
    proofs = [Eth.PopProve(secret) for secret in secrets]
    assert len(set(keys)) == COUNT
    proof_checks = [Eth.PopVerify(key, proof) for key, proof in zip(keys, proofs)]
    assert all(proof_checks)
    print('Verified 16 independent key proofs', flush=True)
    cases, fixtures, outputs = [], [], {}
    for size, repeated in [(4096, False), (65536, False), (65536, True)]:
        messages = [message(size, index, repeated) for index in range(COUNT)]
        assert len(set(messages)) == (1 if repeated else COUNT)
        assert len({value[:-2] for value in messages}) == 1
        signatures = [Eth.Sign(secret, value) for secret, value in zip(secrets, messages)]
        signature = Eth.Aggregate(signatures)
        verified = Eth.AggregateVerify(keys, messages, signature)
        assert verified
        name = f'api_bls12_381_aggregate_ethereum_long_{"repeated" if repeated else "distinct"}_n16_bytes{size}_fast'
        target = HERE / 'cases' / name / 'main.mo'
        outputs[target] = actor(size, repeated, keys, proofs, signature)
        notes = (f'16 distinct full-width-scalar keys and valid PoPs; each message is {size} bytes. ' +
                 ('All 16 separately allocated messages have identical content.' if repeated else
                  f'Messages share the first {size - 1} bytes and differ only in the final byte (two-byte big-endian index suffix).') +
                 ' configure builds all messages outside timing. Complete aggregateVerifyEthereum, including PoPs, message scanning/hash-to-curve and pairing, is measured.')
        cases.append(dict(name=name, family='bls12-381', implementation='fast', api_function='aggregateVerifyEthereum',
                          comparison=name.removesuffix('_fast'), plugins=['bls12-381'],
                          source=target.relative_to(BENCH).as_posix(), expected_hex='0001',
                          operations_per_sample=1, benchmark_kind='absolute-only', notes=notes,
                          fixture_provenance='Ethereum py_ecc 8.0.0 SkToPk/PopProve/PopVerify/Sign/Aggregate/AggregateVerify. Deterministic key seeds, proofs, signatures, message recipe and SHA256 digests retained in round2/api-curves/bls-long-message/fixtures.json.'))
        fixtures.append(dict(name=name, count=COUNT, message_size=size, repeated=repeated,
                             key_seed_hex=SEED.hex(), secret_keys_hex=[secret.to_bytes(32, 'big').hex() for secret in secrets],
                             keys_hex=[key.hex() for key in keys], proofs_hex=[proof.hex() for proof in proofs],
                             message_recipe='For byte positions below size-2: (position * 17 + 23) mod 251. Last two bytes are BE(index), or BE(0) when repeated.',
                             message_sha256=[hashlib.sha256(value).hexdigest() for value in messages],
                             individual_signature_hex=[value.hex() for value in signatures], aggregate_signature_hex=signature.hex(),
                             independent_pop_verify=proof_checks, independent_aggregate_verify=verified, expected_hex='0001'))
        print(f'Verified {name}', flush=True)
    dumps = lambda value: json.dumps(value, indent=2, sort_keys=True) + '\n'
    outputs[HERE / 'cases.json'] = dumps(cases)
    outputs[HERE / 'fixtures.json'] = dumps(fixtures)
    oracle_root = Path(py_ecc.__file__).resolve().parent
    outputs[HERE / 'provenance.json'] = dumps(dict(
        oracle='Ethereum py_ecc', oracle_version=py_ecc.__version__,
        oracle_source_sha256={path.relative_to(oracle_root).as_posix(): hashlib.sha256(path.read_bytes()).hexdigest()
                              for path in sorted(oracle_root.rglob('*.py'))},
        generator_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        generated_sha256={path.relative_to(HERE).as_posix(): hashlib.sha256(text.encode()).hexdigest() for path, text in outputs.items()},
        cases=3, oracle_pop_checks=16, oracle_aggregate_checks=3,
        result_encoding='0001=ok(true),0000=ok(false),ff then unique 1-based Error index for every error.',
        measurement='Message construction in configure, Result assignment of one complete aggregateVerifyEthereum call inside timing, Result serialization/assertions in bytesResult outside timing.',
    ))
    for path, text in outputs.items():
        if check:
            assert path.read_text() == text, f'Generated fixture differs: {path}'
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    print(('Checked' if check else 'Generated') + ' 3 long-message BLS actors', flush=True)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    generate(parser.parse_args().check)
