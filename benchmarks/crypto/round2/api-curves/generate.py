#!/usr/bin/env python3
"""Direct public aliases omitted by the workload-oriented curve benchmarks.

This generator reads the immutable, independently derived round-two fixture
snapshot. It never rewrites the original cases or obtains an oracle from a
plugin. Public aliases each get their own measured call and report row.
"""
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
BENCH = HERE.parents[1]
ROOT = BENCH.parents[1]
FIXTURES = HERE.parent / 'curve-hotspots/fixtures/curve-inputs.json'


def blob(value):
    return '"' + ''.join('\\%02x' % byte for byte in bytes.fromhex(value)) + '"'


def actor(module, inputs, expression, expected):
    declarations = '\n  '.join(f'transient let {name} : Blob = {blob(value)};' for name, value in inputs.items())
    return f'''// Generated by round2/api-curves/generate.py. Do not edit.
import Prim "mo:prim";
import C "mo:fast/{module}";
persistent actor {{
  {declarations}
  transient var result : C.Result<Blob> = #ok("");
  public func configure() : async () {{}};
  public func run() : async {{instructions : Nat64; allocated : Nat; reclaimed : Nat; outputSize : Nat}} {{
    let allocatedBefore = Prim.rts_total_allocation();
    let reclaimedBefore = Prim.rts_reclaimed();
    let start = Prim.performanceCounter(0);
    result := {expression};
    let stop = Prim.performanceCounter(0);
    let allocatedAfter = Prim.rts_total_allocation();
    let reclaimedAfter = Prim.rts_reclaimed();
    {{instructions = stop-start; allocated = allocatedAfter-allocatedBefore;
      reclaimed = reclaimedAfter-reclaimedBefore; outputSize = 0}}
  }};
  public query func bytesResult() : async Blob {{
    let #ok(value) = result else Prim.trap("unexpected curve error");
    assert value == {blob(expected)};
    value
  }};
}}
'''


def main():
    fixtures = {f['name']: f for f in json.loads(FIXTURES.read_text())['cases']}
    cases, provenance = [], []
    for family, module in [('secp256k1', 'Secp256k1'), ('p256', 'P256')]:
        specifications = [('derivePublicKey', 'public-key-uncompressed', 'convert-compressed-to-compressed', 'C.derivePublicKey(secret)')]
        if family == 'secp256k1':
            specifications += [
                ('compressPublicKey', 'convert-uncompressed-to-compressed', 'convert-uncompressed-to-compressed', 'C.compressPublicKey(key)'),
                ('decompressPublicKey', 'convert-compressed-to-uncompressed', 'convert-compressed-to-uncompressed', 'C.decompressPublicKey(key)'),
            ]
        for function, input_case, expected_case, expression in specifications:
            inputs = fixtures[f'r2-{family}-{input_case}']['inputs']
            expected = fixtures[f'r2-{family}-{expected_case}']['expected_hex']
            name = f'api-{family}-{function}-fast'
            target = HERE / 'cases' / name / 'main.mo'
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(actor(module, inputs, expression, expected))
            cases.append(dict(name=name, family=family, implementation='fast', comparison=f'api-{family}-{function}',
                              plugins=[family], source=target.relative_to(BENCH).as_posix(), expected_hex=expected,
                              operations_per_sample=1,
                              notes='One direct public API call. Blob inputs prepared before measurement; Result matching and output assertion outside measurement.',
                              fixture_provenance='Independent Python affine elliptic-curve arithmetic retained in immutable curve-hotspots fixture snapshot.'))
            provenance.append(dict(name=name, function=function, inputs=inputs, expression=expression,
                                   expected_hex=expected, input_case=f'r2-{family}-{input_case}', expected_case=f'r2-{family}-{expected_case}'))
    (HERE / 'gap-cases.json').write_text(json.dumps(cases, indent=2) + '\n')
    (HERE / 'gap-fixtures.json').write_text(json.dumps(dict(
        source=FIXTURES.relative_to(BENCH).as_posix(), source_sha256=hashlib.sha256(FIXTURES.read_bytes()).hexdigest(),
        cases=provenance), indent=2) + '\n')
    print(f'Generated {len(cases)} direct alias cases')


if __name__ == '__main__':
    main()
