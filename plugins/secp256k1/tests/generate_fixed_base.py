#!/usr/bin/env python3
"""Reproduce canonical fixed-generator constants using integer curve arithmetic."""
from pathlib import Path
import argparse

P = 2**256 - 2**32 - 977
G = (0x79BE667EF9DCBBAC55A06295CE870B07029BFCDB2DCE28D959F2815B16F81798,
     0x483ADA7726A3C4655DA4FBFC0E1108A8FD17B448A68554199C47D08FFB10D4B8)


def add(a, b):
    if a is None: return b
    if b is None: return a
    x, y = a
    u, v = b
    if x == u and (y + v) % P == 0: return None
    slope = ((3*x*x) * pow(2*y, -1, P) if a == b
             else (v-y) * pow(u-x, -1, P)) % P
    z = (slope*slope - x - u) % P
    return z, (slope*(x-z) - y) % P


def source():
    lines = ['// Generated by plugins/secp256k1/tests/generate_fixed_base.py.',
             '// Row i contains [1..8] * 2^(8*i) * G; canonical coordinates.',
             'use super::{AffinePoint, FieldElement};',
             'pub(super) static GENERATOR: [[AffinePoint; 8]; 33] = [']
    base = G
    for _ in range(33):
        lines.append('    [')
        point = base
        for _ in range(8):
            assert (point[1]**2 - point[0]**3 - 7) % P == 0
            coords = [','.join(f'0x{b:02x}' for b in c.to_bytes(32, 'big')) for c in point]
            lines.append('        AffinePoint::new(')
            lines.append(f'            FieldElement::from_bytes_unchecked(&[{coords[0]}]),')
            lines.append(f'            FieldElement::from_bytes_unchecked(&[{coords[1]}])),')
            point = add(point, base)
        lines.append('    ],')
        for _ in range(8): base = add(base, base)
    lines.append('];')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = Path(__file__).resolve().parents[1] / 'runtime/vendor/k256/src/arithmetic/fixed_base_table.rs'
    expected = source()
    if args.check:
        assert target.read_text() == expected
    else:
        target.write_text(expected)
