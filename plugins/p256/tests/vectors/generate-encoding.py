#!/usr/bin/env python3
"""Generate focused P256 encoding answers using OpenSSL, not plugin arithmetic."""
import argparse
import json
from pathlib import Path
import subprocess
import tempfile

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
N = int("ffffffff00000000ffffffffffffffffbce6faada7179e84f3b9cac2fc632551", 16)
P = int("ffffffff00000001000000000000000000000000ffffffffffffffffffffffff", 16)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--openssl", default="openssl")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    def openssl(*arguments, input=None):
        return subprocess.run([args.openssl, *arguments], input=input, capture_output=True)

    def der_pair(r, s):
        with tempfile.TemporaryDirectory() as directory:
            config = Path(directory) / "pair.cnf"
            output = Path(directory) / "pair.der"
            config.write_text(f"asn1=SEQUENCE:pair\n[pair]\nr=INTEGER:{r}\ns=INTEGER:{s}\n")
            result = openssl("asn1parse", "-genconf", str(config), "-out", str(output), "-noout")
            assert result.returncode == 0, result.stderr
            return output.read_bytes()

    def length_value(size):
        # Positive DER INTEGER content length, including a needed sign octet.
        return 1 << (255 if size == 33 else 8 * (size - 1))

    pairs = []
    for length in range(8, 73):
        r_size = min(33, length - 7)
        pairs.append((f"der-length-{length}", length_value(r_size), length_value(length - 6 - r_size)))
    for width in range(1, 33):
        for leading in [0x7f, 0x80]:
            value = leading << (8 * (width - 1))
            pairs.append((f"sign-octet-{width}-{leading:02x}", 1, value))
    for s in [1, N // 2, N // 2 + 1, N - 1]:
        pairs.append((f"normalization-{s:064x}", N - 1, s))
    der = []
    for name, r, s in pairs:
        encoded = der_pair(r, s)
        der.append({"name": name, "compact": f"{r:064x}{s:064x}", "der": encoded.hex(),
                    "normalized": f"{r:064x}{min(s, N - s):064x}"})
    assert {len(bytes.fromhex(v["der"])) for v in der} == set(range(8, 73))

    # OpenSSL's EC decoder supplies curve membership and the expanded Y
    # coordinate. The wrapper supplies only the standard prime256v1 SPKI OIDs.
    algorithm = bytes.fromhex("301306072a8648ce3d020106082a8648ce3d030107")

    def decode(key):
        bit_string = bytes([3, len(key) + 1, 0]) + key
        spki = bytes([0x30, len(algorithm) + len(bit_string)]) + algorithm + bit_string
        result = openssl("ec", "-pubin", "-inform", "DER", "-outform", "DER",
                         "-conv_form", "uncompressed", input=spki)
        if result.returncode:
            return None
        point = result.stdout[-65:]
        assert point[0] == 4
        return point

    sec1 = []
    for x in [0, 1, 2, 3, N - 1, N, N + 1, N + 3, P - 3, P - 2, P - 1, P, P + 1, (1 << 256) - 1]:
        for tag in [2, 3]:
            key = bytes([tag]) + x.to_bytes(32, "big")
            point = decode(key)
            assert x < P or point is None, "oracle accepted a noncanonical field coordinate"
            sec1.append({"name": f"x-{x:064x}-tag-{tag}", "compressed": key.hex(),
                         "uncompressed": point.hex() if point else None})
    data = {"oracle": openssl("version").stdout.decode().strip(), "der": der, "sec1": sec1}

    def blob(value):
        return '"' + ''.join('\\' + value[i:i + 2] for i in range(0, len(value), 2)) + '"'

    motoko = ["// Generated by plugins/p256/tests/vectors/generate-encoding.py using OpenSSL.",
              "module {", "  public let der : [(Blob, Blob, Blob)] = ["]
    for row in der:
        motoko.extend([f"    // {row['name']}", "    (" + ", ".join(blob(row[k]) for k in ["compact", "der", "normalized"]) + "),"])
    motoko.extend(["  ];", "  public let sec1 : [(Blob, ?Blob)] = ["])
    for row in sec1:
        expected = "?" + blob(row["uncompressed"]) if row["uncompressed"] else "null"
        motoko.append(f"    ({blob(row['compressed'])}, {expected}),")
    motoko.extend(["  ];", "};", ""])
    outputs = {HERE / "encoding.json": json.dumps(data, indent=2) + "\n",
               ROOT / "packages/fast/tests/lib/P256EncodingVectors.mo": "\n".join(motoko)}
    for path, contents in outputs.items():
        if args.check:
            assert path.read_text() == contents, f"stale generated fixture: {path}"
        else:
            path.write_text(contents)
    print(json.dumps({"der": len(der), "sec1": len(sec1), "der_lengths": "8..72", "oracle": data["oracle"]}))


if __name__ == "__main__":
    main()
