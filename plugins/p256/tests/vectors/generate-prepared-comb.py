#!/usr/bin/env python3
"""Generate a private P256 verification comb; check all points with OpenSSL.

The selected width-eight format is private to this plugin build.
The matching OCaml layout is emitted together to keep output sizes consistent.
"""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import subprocess

HERE=Path(__file__).resolve().parent
PLUGIN=HERE.parents[1]
spec=importlib.util.spec_from_file_location('comb_reference',HERE/'generate-p256-comb.py')
reference=importlib.util.module_from_spec(spec);spec.loader.exec_module(reference)

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--openssl',default='openssl')
    args=parser.parse_args()
    width=8
    rows=(256+width-1)//width
    basis=[reference.G]
    for _ in range(width-1):
        point=basis[-1]
        for _ in range(rows):point=reference.add(point,point)
        basis.append(point)
    points=[];coefficients=[];words=[]
    prefix=bytes.fromhex('3059301306072a8648ce3d020106082a8648ce3d030107034200')
    for digit in range(1,1<<width):
        point=None;coefficient=0
        for column in range(width):
            if digit>>column&1:
                point=reference.add(point,basis[column]);coefficient+=1<<(rows*column)
        encoded=b'\x04'+point[0].to_bytes(32,'big')+point[1].to_bytes(32,'big')
        secret=bytes.fromhex('30310201010420')+coefficient.to_bytes(32,'big')+bytes.fromhex('a00a06082a8648ce3d030107')
        derived=subprocess.run([args.openssl,'pkey','-inform','DER','-pubout','-outform','DER'],input=secret,capture_output=True,check=True).stdout
        assert derived==prefix+encoded
        row=[]
        for coordinate in point:
            montgomery=coordinate*(1<<256)%reference.P
            row.extend((montgomery>>(64*limb))&((1<<64)-1) for limb in range(4))
        points.append(encoded.hex());coefficients.append(f'{coefficient:064x}');words.append(row)
    odd_words=[];odd_points=[]
    point=reference.G
    twice=reference.add(point,point)
    for index in range(8):
        coefficient=2*index+1
        encoded=b'\x04'+point[0].to_bytes(32,'big')+point[1].to_bytes(32,'big')
        secret=bytes.fromhex('30310201010420')+coefficient.to_bytes(32,'big')+bytes.fromhex('a00a06082a8648ce3d030107')
        derived=subprocess.run([args.openssl,'pkey','-inform','DER','-pubout','-outform','DER'],input=secret,capture_output=True,check=True).stdout
        assert derived==prefix+encoded
        row=[]
        for coordinate in point:
            montgomery=coordinate*(1<<256)%reference.P
            row.extend((montgomery>>(64*limb))&((1<<64)-1) for limb in range(4))
        odd_words.append(row);odd_points.append(encoded.hex())
        point=reference.add(point,twice)
    runtime='// Generated by tests/vectors/generate-prepared-comb.py; do not edit.\n'
    runtime+=f'pub const WIDTH: usize = {width};\npub const ROWS: usize = {rows};\npub const POINTS: usize = {len(words)};\npub const BYTES: usize = POINTS * 64;\n'
    runtime+='pub const GENERATOR: [[u64; 8]; POINTS] = [\n'
    runtime+=''.join('    ['+', '.join(f'0x{word:016x}' for word in row)+'],\n' for row in words)+'];\n'
    runtime+='pub const ODD_GENERATOR: [[u64; 8]; 8] = [\n'
    runtime+=''.join('    ['+', '.join(f'0x{word:016x}' for word in row)+'],\n' for row in odd_words)+'];\n'
    (PLUGIN/'runtime/src/prepared_table.rs').write_text(runtime)
    layout='(* Generated by tests/vectors/generate-prepared-comb.py; do not edit. *)\n'
    layout+=f'let payload_size = {len(words)*64}\n'
    (PLUGIN/'compiler/prepared_layout.ml').write_text(layout)
    report={'width':width,'rows':rows,'points':points,'coefficients':coefficients,'montgomery_words':words,'odd_generator_points':odd_points,'odd_generator_words':odd_words,
            'validated':'Every point matches independent Python arithmetic and OpenSSL exact-scalar multiplication',
            'openssl':subprocess.check_output([args.openssl,'version'],text=True).strip(),
            'generator_sha256':hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
            'runtime_table_sha256':hashlib.sha256(runtime.encode()).hexdigest(),
            'compiler_layout_sha256':hashlib.sha256(layout.encode()).hexdigest()}
    (HERE/'prepared-comb-proof.json').write_text(json.dumps(report,indent=2)+'\n')
    print(f'Generated width{width} / {rows} rows / {len(words)*64} bytes; all OpenSSL checks passed')

if __name__=='__main__':main()
