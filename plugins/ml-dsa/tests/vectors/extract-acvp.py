#!/usr/bin/env python3
"""Pin and extract FIPS 204 ML-DSA-44 external-interface known answers.

Requires only Python's standard library. Upstream data, not the implementation
under test, supplies every expected public key, signature and verification result.
"""
import hashlib
import json
from pathlib import Path
import urllib.request

COMMIT = "975de31eb83d87039ec88934fdc47d8c312b892d"
ROOT = Path(__file__).resolve().parent
SOURCES = {
    "keyGen": "ML-DSA-keyGen-FIPS204",
    "sigGen": "ML-DSA-sigGen-FIPS204-tr1",
    "sigVer": "ML-DSA-sigVer-FIPS204",
}


def extract():
    result = {"sourceCommit": COMMIT, "sources": {}, "keyGen": [], "sigGen": [], "sigVer": []}
    for operation, directory in SOURCES.items():
        url = f"https://raw.githubusercontent.com/usnistgov/ACVP-Server/{COMMIT}/gen-val/json-files/{directory}/internalProjection.json"
        raw = urllib.request.urlopen(url).read()
        result["sources"][operation] = {"url": url, "sha256": hashlib.sha256(raw).hexdigest()}
        data = json.loads(raw)
        for group in data["testGroups"]:
            if group["parameterSet"] != "ML-DSA-44":
                continue
            if operation != "keyGen" and (group["signatureInterface"] != "external" or group["preHash"] != "pure"):
                continue
            if operation == "sigGen" and group["keyFormat"] != "seed":
                continue
            fields = {"keyGen": ["tcId", "seed", "pk"],
                      "sigGen": ["tcId", "seed", "pk", "message", "context", "rnd", "signature"],
                      "sigVer": ["tcId", "pk", "message", "context", "signature", "testPassed", "reason"]}[operation]
            for test in group["tests"]:
                row = {name: test[name] for name in fields if name in test}
                row["tgId"] = group["tgId"]
                if operation == "sigGen":
                    row["deterministic"] = group["deterministic"]
                    row.setdefault("rnd", "00" * 32)
                result[operation].append(row)
    assert [len(result[k]) for k in SOURCES] == [25, 30, 15]
    (ROOT / "acvp-ml-dsa-44.json").write_text(json.dumps(result, indent=2) + "\n")
    return result


def blob(value):
    return '"' + ''.join('\\' + value[i:i+2].lower() for i in range(0, len(value), 2)) + '"'


def motoko(data):
    selected = {"keyGen": [1, 2, 3], "sigGen": [4, 6, 11, 362, 365, 373], "sigVer": list(range(1, 16))}
    lines = ["// Generated by vectors/extract-acvp.py from pinned NIST ACVP answers.",
             "// Public test seeds; never use these seeds for real keys.", "module {",
             "  public type KeyGen = { id : Nat; seed : Blob; publicKey : Blob };",
             "  public type SigGen = { id : Nat; seed : Blob; publicKey : Blob; message : Blob; context : Blob; randomness : Blob; signature : Blob; deterministic : Bool };",
             "  public type SigVer = { id : Nat; publicKey : Blob; message : Blob; context : Blob; signature : Blob; valid : Bool };"]
    for op, ty in [("keyGen", "KeyGen"), ("sigGen", "SigGen"), ("sigVer", "SigVer")]:
        lines.append(f"  public let {op} : [{ty}] = [")
        for row in data[op]:
            if row["tcId"] not in selected[op]:
                continue
            pairs = [f'id = {row["tcId"]}']
            for src, dst in [("seed", "seed"), ("pk", "publicKey"), ("message", "message"), ("context", "context"), ("rnd", "randomness"), ("signature", "signature")]:
                if src in row:
                    pairs.append(f"{dst} = {blob(row[src])}")
            if op == "sigGen": pairs.append(f'deterministic = {str(row["deterministic"]).lower()}')
            if op == "sigVer": pairs.append(f'valid = {str(row["testPassed"]).lower()}')
            lines.append("    { " + "; ".join(pairs) + " },")
        lines.append("  ];")
    lines.append("}")
    (ROOT.parent / "Vectors.mo").write_text("\n".join(lines) + "\n")
    (ROOT / "selected-motoko-cases.json").write_text(json.dumps(selected, indent=2) + "\n")


if __name__ == "__main__":
    motoko(extract())
