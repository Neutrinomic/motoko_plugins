#!/usr/bin/env python3
"""Regenerate compact Bitcoin references with hash-pinned Core v29.0 helpers.

CKDpub answers use private-scalar CKD plus Core's point multiplication, rather
than the production public-point tweak route. Inputs are deterministic test keys.
No production code or installed dependency is used by this oracle.
"""
import argparse
import hashlib
import hmac
import json
from pathlib import Path
import sys
import urllib.request

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
PIN = ROOT / "tests/crypto-audit/bitcoin/oracle-provenance.json"
OUT = ROOT / "packages/fast/tests/lib/BitcoinPropertiesVectors.mo"


def blob(data):
    return '"' + ''.join('\\%02x' % b for b in data) + '"'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cache', type=Path, default=Path('/tmp/bitcoin-base58-audit'))
    args = parser.parse_args()
    pins = json.loads(PIN.read_text())['files']
    for name, pin in pins.items():
        path = args.cache / 'test_framework' / name
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists():
            path.write_bytes(urllib.request.urlopen(pin['url']).read())
        assert hashlib.sha256(path.read_bytes()).hexdigest() == pin['sha256'], name
    sys.path.insert(0, str(args.cache))
    from test_framework.key import ECKey, ORDER
    from test_framework.messages import COutPoint, CTransaction, CTxIn, CTxOut, CTxInWitness, hash256
    from test_framework.script import CScript, LegacySignatureHash, SegwitV0SignatureHash, TaprootSignatureHash

    def public(secret):
        key = ECKey()
        key.set(secret.to_bytes(32, 'big'), True)
        return key.get_pubkey().get_bytes()

    def child(secret, chain, index):
        node = hmac.digest(chain, public(secret) + index.to_bytes(4, 'big'), 'sha512')
        tweak = int.from_bytes(node[:32], 'big')
        result = (secret + tweak) % ORDER
        assert tweak < ORDER and result != 0
        return result, node[32:]

    def fingerprint(pub):
        return hashlib.new('ripemd160', hashlib.sha256(pub).digest()).digest()[:4]

    bip = []
    secrets = [1, 2, ORDER - 1, int.from_bytes(hashlib.sha256(b'round5 BIP32 test key').digest(), 'big')]
    chains = [bytes(32), bytes([255]) * 32, bytes(range(32)), hashlib.sha256(b'round5 BIP32 chain').digest()]
    for secret, chain in zip(secrets, chains):
        for index in [0, 255, 256, 0x7fffffff]:
            csecret, cchain = child(secret, chain, index)
            gsecret, gchain = child(csecret, cchain, 7)
            fields = [blob(public(secret)), blob(chain), str(index), blob(public(csecret)), blob(cchain),
                      blob(public(gsecret)), blob(gchain), blob(fingerprint(public(secret)))]
            bip.append('    (' + ', '.join(fields) + '),')

    tx = CTransaction()
    tx.version = 2
    tx.nLockTime = 0x12345678
    tx.vin = [CTxIn(COutPoint(int.from_bytes(bytes([i + 1]) * 32, 'little'), i + 7),
                    bytes([0x51 + i]), 0xfffffffd - i) for i in range(3)]
    tx.vout = [CTxOut(1000 + i, bytes([0x51 + i])) for i in range(3)]
    spent = [CTxOut(2000 + i, b'\x51\x20' + bytes([0x61 + i]) * 32) for i in range(3)]
    script = CScript(bytes.fromhex('01abab51'))
    sighashes = []
    for kind in [1, 2, 3, 0x81, 0x82, 0x83, 0]:
        legacy, error = LegacySignatureHash(script, tx, 1, kind)
        assert error is None
        v0 = SegwitV0SignatureHash(script, tx, 1, kind, spent[1].nValue)
        tap = TaprootSignatureHash(tx, spent, kind, 1)
        sighashes.append('    (' + ', '.join([str(kind), blob(legacy), blob(v0), blob(tap)]) + '),')

    wire = []
    for kind in range(3):
        for count in [252, 253, 254]:
            wide = CTransaction()
            wide.version = 0xffffffff
            wide.nLockTime = 0x80000000
            wide.vin = [CTxIn(COutPoint(int.from_bytes(bytes([0xa5]) * 32, 'little'), 0xffffffff), b'', 0x80000000)
                        for _ in range(count if kind == 0 else 1)]
            wide.vout = [CTxOut(0x0102030405060708, b'') for _ in range(count if kind == 1 else 1)]
            if kind == 2:
                wit = CTxInWitness()
                wit.scriptWitness.stack = [b''] * count
                wide.wit.vtxinwit = [wit]
            raw = wide.serialize_with_witness()
            txid = hash256(wide.serialize_without_witness())[::-1]
            wtxid = hash256(raw)[::-1]
            wire.append('    (' + ', '.join([str(kind), str(count), str(len(raw)), blob(txid), blob(wtxid)]) + '),')

    source = '''// Generated by tests/crypto-audit/round5/bitcoin/generate.py.
// Core v29.0 (MIT), verified against retained source hashes. Test keys only.
module {
  // parent key, chain, index, child key/chain, grandchild key/chain, fingerprint
  public let bip32 : [(Blob, Blob, Nat32, Blob, Blob, Blob, Blob, Blob)] = [
''' + '\n'.join(bip) + '''
  ];
  // kind, legacy digest, BIP143 digest, BIP341 digest
  public let sighashes : [(Nat32, Blob, Blob, Blob)] = [
''' + '\n'.join(sighashes) + '''
  ];
  // count location (inputs/outputs/witness), count, wire size, txid, wtxid
  public let wire : [(Nat, Nat, Nat, Blob, Blob)] = [
''' + '\n'.join(wire) + '''
  ];
}
'''
    OUT.write_text(source)
    (HERE / 'provenance.json').write_text(json.dumps({
        'oracle': 'Bitcoin Core v29.0 test-only ECKey and transaction/sighash helpers',
        'files': pins,
        'bip32_method': 'BIP32 private-scalar child derivation then Core point multiplication; no CKDpub implementation copied',
        'bip32_child_and_grandchild_cases': len(bip) * 2,
        'sighash_reference_cases': len(sighashes) * 3,
        'wire_reference_cases': len(wire),
        'generated_path': str(OUT.relative_to(ROOT)),
        'generated_sha256': hashlib.sha256(source.encode()).hexdigest(),
        'specifications': ['https://github.com/bitcoin/bips/blob/master/bip-0032.mediawiki',
                           'https://github.com/bitcoin/bips/blob/master/bip-0143.mediawiki',
                           'https://github.com/bitcoin/bips/blob/master/bip-0341.mediawiki'],
    }, indent=2) + '\n')


if __name__ == '__main__':
    main()
