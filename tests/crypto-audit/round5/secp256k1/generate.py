#!/usr/bin/env python3
"""Generate independent BIP340 SHA256-padding boundary vectors and Motoko tests.

Download the pinned bitcoin/bips reference.py separately, then run:
  python3 tests/crypto-audit/round5/secp256k1/generate.py --reference /path/reference.py
Add --check to verify the retained files without changing them.
"""
import argparse
import csv
import hashlib
import importlib.util
import json
from pathlib import Path
import sys

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
REFERENCE_COMMIT = "f98774a68c23269d9bfa78c8d9c4671ebf4ceb69"
REFERENCE_SHA256 = "4b1d4ad9e60820df4a6d239733d52b014bc03e4c47afd757a2fe4d3b586d892c"
REFERENCE_URL = f"https://raw.githubusercontent.com/bitcoin/bips/{REFERENCE_COMMIT}/bip-0340/reference.py"
LENGTHS = [55, 56, 57, 63, 64, 65, 119, 120, 121, 127, 128, 129]


def sha(data):
    return hashlib.sha256(data).hexdigest()


def blob(data):
    return '"' + ''.join(f"\\{byte:02x}" for byte in data) + '"'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--reference", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    reference_bytes = args.reference.read_bytes()
    if sha(reference_bytes) != REFERENCE_SHA256:
        raise SystemExit("BIP340 reference source does not match the pinned SHA256")
    spec = importlib.util.spec_from_file_location("bip340_official", args.reference)
    ref = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(ref)

    official_path = ROOT / "plugins/secp256k1/tests/vectors/bip340.csv"
    official = list(csv.DictReader(official_path.read_text().splitlines()))
    signing_count = 0
    for row in official:
        public = bytes.fromhex(row["public key"])
        message = bytes.fromhex(row["message"])
        signature = bytes.fromhex(row["signature"])
        assert ref.schnorr_verify(message, public, signature) == (row["verification result"] == "TRUE"), row["index"]
        if row["secret key"]:
            secret = bytes.fromhex(row["secret key"])
            assert ref.pubkey_gen(secret) == public, row["index"]
            assert ref.schnorr_sign(message, secret, bytes.fromhex(row["aux_rand"])) == signature, row["index"]
            signing_count += 1
    assert (len(official), signing_count) == (19, 8)

    rows = []
    parities = []
    for index, length in enumerate(LENGTHS):
        seed = hashlib.sha256(f"secp-audit5/secret/{index}".encode()).digest()
        scalar = 1 + int.from_bytes(seed, "big") % (ref.n - 1)
        point = ref.point_mul(ref.G, scalar)
        # Alternate raw even/odd keys, explicitly exercising secret normalization.
        wanted_odd = index % 2
        if (point[1] & 1) != wanted_odd:
            scalar = ref.n - scalar
        secret = scalar.to_bytes(32, "big")
        parities.append(ref.point_mul(ref.G, scalar)[1] & 1)
        public = ref.pubkey_gen(secret)
        message = bytes((index * 43 + offset * 29) % 256 for offset in range(length))
        auxiliary = [bytes(32), bytes([255]) * 32, bytes(range(32)),
                     hashlib.sha256(f"secp-audit5/auxiliary/{index}".encode()).digest()][index % 4]
        signature = ref.schnorr_sign(message, secret, auxiliary)
        mutated = signature[:-1] + bytes([signature[-1] ^ 1])
        assert int.from_bytes(mutated[32:], "big") < ref.n
        assert ref.schnorr_verify(message, public, signature)
        assert not ref.schnorr_verify(message, public, mutated)
        rows.append((secret, public, message, auxiliary, signature, mutated))
    assert parities.count(0) == parities.count(1) == 6

    tsv = ''.join('\t'.join(value.hex() for value in row) + '\n' for row in rows)
    cases = ''.join("    (" + ", ".join(blob(value) for value in row) + "),\n" for row in rows)
    module = '''// Generated by tests/crypto-audit/round5/secp256k1/generate.py.
// Expected bytes come from the pinned official BIP340 Python implementation.
import Prim "mo:⛔";
import Secp "mo:fast/Secp256k1";

module {
  func ok<T>(result : Secp.Result<T>) : T {
    switch result { case (#ok value) value; case (#err _) Prim.trap("unexpected audit5 secp256k1 error") }
  };
  func err<T>(result : Secp.Result<T>, expected : Secp.Error) {
    switch result { case (#err actual) assert actual == expected; case (#ok _) assert false }
  };
  // secret, x-only public key, message, auxiliary, signature, invalid mutation.
  let vectors : [(Blob, Blob, Blob, Blob, Blob, Blob)] = [
''' + cases + '''  ];

  public func schnorrHashBoundaries() {
    for ((secret, publicKey, message, auxiliary, expected, mutated) in vectors.values()) {
      let preparedSecret = ok(Secp.prepareSchnorrSecretKey(secret));
      let preparedPublic = ok(Secp.prepareSchnorrPublicKey(publicKey));
      assert Secp.schnorrSign(secret, message, auxiliary) == #ok(expected);
      assert Secp.schnorrSignPrepared(preparedSecret, message, auxiliary) == #ok(expected);
      assert Secp.schnorrVerify(publicKey, message, expected) == #ok(true);
      assert Secp.schnorrVerifyPrepared(preparedPublic, message, expected) == #ok(true);
      assert Secp.schnorrVerify(publicKey, message, mutated) == #ok(false);
      assert Secp.schnorrVerifyPrepared(preparedPublic, message, mutated) == #ok(false);
      // Reuse the same opaque objects after a failed equation.
      assert Secp.schnorrSignPrepared(preparedSecret, message, auxiliary) == #ok(expected);
      assert Secp.schnorrVerifyPrepared(preparedPublic, message, expected) == #ok(true);
    }
  };

  public func malformedLengthsAndPrecedence() {
    let (secret, publicKey, message, auxiliary, signature, _) = vectors[0];
    let key = ok(Secp.derivePublicKey(secret));
    let digest = auxiliary;
    let ecdsa = ok(Secp.signPrehash(secret, digest));
    let preparedEcdsa = ok(Secp.preparePublicKey(key));
    let preparedSecret = ok(Secp.prepareSchnorrSecretKey(secret));
    let preparedPublic = ok(Secp.prepareSchnorrPublicKey(publicKey));
    for (length in [0, 1, 31, 33, 63, 64, 65, 511, 512, 513].values()) {
      let bad = Prim.arrayToBlob(Prim.Array_tabulate<Nat8>(length, func(_) { 0 }));
      err(Secp.derivePublicKey(bad), #invalidSecretKey);
      err(Secp.prepareSchnorrSecretKey(bad), #invalidSecretKey);
      err(Secp.signPrehash(bad, bad), #invalidSecretKey);
      err(Secp.schnorrSign(bad, message, bad), #invalidSecretKey);
      err(Secp.tweakXOnlySecretKey(bad, bad), #invalidSecretKey);
      err(Secp.signPrehash(secret, bad), #invalidDigest);
      err(Secp.verifyPrehash(key, bad, bad), #invalidDigest);
      err(Secp.verifyPrehashPrepared(preparedEcdsa, bad, bad), #invalidDigest);
      err(Secp.baseMultiply(bad), #invalidScalar);
      err(Secp.pointMultiply(key, bad), #invalidScalar);
      err(Secp.tweakPublicKey(key, bad), #invalidScalar);
      err(Secp.tweakXOnlyPublicKey(publicKey, bad), #invalidScalar);
      err(Secp.tweakXOnlySecretKey(secret, bad), #invalidScalar);
      err(Secp.compressPublicKey(bad), #invalidPublicKey);
      err(Secp.decompressPublicKey(bad), #invalidPublicKey);
      err(Secp.preparePublicKey(bad), #invalidPublicKey);
      err(Secp.xOnlyPublicKey(bad), #invalidPublicKey);
      err(Secp.pointAdd(bad, bad), #invalidPublicKey);
      err(Secp.pointMultiply(bad, bad), #invalidPublicKey);
      err(Secp.verifyPrehash(bad, bad, bad), #invalidPublicKey);
      err(Secp.prepareSchnorrPublicKey(bad), #invalidPublicKey);
      err(Secp.schnorrVerify(bad, message, bad), #invalidPublicKey);
      err(Secp.schnorrSign(secret, message, bad), #invalidAuxiliaryRandomness);
      err(Secp.schnorrSignPrepared(preparedSecret, message, bad), #invalidAuxiliaryRandomness);
      if (length != 64) {
        err(Secp.verifyPrehash(key, digest, bad), #invalidSignature);
        err(Secp.verifyPrehashPrepared(preparedEcdsa, digest, bad), #invalidSignature);
        err(Secp.signatureToDer(bad), #invalidSignature);
        err(Secp.normalizeSignature(bad), #invalidSignature);
        err(Secp.schnorrVerify(publicKey, message, bad), #invalidSignature);
        err(Secp.schnorrVerifyPrepared(preparedPublic, message, bad), #invalidSignature);
      };
      // Failed calls cannot alter existing inputs or opaque prepared handles.
      assert Secp.verifyPrehashPrepared(preparedEcdsa, digest, ecdsa) == #ok(true);
      assert Secp.schnorrVerifyPrepared(preparedPublic, message, signature) == #ok(true);
    }
  };
}
'''
    run = '''//MOC-FLAG --package fast ../../src --package core $MOTOKO_CORE --plugin ../../../../dist/secp256k1 --sanity-checks
import Cases "../lib/Secp256k1Audit5Tests";

Cases.schnorrHashBoundaries();
Cases.malformedLengthsAndPrecedence();
'''
    actor = '''import Test "mo:test";
import Cases "../lib/Secp256k1Audit5Tests";

persistent actor {
  public func test_bip340_hash_padding_boundaries() : async Test.Metrics {
    Test.test(Cases.schnorrHashBoundaries)
  };
  public func test_malformed_lengths_and_error_precedence() : async Test.Metrics {
    Test.test(Cases.malformedLengthsAndPrecedence)
  };
}
'''
    ash = json.dumps({"mo": {"fast": "../../src", "core": "../../.mops/core@2.5.0/src"},
                      "canisters": [{"name": "secp256k1_audit5", "src": "Secp256k1Audit5.mo",
                                     "mocArgs": ["--plugin", "../../../../dist/secp256k1"]}]}, indent=2) + "\n"
    outputs = {
        HERE / "schnorr-boundaries.tsv": tsv,
        ROOT / "packages/fast/tests/lib/Secp256k1Audit5Tests.mo": module,
        ROOT / "packages/fast/tests/run/crypto-secp256k1-audit5.mo": run,
        ROOT / "packages/fast/tests/ash/Secp256k1Audit5.mo": actor,
        ROOT / "packages/fast/tests/ash/Secp256k1Audit5.ash.json": ash,
    }
    report = {"reference_url": REFERENCE_URL, "reference_commit": REFERENCE_COMMIT,
              "reference_sha256": REFERENCE_SHA256, "official_csv_sha256": sha(official_path.read_bytes()),
              "official_verifications": len(official), "official_exact_signatures": signing_count,
              "message_lengths": LENGTHS, "raw_public_y_parities": parities,
              "independent_signatures": len(rows), "independently_rejected_signature_mutations": len(rows),
              "tsv_columns": ["secret", "xonly_public", "message", "auxiliary", "signature", "mutated_signature"],
              "sha256": {str(path.relative_to(ROOT)): sha(text.encode()) for path, text in outputs.items()}}
    outputs[HERE / "generator-evidence.json"] = json.dumps(report, indent=2) + "\n"
    for path, text in outputs.items():
        if args.check:
            if path.read_text() != text:
                raise SystemExit(f"stale generated file: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    print(json.dumps({"checked" if args.check else "generated": len(outputs),
                      "official_verifications": len(official), "official_signatures": signing_count,
                      "new_signatures": len(rows), "mutations": len(rows)}))


if __name__ == "__main__":
    main()
