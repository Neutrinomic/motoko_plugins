//! Hash outputs are forced only by run_injected.py in a temporary source copy.
//! These are algebraic branch regressions, not natural SHA256 test vectors.
use super::{call, hex};
use k256::schnorr::{Signature, SigningKey};

const ORDER: &str = "fffffffffffffffffffffffffffffffebaaedce6af48a03bbfd25e8cd0364141";
const GX: &str = "79be667ef9dcbbac55a06295ce870b07029bfcdb2dce28d959f2815b16f81798";

fn force(nonce: &[u8], challenge: &[u8]) {
    k256::schnorr::audit_force_hashes(nonce.try_into().unwrap(), challenge.try_into().unwrap());
}
fn one() -> [u8; 32] { let mut value = [0; 32]; value[31] = 1; value }

#[test]
fn audit5_rare_nonce_is_reduced_before_zero_rejection() {
    let secret = one();
    let key = SigningKey::from_bytes(&secret).unwrap();
    let prepared = call(21, &secret, &[], &[], 64).1;
    for nonce in [[0; 32].to_vec(), hex(ORDER)] {
        force(&nonce, &[0; 32]);
        assert!(key.sign_raw(b"forced nonce", &[0; 32]).is_err());
        assert_eq!(call(13, &secret, b"forced nonce", &[0; 32], 64).0, -5);
        assert_eq!(call(22, &prepared, b"forced nonce", &[0; 32], 64).0, -5);
    }
    // Values independently generated by the official BIP340 reference with the
    // same tagged-hash substitutions, stored by run_injected.py.
    let vectors = std::fs::read_to_string(std::env::var("SECP_AUDIT_FORCED_VECTORS").unwrap()).unwrap();
    for line in vectors.lines() {
        let fields: Vec<Vec<u8>> = line.split('\t').map(hex).collect();
        force(&fields[0], &[0; 32]);
        assert_eq!(key.sign_raw(b"forced nonce", &[0; 32]).unwrap().to_bytes().as_slice(), fields[1]);
        assert_eq!(call(13, &secret, b"forced nonce", &[0; 32], 64), (64, fields[1].clone()));
        assert_eq!(call(22, &prepared, b"forced nonce", &[0; 32], 64), (64, fields[1].clone()));
        let public = hex(GX);
        let public_prepared = call(19, &public, &[], &[], 512).1;
        assert_eq!(call(14, &public, b"forced nonce", &fields[1], 0).0, 1);
        assert_eq!(call(20, &public_prepared, b"forced nonce", &fields[1], 0).0, 1);
    }
}

#[test]
fn audit5_rare_zero_s_signs_serializes_and_verifies() {
    let secret = one();
    let mut challenge = hex(ORDER); challenge[31] -= 1;
    force(&secret, &challenge);
    let key = SigningKey::from_bytes(&secret).unwrap();
    let mut expected = hex(GX); expected.extend([0; 32]);
    let signature = key.sign_raw(b"zero s", &[0; 32]).unwrap();
    assert_eq!(signature.to_bytes().as_slice(), expected);
    let parsed = Signature::try_from(expected.as_slice()).unwrap();
    key.verifying_key().verify_raw(b"zero s", &parsed).unwrap();
    let prepared = call(21, &secret, &[], &[], 64).1;
    assert_eq!(call(13, &secret, b"zero s", &[0; 32], 64), (64, expected.clone()));
    assert_eq!(call(22, &prepared, b"zero s", &[0; 32], 64), (64, expected.clone()));
    let public = hex(GX);
    let public_prepared = call(19, &public, &[], &[], 512).1;
    assert_eq!(call(14, &public, b"zero s", &expected, 0).0, 1);
    assert_eq!(call(20, &public_prepared, b"zero s", &expected, 0).0, 1);
}

#[test]
fn audit5_rare_encoding_accepts_zero_and_rejects_noncanonical() {
    let zero = [0; 64];
    assert_eq!(Signature::try_from(zero.as_slice()).unwrap().to_bytes(), zero);
    let mut out_of_range_s = hex(GX); out_of_range_s.extend(hex(ORDER));
    assert!(Signature::try_from(out_of_range_s.as_slice()).is_err());
    let mut out_of_range_r = hex("fffffffffffffffffffffffffffffffffffffffffffffffffffffffefffffc2f");
    out_of_range_r.extend(one());
    assert!(Signature::try_from(out_of_range_r.as_slice()).is_err());
    for size in [0, 1, 31, 32, 33, 63, 65, 96] {
        assert!(Signature::try_from(vec![0; size].as_slice()).is_err());
    }
}
