#!/usr/bin/env python3
"""Regenerate the small public/native protocol corpus with py_ecc==8.0.0.

Only test constants are used as secret keys. No plugin code is imported.
The 256-byte DST is normalized per RFC9380 section 5.3.3 because py_ecc's
expand_message_xmd rejects DSTs longer than 255 bytes.
"""
import argparse
import hashlib
from pathlib import Path

import py_ecc
from py_ecc.bls import G2Basic, G2MessageAugmentation, G2ProofOfPossession
from py_ecc.bls.hash_to_curve import hash_to_G1, hash_to_G2
from py_ecc.bls.point_compression import compress_G1, compress_G2
from py_ecc.optimized_bls12_381 import G2, add, multiply

assert py_ecc.__version__ == "8.0.0"
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true", help="check the retained files without rewriting them")
args = parser.parse_args()
HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
SECRET = 5
MESSAGE = b"a\x00b\xff"


def g1(point):
    return int(compress_G1(point)).to_bytes(48, "big")


def g2(point):
    return b"".join(int(part).to_bytes(48, "big") for part in compress_G2(point))


def ic_sign(message, scheme="NUL"):
    dst = f"BLS_SIG_BLS12381G1_XMD:SHA-256_SSWU_RO_{scheme}_".encode()
    return multiply(hash_to_G1(message, dst, hashlib.sha256), SECRET)


eth = G2ProofOfPossession
ic_key = g2(multiply(G2, SECRET))
eth_key = eth.SkToPk(SECRET)
framed = b"\x0dic-state-root" + bytes(range(32))
data = {
    "message": MESSAGE,
    "otherMessage": b"a\x00b\xfe",
    "icKey": ic_key,
    "icSignature": g1(ic_sign(MESSAGE)),
    "icPopSignature": g1(ic_sign(MESSAGE, "POP")),
    "icAugSignature": g1(ic_sign(ic_key + MESSAGE, "AUG")),
    "icFramedMessage": framed,
    "icRoot": bytes(range(32)),
    "icFramedSignature": g1(ic_sign(framed)),
    "icSameKeyAggregate": g1(add(ic_sign(MESSAGE), ic_sign(b"a\x00b\xfe"))),
    "ethKey": eth_key,
    "ethSignature": eth.Sign(SECRET, MESSAGE),
    "ethBasicSignature": G2Basic.Sign(SECRET, MESSAGE),
    "ethAugSignature": G2MessageAugmentation.Sign(SECRET, MESSAGE),
    "ethProof": eth.PopProve(SECRET),
    "ethSignatureOnKey": eth.Sign(SECRET, eth_key),
    "ethRepeatedSignature": eth.Aggregate([eth.Sign(SECRET, MESSAGE)] * 2),
}
assert eth.Verify(eth_key, MESSAGE, data["ethSignature"])
assert G2Basic.Verify(eth_key, MESSAGE, data["ethBasicSignature"])
assert G2MessageAugmentation.Verify(eth_key, MESSAGE, data["ethAugSignature"])
assert eth.PopVerify(eth_key, data["ethProof"])
for length in (255, 256):
    dst = bytes(i % 251 for i in range(length))
    normalized = (hashlib.sha256(b"H2C-OVERSIZE-DST-" + dst).digest()
                  if length > 255 else dst)
    data[f"dst{length}"] = dst
    data[f"hashG1Dst{length}"] = g1(hash_to_G1(MESSAGE, normalized, hashlib.sha256))
    data[f"hashG2Dst{length}"] = g2(hash_to_G2(MESSAGE, normalized, hashlib.sha256))

target = ROOT / "packages/fast/tests/bls/ProtocolVectors.mo"
header = "// Generated by tests/crypto-audit/round5/bls/generate.py with py_ecc 8.0.0.\n"
outputs = {
    HERE / "vectors.tsv": "".join(f"{key}\t{value.hex()}\n" for key, value in data.items()),
    target: header + "module {\n" + "".join(
    f'  public let {key} : Blob = "' + "".join(f"\\{byte:02x}" for byte in value) + '";\n'
    for key, value in data.items()) + "}\n",
}
for path, contents in outputs.items():
    if args.check:
        assert path.read_text() == contents, f"stale fixture: {path}"
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(contents)
print(f"{'Checked' if args.check else 'Generated'} {len(data)} independent fixtures")
