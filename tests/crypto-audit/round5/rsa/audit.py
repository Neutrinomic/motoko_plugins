#!/usr/bin/env python3
"""Round-five RSA caller/encoding tests; all key material is PUBLIC TEST DATA.

Independent RFC 8017 encoding + Python full-exponent pow, checked with OpenSSL.
No production helper or older audit encoder is used to calculate expectations.
Generate maintained fixtures with --generate; transient files stay under _out.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path
import subprocess

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
OUT = HERE / '_out'
RUNTIME = ROOT / 'plugins/rsa/runtime'
FIXTURE = ROOT / 'plugins/rsa/vectors/openssl3072.json'
MO_FIXTURE = ROOT / 'packages/fast/tests/fixtures/RSARound5.mo'


def encoded(digest, salt):
    # RFC 8017 9.1.1, emBits = 3071. General salt length supports malformed cases.
    h = hashlib.sha256(bytes(8) + digest + salt).digest()
    db = bytes(350 - len(salt)) + b'\x01' + salt
    mask = b''.join(hashlib.sha256(h + counter.to_bytes(4, 'big')).digest()
                    for counter in range(11))[:351]
    masked = bytes(x ^ y for x, y in zip(db, mask))
    return bytes([masked[0] & 127]) + masked[1:] + h + b'\xbc'


def material():
    source = json.loads(FIXTURE.read_text())
    key = bytes.fromhex(source['privateKey'])
    p, q, dp, dq, qi = [int.from_bytes(key[i:i+192], 'big') for i in range(0, 960, 192)]
    n = p*q
    # Full exponentiation is independent of both native CRT implementations.
    d = pow(65537, -1, math.lcm(p-1, q-1))
    assert (dp, dq, qi) == (d % (p-1), d % (q-1), pow(q, -1, p))
    public = n.to_bytes(384, 'big')
    assert public.hex() == source['publicKey']

    def signature(em):
        value = int.from_bytes(em, 'big')
        assert value < n
        sig = pow(value, d, n)
        assert pow(sig, 65537, n) == value
        return sig.to_bytes(384, 'big')

    positives = []
    for name, message, salt, prehash in [
        ('key-as-message', key, key[383:415], False),
        ('message-salt-alias', bytes(range(32)), bytes(range(32)), False),
        ('digest-salt-alias', bytes([255])*32, bytes([255])*32, True),
        ('multi-block-message', bytes((i*71 + 193) % 256 for i in range(8193)), bytes(32), False),
    ]:
        digest = message if prehash else hashlib.sha256(message).digest()
        positives.append(dict(name=name, message=message, salt=salt, digest=digest,
                              prehash=prehash, signature=signature(encoded(digest, salt))))

    digest = hashlib.sha256(b'round five PSS boundaries').digest()
    em = encoded(digest, bytes([255])*32)
    malformed = []
    # Each mutation stays in its field, including both sides of MGF block boundaries.
    for offset in [31, 32, 63, 64, 95, 96, 255, 256, 317, 319, 350, 352, 382]:
        mutated = bytearray(em)
        mutated[offset] ^= 0x80
        malformed.append((f'field-byte-{offset}', signature(mutated)))
    for bit in range(8):
        mutated = bytearray(em)
        mutated[318] ^= 1 << bit
        malformed.append((f'delimiter-bit-{bit}', signature(mutated)))
    # Construct an otherwise-valid encoding with forbidden high bit, without modular wrap.
    for counter in range(256):
        top = bytearray(encoded(digest, bytes([counter])*32))
        top[0] |= 128
        if int.from_bytes(top, 'big') < n:
            malformed.append(('forbidden-high-bit', signature(top)))
            break
    else:
        raise AssertionError('could not construct top-bit case')
    return key, public, positives, digest, malformed


def blob(data):
    return '"' + ''.join(f'\\{byte:02x}' for byte in data) + '"'


def generate(write_fixture=False):
    OUT.mkdir(parents=True, exist_ok=True)
    key, public, positives, digest, malformed = material()
    lines = ['// Generated by tests/crypto-audit/round5/rsa/audit.py --generate.',
             '// Published test keys/signatures only; never use for real authentication.', 'module {',
             '  public let signatures : [Blob] = [']
    lines += ['    ' + blob(row['signature']) + ',' for row in positives]
    lines += ['  ];', '  public let keySalt : Blob = ' + blob(positives[0]['salt']) + ';',
              '  public let boundaryDigest : Blob = ' + blob(digest) + ';',
              '  public let malformed : [Blob] = [']
    lines += ['    ' + blob(sig) + ', // ' + name for name, sig in malformed]
    lines += ['  ];', '}']
    text = '\n'.join(lines) + '\n'
    if write_fixture:
        MO_FIXTURE.write_text(text)
    else:
        assert MO_FIXTURE.read_text() == text, 'stale fixture; rerun with --generate'
    # C fixtures are transient and use the exact same independent oracle bytes.
    c = []
    def array(name, data):
        c.append(f'static const unsigned char {name}[] = {{' + ','.join(str(x) for x in data) + '};')
    array('raw_key', key)
    array('raw_public', public)
    for i, row in enumerate(positives):
        for field in ['message', 'salt', 'digest', 'signature']:
            array(f'{field}{i}', row[field])
    array('boundary_digest', digest)
    for i, (_, sig) in enumerate(malformed):
        array(f'malformed{i}', sig)
    c.append('static const unsigned char *malformed[] = {' + ','.join(f'malformed{i}' for i in range(len(malformed))) + '};')
    (OUT / 'vectors.h').write_text('\n'.join(c) + '\n')
    return positives, malformed


def run(command, label, success=True):
    result = subprocess.run([str(x) for x in command], cwd=ROOT, capture_output=True)
    (OUT / (label + '.log')).write_bytes(result.stdout + result.stderr)
    if (result.returncode == 0) != success:
        raise RuntimeError(f'{label}: unexpected status {result.returncode}; see _out/{label}.log')
    return result.stdout.decode(errors='replace').strip()


def der(tag, data):
    n = len(data)
    length = bytes([n]) if n < 128 else bytes([128 + (n.bit_length()+7)//8]) + n.to_bytes((n.bit_length()+7)//8, 'big')
    return bytes([tag]) + length + data


def integer(n):
    value = n.to_bytes((n.bit_length()+7)//8, 'big')
    return der(2, (b'\x00' if value[0] & 128 else b'') + value)


def main():
    global OUT
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--generate', action='store_true')
    parser.add_argument('--native', action='store_true')
    parser.add_argument('--openssl', default='openssl')
    parser.add_argument('--oracle', action='store_true')
    parser.add_argument('--cc', default='cc')
    parser.add_argument('--output', type=Path, default=OUT)
    args = parser.parse_args()
    OUT = args.output.resolve()
    positives, malformed = generate(args.generate)
    report = dict(signing_vectors=len(positives), malformed_pss_vectors=len(malformed),
                  fixture_sha256=hashlib.sha256(MO_FIXTURE.read_bytes()).hexdigest(),
                  key_source_sha256=hashlib.sha256(FIXTURE.read_bytes()).hexdigest())
    if args.oracle:
        key, public, _, digest, _ = material()
        public_der = OUT / 'public.der'
        public_der.write_bytes(der(48, integer(int.from_bytes(public, 'big')) + integer(65537)))
        for index, row in enumerate(positives):
            data, sig = OUT/'digest', OUT/'signature'
            data.write_bytes(row['digest']); sig.write_bytes(row['signature'])
            run([args.openssl, 'pkeyutl', '-verify', '-pubin', '-inkey', public_der,
                 '-keyform', 'DER', '-in', data, '-sigfile', sig,
                 '-pkeyopt', 'digest:sha256', '-pkeyopt', 'rsa_padding_mode:pss',
                 '-pkeyopt', 'rsa_pss_saltlen:32'], f'openssl-positive-{index}')
        for index, (_, signature) in enumerate(malformed):
            (OUT/'digest').write_bytes(digest); (OUT/'signature').write_bytes(signature)
            run([args.openssl, 'pkeyutl', '-verify', '-pubin', '-inkey', public_der,
                 '-keyform', 'DER', '-in', OUT/'digest', '-sigfile', OUT/'signature',
                 '-pkeyopt', 'digest:sha256', '-pkeyopt', 'rsa_padding_mode:pss',
                 '-pkeyopt', 'rsa_pss_saltlen:32'], f'openssl-negative-{index}', success=False)
        report['openssl'] = run([args.openssl, 'version'], 'openssl-version')
        report['oracle'] = '4 accepted, 22 rejected by OpenSSL; Python full-exponent pow'
    if args.native:
        sources = sorted((RUNTIME/'vendor/bearssl/src').rglob('*.c'))
        run([args.cc, '-std=c11', '-O3', '-g', '-fno-omit-frame-pointer',
             '-fsanitize=address,undefined', '-fno-sanitize-recover=all',
             '-I'+str(RUNTIME/'src'), '-I'+str(RUNTIME/'vendor/bearssl/inc'),
             '-I'+str(RUNTIME/'vendor/bearssl/src'), '-I'+str(OUT), HERE/'driver.c',
             *sources, '-o', OUT/'driver'], 'native-build')
        report['native'] = run([OUT/'driver'], 'native')
        report['native_binary_sha256'] = hashlib.sha256((OUT/'driver').read_bytes()).hexdigest()
    report['implementation_sha256'] = {str(p.relative_to(ROOT)):hashlib.sha256(p.read_bytes()).hexdigest()
        for p in sorted((ROOT/'plugins/rsa').rglob('*')) if p.is_file()}
    (OUT/'report.json').write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps({k:v for k,v in report.items() if k != 'implementation_sha256'}, indent=2))


if __name__ == '__main__':
    main()
