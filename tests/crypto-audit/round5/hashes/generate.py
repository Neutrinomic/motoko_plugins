#!/usr/bin/env python3
"""Reproduce small independent hash/HMAC oracles with Python hashlib + hmac.

No plugin code is imported. Xorshift32 describes inputs, not a hash oracle.
BLAKE3 answers use the earlier pinned official corpus and the unmodified upstream
reference implementation via generate-blake3.rs (see REPORT.md).
"""
import hashlib
import hmac
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent

def data(seed, length):
    out = bytearray()
    for _ in range(length):
        seed ^= (seed << 13) & 0xffffffff
        seed ^= seed >> 17
        seed ^= (seed << 5) & 0xffffffff
        out.append(seed & 255)
    return bytes(out)

def answers(key, message):
    return [hashlib.new(a, message).digest() for a in ('sha256', 'sha512', 'sha384', 'ripemd160')] + [hmac.digest(key, message, a) for a in ('sha256', 'sha512')]

def blob(value):
    return '"' + ''.join(f'\\{b:02x}' for b in value) + '"'

def array(values):
    return '[' + ', '.join(map(blob, values)) + ']'

sizes = [0, 1, 31, 32, 33, 55, 56, 63, 64, 65, 111, 112, 127, 128, 129, 255, 256, 257, 511, 512, 1023, 1024, 1025, 2047, 2048, 4095, 4096, 4097]
sizes += [int.from_bytes(data(0x92357f10 + i, 2), 'little') % 2049 for i in range(20)]
rows = []
mo = ['// Generated by generate.py; independent Python hashlib/hmac and upstream BLAKE3 answers.\nmodule {\n  public type Case = { seed : Nat32; length : Nat; split : Nat; keyLength : Nat; full : [Blob]; prefix : [Blob]; emptyMac : [Blob]; selfMac : [Blob] };\n  public let cases : [Case] = [\n']
for i, size in enumerate(sizes):
    seed = 0x9e3779b9 ^ (i * 0x1020401)
    key_len = [0, 1, 63, 64, 65, 127, 128, 129, 131, 257][i % 10]
    split = [0, size, max(0, size - 1), size // 2][i % 4]
    message, key = data(seed, size), data(seed ^ 0xa5a55a5a, key_len)
    full, prefix = answers(key, message), answers(key, message[:split])
    empty = answers(key, b'')[4:]
    self_mac = answers(message, message)[4:]
    rows.append('\t'.join(map(str, [seed, size, split, key_len])) + '\t' + '\t'.join(x.hex() for x in full + prefix + empty + self_mac))
    if i in [0, 3, 4, 6, 8, 10, 11, 12, 13, 14, 17, 22, 23, 24, 26, 27]:
        mo.append(f'    {{ seed = {seed}; length = {size}; split = {split}; keyLength = {key_len}; full = {array(full)}; prefix = {array(prefix)}; emptyMac = {array(empty)}; selfMac = {array(self_mac)} }},\n')
mo.append('  ];\n  public let blake3 : [(Nat, [Blob])] = [\n')
original = json.loads((HERE / '../../hash-codec/blake3-official.json').read_text())
for case in original['cases']:
    if case['input_len'] in [1024, 1025, 2048, 2049, 4096, 4097]:
        mo.append(f"    ({case['input_len']}, {array([bytes.fromhex(case[k]) for k in ('hash', 'keyed_hash', 'derive_key')])}),\n")
mo.append('  ];\n  public let contexts : [(Text, Blob)] = [\n')
for line in (HERE / 'blake3-contexts.tsv').read_text().splitlines():
    context, expected = line.split('\t')
    literal = json.dumps(bytes.fromhex(context).decode(), ensure_ascii=False).replace('\\u0000', '\\00')
    mo.append(f'    ({literal}, {blob(bytes.fromhex(expected))}),\n')
mo.append('  ];\n}\n')
(HERE / 'vectors.tsv').write_text('\n'.join(rows) + '\n')
(HERE / 'Vectors.mo').write_text(''.join(mo))
print(f'{len(rows)} native cases; 16 public cases; 6 official BLAKE3 vectors')
