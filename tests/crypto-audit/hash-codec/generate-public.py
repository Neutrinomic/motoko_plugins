#!/usr/bin/env python3
"""Generate a standalone Motoko audit from the checked-in independent vectors."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
def blob(hextext):
    return '"' + ''.join('\\' + hextext[i:i+2] for i in range(0,len(hextext),2)) + '"'
def text(s):
    return json.dumps(s)
parts = ['''// Generated by generate-public.py from checked-in independent vector fixtures.
import Array "mo:core/Array";
import Blob "mo:core/Blob";
import Nat8 "mo:core/Nat8";
import Prim "mo:⛔";
import BLAKE3 "mo:fast/BLAKE3";
import SHA512 "mo:fast/SHA512";
import RIPEMD160 "mo:fast/RIPEMD160";
import HMAC "mo:fast/HMAC";
import Base58 "mo:fast/Base58";
import Base58Check "mo:fast/Base58Check";
import Bech32 "mo:fast/Bech32";
import Segwit "mo:fast/Segwit";

func pattern(n:Nat,mult:Nat,add:Nat,modulus:Nat):Blob {
  Blob.fromArray(Array.tabulate<Nat8>(n,func(i){Nat8.fromNat((i*mult+add)%modulus)}))
};
func cut(b:Blob,start:Nat,n:Nat):Blob {
  Blob.fromArray(Array.tabulate<Nat8>(n,func(i){b[start+i]}))
};
func mutate(b:Blob,offset:Nat,value:Nat8):Blob {
  Blob.fromArray(Array.tabulate<Nat8>(b.size(),func(i){if(i==offset)value else b[i]}))
};
func b3ok(r:BLAKE3.Result<Blob>):Blob {
  switch r {case(#ok b)b;case(#err e)Prim.trap(debug_show(e))}
};
''']
hashes=[]
for line in (HERE/'openssl-hash-vectors.tsv').read_text().splitlines():
    alg,n,answer=line.split('\t')
    hashes.append(f'({text(alg)}, {n}, {blob(answer)} : Blob)')
parts.append('for ((algorithm,n,expected) in [\n'+',\n'.join(hashes)+'''].values()) {
  let input=pattern(n,29,157,256);
  if(algorithm=="sha384")assert(SHA512.digest384(input)==expected)
  else if(algorithm=="sha512")assert(SHA512.digest(input)==expected)
  else assert(RIPEMD160.digest(input)==expected);
  for(stride in [1,63,127,129].values()) {
    let sha=SHA512.Digest();let sha384=SHA512.Digest384();let ripe=RIPEMD160.Digest();
    var offset=0;
    while(offset < n) {
      let take=if(n-offset < stride)n-offset else stride;let piece=cut(input,offset,take);
      if(algorithm=="sha384")sha384.write(piece)
      else if(algorithm=="sha512")sha.write(piece)
      else assert(ripe.write(piece));
      offset+=take;
    };
    if(algorithm=="sha384") {
      assert(sha384.sum()==expected);assert(sha384.sum()==expected);sha384.write("");assert(sha384.sum()==expected);
      sha384.reset();assert(sha384.sum()==SHA512.digest384(""));
    } else if(algorithm=="sha512") {
      assert(sha.sum()==expected);assert(sha.sum()==expected);sha.write("");assert(sha.sum()==expected);
      sha.reset();assert(sha.sum()==SHA512.digest(""));
    } else {
      assert(ripe.sum()==expected);assert(ripe.sum()==expected);assert(ripe.write(""));assert(ripe.sum()==expected);
      ripe.reset();assert(ripe.sum()==RIPEMD160.digest(""));
    };
  };
};
''')
b3=[]
for case in json.loads((HERE/'blake3-official.json').read_text())['cases']:
    if case['input_len'] > 4097: continue
    b3.append('('+str(case['input_len'])+', '+', '.join(blob(case[k])+' : Blob' for k in ('hash','keyed_hash','derive_key'))+')')
parts.append('for ((n,hash,keyed,derived) in [\n'+',\n'.join(b3)+'''].values()) {
  let key:Blob="whats the Elvish word for friend";
  let context="BLAKE3 2019-12-27 16:29:52 test vectors context";
  let input=pattern(n,1,0,251);
  assert(BLAKE3.digest(input)==cut(hash,0,32));
  assert(b3ok(BLAKE3.keyedHash(key,input))==cut(keyed,0,32));
  assert(BLAKE3.deriveKey(context,input)==cut(derived,0,32));
  for ((initial,expected) in [(BLAKE3.new(),hash),(b3ok(BLAKE3.newKeyed(key)),keyed),(BLAKE3.newDeriveKey(context),derived)].values()) {
    var state=initial;var offset=0;
    while(offset < n) {
      let take=if(n-offset < 997)n-offset else 997;
      state:=b3ok(BLAKE3.update(state,cut(input,offset,take)));offset+=take;
      assert(state.size()==2816);
    };
    assert(b3ok(BLAKE3.finalize(state))==cut(expected,0,32));
    assert(b3ok(BLAKE3.finalizeXof(state,63,65))==cut(expected,63,65));
    assert(b3ok(BLAKE3.update(state,""))==state);
  };
};
assert(BLAKE3.keyedHash("short","")==#err(#invalidKey));
assert(BLAKE3.finalize("garbage")==#err(#invalidState));
assert(BLAKE3.xof("",18_446_744_073_709_551_615,1)==#err(#invalidSeek));
assert(BLAKE3.xof("",0,16_777_217)==#err(#outputTooLarge));
assert(BLAKE3.deriveKey("one","same")!=BLAKE3.deriveKey("two","same"));
for(offset in [0,4,5,7,8,39,40,47,49,50,51,63,64,1087,1088,2815].values()) {
  assert(BLAKE3.finalize(mutate(BLAKE3.new(),offset,255))==#err(#invalidState));
};
for(mode in [false,true].values()) {
  let initial=if(mode)Prim.sha512_init384() else Prim.sha512_init();
  for(offset in [0,3,4,5,7,8,71,72,88,215].values()) {
    assert(Prim.sha512_update(mutate(initial,offset,initial[offset]^255),"x")==null);
  };
};
for(offset in [0,3,4,7,15,16,35,36,39,40,103].values()) {
  let initial=RIPEMD160.init();
  assert(RIPEMD160.update(mutate(initial,offset,initial[offset]^255),"x")==null);
};
''')
hm=[]
for line in (HERE/'openssl-hmac-vectors.tsv').read_text().splitlines():
    alg,k,n,answer=line.split('\t')
    # Full cross-matrix is covered natively; representative source/IR/Wasm cases.
    if int(k) not in (0,64,65,128,129,131) or int(n) not in (0,55,56,111,112,129,257): continue
    hm.append(f'({text(alg)}, {k}, {n}, {blob(answer)} : Blob)')
parts.append('for ((algorithm,k,n,expected) in [\n'+',\n'.join(hm)+'''].values()) {
  let key=pattern(k,83,97,256);let input=pattern(n,29,157,256);
  let prepared=if(algorithm=="sha256")HMAC.prepareSha256(key) else HMAC.prepareSha512(key);
  if(algorithm=="sha256")assert(HMAC.sha256(key,input)==expected) else assert(HMAC.sha512(key,input)==expected);
  assert(prepared.digest(input)==expected);assert(prepared.digest(input)==expected);
  let stream=prepared.stream();let independent=prepared.stream();
  stream.write(cut(input,0,n/2));independent.write(input);stream.write(cut(input,n/2,n-n/2));
  assert(stream.sum()==expected);assert(independent.sum()==expected);assert(stream.sum()==expected);
  stream.reset();stream.write(input);assert(stream.sum()==expected);
};
''')
b58=[]
for data,encoded in json.loads((HERE/'base58-bitcoin-core.json').read_text()):
    b58.append(f'({blob(data)} : Blob,{text(encoded)})')
parts.append('for ((data,encoded) in [\n'+',\n'.join(b58)+'''].values()) {
  assert(Base58.encode(data)==encoded);assert(Base58.decode(encoded)==#ok(data));
};
assert(Base58.decode("1230")==#err(#invalidCharacter(3)));
assert(Base58.decode("123é")==#err(#invalidCharacter(3)));
assert(Base58Check.decode("1")==#err(#tooShort));
assert(Base58Check.decode("1111")==#err(#invalidChecksum));
assert(Base58Check.encode("")=="3QJmnh");
assert(Base58Check.decode("3QJmnh")==#ok(""));
assert(Base58.decode(Base58.encode(pattern(4096,0,0,256)))==#ok(pattern(4096,0,0,256)));
assert(Bech32.decode("a12UEL5L")==#err(#mixedCase));
assert(Bech32.convertBits("\\20",5,8,false)==#err(#invalidData));
assert(Bech32.convertBits("\\00",5,8,false)==#err(#invalidPadding));
assert(Bech32.convertBits("\\00\\01",5,8,false)==#err(#invalidPadding));
assert(Bech32.convertBits("",0,8,false)==#err(#invalidBitWidth));
assert(Bech32.convertBits("\\ff\\00",8,5,true)==#ok("\\1f\\1c\\00\\00"));
''')
segwit=json.loads((HERE/'bip350-segwit.json').read_text())
valid=[]
for row in segwit['valid']:
    valid.append(f'({text(row["address"])},{text(row["address"].lower())},{text(row["address"].split("1")[0].lower())},{row["version"]} : Nat8,{blob(row["program"])} : Blob)')
parts.append('for((address,lower,hrp,version,program) in [\n'+',\n'.join(valid)+'''].values()) {
  assert(Segwit.decode(address)==#ok({hrp;version;program}));
  assert(Segwit.encode(hrp,version,program)==#ok(lower));
};
''')
for row in segwit['invalid']:
    # Generic Segwit accepts custom networks by design; Address owns network checks.
    if row['reason']=='Invalid human-readable part': continue
    parts.append(f'switch(Segwit.decode({text(row["address"])})){{case(#err _){{}};case(#ok _)assert false}};\n')
parts.append('Prim.debugPrint("hash-codec independent audit ok");\n')
(HERE/'public-audit.mo').write_text(''.join(parts))
