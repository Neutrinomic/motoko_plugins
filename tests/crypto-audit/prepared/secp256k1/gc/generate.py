#!/usr/bin/env python3
"""Generate the independent vectors and Ash config for the prepared GC audit.

Only Python integer arithmetic/hashlib is used for expected outputs. Running
this script does not build the plugin/compiler or execute the canister.
"""
import argparse
import csv
import hashlib
import importlib.util
import json
from pathlib import Path
import sys

# Loading the retained oracle must not write outside this GC audit directory.
sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[4]
ORACLE = ROOT / "tests/crypto-audit/round3/secp256k1/generate.py"
spec = importlib.util.spec_from_file_location("retained_secp256k1_oracle", ORACLE)
oracle = importlib.util.module_from_spec(spec)
spec.loader.exec_module(oracle)
curve = oracle.curve
octets, blob = oracle.octets, oracle.blob


def ecdsa_verify(public, digest, signature):
    r = int.from_bytes(signature[:32], "big")
    s = int.from_bytes(signature[32:], "big")
    inverse = pow(s, -1, curve["n"])
    point = oracle.audit.add(
        curve,
        oracle.multiply(int.from_bytes(digest, "big") * inverse % curve["n"]),
        oracle.multiply_point(public, r * inverse % curve["n"]),
    )
    return point is not None and point[0] % curve["n"] == r


def schnorr_verify(public, message, signature):
    px, py = public
    even_public = (px, py if py % 2 == 0 else curve["p"] - py)
    r = int.from_bytes(signature[:32], "big")
    s = int.from_bytes(signature[32:], "big")
    e = int.from_bytes(oracle.tag("BIP0340/challenge", octets(r) + octets(px) + message), "big") % curve["n"]
    point = oracle.audit.add(curve, oracle.multiply(s), oracle.multiply_point(even_public, (-e) % curve["n"]))
    return point is not None and point[0] == r and point[1] % 2 == 0


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--plugin", type=Path, default=ROOT / "dist/secp256k1")
    args = parser.parse_args()
    official_path = ROOT / "plugins/secp256k1/tests/vectors/bip340.csv"
    official_count = 0
    with official_path.open() as source:
        for row in csv.DictReader(source):
            if row["secret key"]:
                actual = oracle.schnorr(int(row["secret key"], 16), bytes.fromhex(row["message"]), bytes.fromhex(row["aux_rand"]))
                assert actual.hex() == row["signature"].lower()
                official_count += 1

    vectors = []
    for index, secret in enumerate((1, 3, 6)):
        public = oracle.multiply(secret)
        digest = hashlib.sha256(f"prepared-gc/digest/{index}".encode()).digest()
        message = (hashlib.sha256(f"prepared-gc/message/{index}".encode()).digest() * 3)[:(0, 32, 67)[index]]
        auxiliary = bytes(32) if index == 1 else hashlib.sha256(f"prepared-gc/auxiliary/{index}".encode()).digest()
        ecdsa = oracle.audit.sign(curve, secret, digest, True)
        schnorr = oracle.schnorr(secret, message, auxiliary)
        high_s = ecdsa[:32] + octets(curve["n"] - int.from_bytes(ecdsa[32:], "big"))
        bad_schnorr = schnorr[:32] + octets((int.from_bytes(schnorr[32:], "big") + 1) % curve["n"])
        assert ecdsa_verify(public, digest, ecdsa)
        assert ecdsa_verify(public, digest, high_s)
        assert schnorr_verify(public, message, schnorr)
        assert not schnorr_verify(public, message, bad_schnorr)
        vectors.append({"secret": octets(secret), "key": oracle.encoded(public), "xOnly": octets(public[0]),
                        "digest": digest, "message": message, "auxiliary": auxiliary,
                        "ecdsa": ecdsa, "ecdsaHighS": high_s, "schnorr": schnorr, "badSchnorr": bad_schnorr})
    assert vectors[2]["key"][0] == 3  # Includes odd-Y secret normalization.
    for index, vector in enumerate(vectors):
        other = vectors[(index + 1) % len(vectors)]
        public = oracle.multiply(int.from_bytes(vector["secret"], "big"))
        assert not ecdsa_verify(public, vector["digest"], other["ecdsa"])
        assert not schnorr_verify(public, vector["message"], other["schnorr"])
        vector["otherEcdsa"] = other["ecdsa"]
        vector["otherSchnorr"] = other["schnorr"]

    fields = list(vectors[0])
    source = "// Generated by generate.py; expected signatures use retained Python affine arithmetic.\nmodule {\n"
    source += "  public type Vector = {\n" + "".join(f"    {field} : Blob;\n" for field in fields) + "  };\n"
    source += "  public let cases : [Vector] = [\n"
    for index, vector in enumerate(vectors):
        source += f"    // Secret {int.from_bytes(vector['secret'], 'big')}; message length {len(vector['message'])}; SEC1 prefix {vector['key'][0]}.\n    {{\n"
        source += "".join(f"      {field} = {blob(vector[field])};\n" for field in fields)
        source += "    },\n"
    source += "  ];\n}\n"
    (HERE / "Vectors.mo").write_text(source)
    config = {"mo": {"fast": "../../../../../packages/fast/src"},
              "canisters": [{"name": "prepared-secp256k1-gc", "src": "PreparedSecp256k1GC.mo",
                             "mocArgs": ["--plugin", str(args.plugin.resolve()), "--sanity-checks"]}]}
    (HERE / "PreparedSecp256k1GC.ash.json").write_text(json.dumps(config, indent=2) + "\n")
    evidence = {"generation_only": True, "canister_executed": False, "keys": [1, 3, 6],
                "message_lengths": [0, 32, 67], "official_bip340_signing_vectors_checked": official_count,
                "oracle_method": "Retained independent Python-bigint affine secp256k1, RFC6979, BIP340; direct verification equations cross-check each generated signature and mismatched key case.",
                "source_sha256": {str(path.relative_to(ROOT)): hashlib.sha256(path.read_bytes()).hexdigest()
                                  for path in (ORACLE, ROOT / "tests/crypto-audit/curves/run_audit.py", official_path, Path(__file__), HERE / "Vectors.mo")}}
    (HERE / "vector-provenance.json").write_text(json.dumps(evidence, indent=2) + "\n")
    print(f"Generated 3 GC vectors; checked {official_count} published BIP340 signing vectors. No compiler/build/PocketIC test run.")


if __name__ == "__main__":
    main()
